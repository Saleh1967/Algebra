"""**ختمٌ قبل النظر**: الطبقةُ الأولى من السلّم — تقطيعُ الكلمة، مستخرَجًا فوريًّا
من QAC.

**لم يُعَدّ شيءٌ بهذه القاعدة بعد.**

**العِلّة**: طلب صاحبُ المستودع بناءَ اللغة من الوحدات الـ112 صعودًا بالهندسة
العكسيّة، طبقةً
طبقة (`deposits/ladder_reverse_engineering.md`). والطبقةُ الأولى: **توقيعُ الكلمة**
— سوابقُها
ووسومُها، وقسمُ جذعها، ولواحقُها ووسومُها — يتنبّأ به المتعلِّمُ من الرسم **قبل**
أن يرى جوابَ
QAC، ثم يرى الجوابَ فيتعلّم. **والمتعلِّم**: ذاكرةٌ للهياكل التي رآها، فإن لم يرَ
الهيكلَ
تراجع إلى ما استخرجه من السوابق واللواحق بصورها ومعدّلاتها.

**وتوقّعي بالتفكير**: يثبت الأربعة؛ وأضعفُها س٤ (التعميمُ على هيكلٍ لم يُرَ).
"""

from __future__ import annotations

from fractions import Fraction

from algebra.signified import Direction, Oracle, Prediction, seal

ORACLE = Oracle(
    name="الطبقةُ الأولى: تقطيعُ الكلمة فوريًّا بالهندسة العكسيّة من QAC",
    source=(
        "quran-simple-enhanced.txt — البصمة 37633090…؛ "
        "وquran-morphology.txt من mustafa0x/quran-morphology عند 8f38b39"
    ),
    extraction=(
        "الآياتُ المتطابقة وكلماتُها كما في ختم 7f050383، والكلماتُ بترتيب المصحف. "
        "وتوقيعُ كلمة QAC: لكلّ مقطعٍ بترتيبه وسمٌ: إن كان "
        "فيه PREF فوسمُه POS:أوّلُ خصائصه، "
        "وإن كان فيه SUFF فكذلك ويُزاد لـPRON آخرُ "
        "خصائصه، وإلّا فـPOS وحده. وصورةُ المقطع "
        "حروفُه بعد حذف ما بين U+064B وU+065F وU+0670 وما بين U+06D6 وU+06ED وU+0640، "
        "وإبدال U+0671 ألفًا. وخامُ اللفظ حروفُه بلا علامات الشكل (run_jazm_zero.raw)، "
        "وهيكلُه skeleton(units). "
        "والمتعلِّمُ: ذاكرةٌ من الهيكل إلى عدّ "
        "التوقيعات؛ وP مجموعُ صور السوابق متّصلةً، "
        "وS مجموعُ صور اللواحق متّصلةً، ووسومُهما؛ "
        "ومعدّلُ P: عددُ الكلمات التي سوابقُها P "
        "على عدد الكلمات التي يبدأ خامُها بـP؛ ومعدّلُ S "
        "كذلك بالانتهاء؛ وذاكرةُ الجذع: من "
        "الخامِ بلا P وS إلى عدّ POS جذعه؛ وقسمُ الجذع الغالبُ لكلّ وسومِ سوابق. "
        "والتنبّؤ: إن كان الهيكلُ في الذاكرة فأكثرُ توقيعاته عدًّا (والتعادلُ لأوّلها "
        "وقوعًا)؛ وإلّا فأطولُ P معدّلُه نصفٌ فأكثر ويبدأ "
        "به الخام، ثم أطولُ S معدّلُه نصفٌ "
        "فأكثر وينتهي به الخام ويبقى بينهما حرفان فأكثر، "
        "وقسمُ الجذع من ذاكرة الجذع، وإلّا "
        "فالغالبُ لوسوم P، وإلّا فN؛ والتوقيعُ وسومُ P ثم القسم ثم وسومُ S. "
        "والفوريُّ يتنبّأ قبل أن يتعلّم الكلمة؛ وغيرُ الفوريّ تعلّم الكلمات كلَّها قبل "
        "التنبّؤ. س١: حصّةُ صواب الفوريّ (التوقيعُ "
        "كلُّه). س٢: صوابُ الفوريّ على صواب غير "
        "الفوريّ. س٣: حصّةُ صواب الفوريّ في الربع "
        "الأخير من الكلمات ناقصًا الربع الأوّل "
        "(والربعُ بعدد الكلمات، والباقي في الأخير). س٤: "
        "حصّةُ صواب الفوريّ في كلماتٍ لم يكن هيكلُها في ذاكرته؛ والعدُّ على QAC لم يُرَ"
    ),
)

PREDICTIONS = (
    Prediction(
        identifier="س١",
        statistic="حصّةُ صواب التوقيع فوريًّا",
        threshold=Fraction(17, 20),
        direction=Direction.AT_LEAST,
        falsifies="أنّ تقطيعَ الكلمة يُستخرج فوريًّا من أجوبةٍ مضت",
    ),
    Prediction(
        identifier="س٢",
        statistic="النسبةُ التنافسيّة للتقطيع",
        threshold=Fraction(9, 10),
        direction=Direction.AT_LEAST,
        falsifies="أنّ التقطيعَ الفوريَّ تنافسيٌّ بنسبةٍ ثابتة",
    ),
    Prediction(
        identifier="س٣",
        statistic="صوابُ الربع الأخير ناقصًا الأوّل",
        threshold=Fraction(1, 20),
        direction=Direction.AT_LEAST,
        falsifies="أنّ المتعلِّمَ يتعلّم التقطيعَ كلّما مرّ",
    ),
    Prediction(
        identifier="س٤",
        statistic="صوابُ التوقيع في هياكل لم تُرَ",
        threshold=Fraction(3, 5),
        direction=Direction.AT_LEAST,
        falsifies="أنّ الهندسةَ العكسيّة استخرجت قاعدةً تتعدّى الحفظ",
    ),
)

DIGEST = "1b3a639a50f3b36381de50d6a2d45e74d95ad67b49f57199107244ae5ccddb58"
"""يُثبَّت بعد أوّل اشتقاق، ولا يُمَسّ بعدَه."""


def test_the_seal_is_recomputed_from_the_written_conditions() -> None:
    """البصمةُ تُشتَقّ من الشروط لا تُنقَل."""

    assert seal(ORACLE, PREDICTIONS) == DIGEST


def test_four_conditions() -> None:
    """الصواب، والتنافس، والتعلّم، والتعميم."""

    assert [one.identifier for one in PREDICTIONS] == ["س١", "س٢", "س٣", "س٤"]
    assert "والعدُّ على QAC لم يُرَ" in ORACLE.extraction
