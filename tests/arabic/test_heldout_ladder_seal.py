"""**ختمٌ قبل النظر**: السلّمُ محجوزًا — هل تصمد أرقامي أنا؟

**لم يُشغَّل شيءٌ بعد.** يُودَع قبل كتابة القارئ وقبل أيّ رقم.

**لماذا**: سلّمُ `9034199d…` قِيس **داخلَ العيّنة**: التوزيعُ الشرطيُّ
يُقدَّر من المواضع نفسِها التي تُقاس عليها الإنتروبيا. وذلك **يُنقِص h
انتحالًا** كلّما كثرت السياقاتُ وقلّ نصيبُ كلٍّ منها — وهو بعينه العطلُ الذي
سمّيتُه في هضبة المدى البعيد، **ولم أطبّقه على نفسي**. فالنزولُ من ١٫٩٥ إلى
٠٫٧٦ قد يكون حفظًا لا تنبّؤًا.

**والقياسُ الصحيحُ للسؤال نفسِه**: القارئُ يتنبّأ بنصٍّ **لم يره**. فالمقدارُ
المطلوب **إنتروبيا متقاطعةٌ محجوزة**: يُقدَّر التوزيعُ من نصفٍ ويُقاس على
النصف الآخر، ثمّ يُعكَس ويُؤخَذ المتوسّط.

**القراراتُ تُختَم معها**:

- **القسمة**: الأسطرُ الزوجيّةُ سندًا والفرديّةُ قياسًا، ثمّ بالعكس.
- **التنعيم**: لابلاس (إضافةُ واحد) على أبجديّة الحالات المرصودةِ في السند
  — قرارٌ معلنٌ قبل النظر، لا مضبوطٌ بعده.
- **الارتداد**: سياقٌ لم يُرَ في السند يرتدّ إلى **الرتبة صفر** من السند،
  **ويُعلَن نصيبُ المرتدّ**.
- **الخطأُ المعياريّ**: تمهيدٌ بإعادة المعاينة على **الأسطر** (٤٠ سحبة)،
  ويُنشَر مع كلّ رقم — فرقمٌ بلا خطئه إدّعاءُ دقّةٍ لا دقّة.
- **السندُ المشترك**: يُعاد السلّمُ أيضًا على المواضع التي **سياقُها من
  الرتبة الثالثة مقروء** وحدَها، ليُقارَن مثلٌ بمثل.
"""

from __future__ import annotations

from fractions import Fraction

from algebra.signified import Direction, Oracle, Prediction, seal

ORACLE = Oracle(
    name="السلّمُ محجوزًا — تدقيقُ أرقامي على أفضل الممارسة",
    source="quran-simple-enhanced.txt — البصمة 37633090…",
    extraction=(
        "إنتروبيا متقاطعةٌ محجوزة: الأسطرُ الزوجيّةُ سندًا والفرديّةُ قياسًا "
        "ثمّ بالعكس والمتوسّط؛ تنعيمُ لابلاس على أبجديّة حالات السند؛ "
        "الارتدادُ إلى الرتبة صفر لسياقٍ لم يُرَ مع إعلان نصيبه؛ الخطأُ "
        "المعياريُّ بإعادة معاينة الأسطر أربعين سحبة؛ وإعادةُ السلّم على "
        "سندٍ مشتركٍ هو المواضعُ المقروءةُ سياقًا عند الرتبة الثالثة"
    ),
)

PREDICTIONS = (
    Prediction(
        identifier="م١",
        statistic="|المحجوزة عند الرتبة صفر − المُبلَّغة ١٫٩٥٢٥| (بت)",
        threshold=Fraction(1, 100),
        direction=Direction.AT_MOST,
        falsifies=(
            "الآلةَ لا المادّة: الرتبةُ صفرٌ لا سياقَ فيها فلا انتحال، "
            "فاختلافُها يعني عطلًا في القسمة أو التنعيم يوجب ردَّ السلّم كلِّه"
        ),
    ),
    Prediction(
        identifier="م٢",
        statistic="أدنى (المحجوزة − المُبلَّغة) على الرتب والسلّمين (بت)",
        threshold=Fraction(0),
        direction=Direction.AT_LEAST,
        falsifies=(
            "اتّجاهَ الانتحال المعروف: التقديرُ داخلَ العيّنة لا يَزيد على "
            "المحجوز؛ فنزولُ المحجوزة تحتها عطلُ آلةٍ لا كسبُ مادّة"
        ),
    ),
    Prediction(
        identifier="م٣",
        statistic="أدنى h محجوزةٍ على السلّمين عند رتبةٍ لا تتجاوز الثانية (بت)",
        threshold=Fraction(1),
        direction=Direction.AT_MOST,
        falsifies=(
            "**نتيجتي أنا** في `ca8fd2c`: إن بلغت المحجوزةُ بتًّا فأكثر، فسقوطُ "
            "س٣ كان انتحالًا لا بنية، ويُسحَب قولي «أكثرُ الشكل مُستنتَجٌ لا "
            "مُخبِر» ويُعاد الحكمُ على س٣ إلى الصمود"
        ),
    ),
    Prediction(
        identifier="م٤",
        statistic="أقصى خطأٍ معياريٍّ عند الرتبة الثانية في السلّمين (بت)",
        threshold=Fraction(1, 20),
        direction=Direction.AT_MOST,
        falsifies=(
            "نشرَ أربعِ خاناتٍ عشريّة: إن جاوز الخطأُ نصفَ العُشر فالمنشورُ "
            "خانتان لا أربع، وتُعاد كتابةُ الأرقام كلِّها بخطئها"
        ),
    ),
    Prediction(
        identifier="م٥",
        statistic="أدنى فرقٍ بين رتبتين متتاليتين على السند المشترك (بت)",
        threshold=Fraction(0),
        direction=Direction.AT_LEAST,
        falsifies=(
            "تناقصَ السلّم نفسَه: على سندٍ واحدٍ يوجب الشرطُ التناقصَ مبرهنةً، "
            "فصعودُه ههنا عطلُ حسابٍ لا خبرٌ عن اللغة"
        ),
    ),
)

DIGEST = "455167a5c3f10a6f7fca17fd5e12c889ecb20cca2f2388415102cce0faff6c20"
"""يُثبَّت بعد أوّل اشتقاق، ولا يُمَسّ بعدَه."""


def test_the_seal_is_recomputed_from_the_written_conditions() -> None:
    """البصمةُ تُشتَقّ من الشروط لا تُنقَل."""

    assert seal(ORACLE, PREDICTIONS) == DIGEST


def test_the_risky_condition_is_aimed_at_my_own_published_result() -> None:
    """م٣ يُعرّض نتيجتي أنا للنقض، لا نتيجةَ غيري."""

    risky = next(one for one in PREDICTIONS if one.identifier == "م٣")
    assert risky.threshold == Fraction(1)
    assert risky.direction is Direction.AT_MOST
    assert "ca8fd2c" in risky.falsifies
    assert len(PREDICTIONS) == 5
    assert len({one.identifier for one in PREDICTIONS}) == 5


def test_three_conditions_guard_the_machine_and_two_the_publication() -> None:
    """م١ وم٢ وم٥ عن الآلة، وم٣ عن النتيجة، وم٤ عن عددِ الخانات المنشورة."""

    machine = {"م١", "م٢", "م٥"}
    published = {"م٣", "م٤"}
    assert machine | published == {one.identifier for one in PREDICTIONS}
    assert not machine & published
