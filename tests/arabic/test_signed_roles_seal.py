"""**ختمٌ قبل النظر**: الـ١١٢ مصنَّفةً كلُّها بجدولٍ وقّعه صاحبُ المستودع.

**لم يُشغَّل شيءٌ بعد.**

**العِلّة**: ختمُ `a581ddb9…` ترك ٨٢٤ خانةً `UNCLASSIFIED` لأنّ جداولها لم تُودَع:
الجُمَّل، والصفة، والاشتقاقيّ، والصرفيّ، والنحويّ، والإعرابيّ، وبعضَ الوظيفيّ والدالّ
والمدلول معًا. فقال صاحبُ المستودع «يجب يصنّف كلّ شيء»، واختار أن تصوغ الآلةُ
مسوّدةً من محفوظها ويوقّعها هو؛ ثمّ كتب «انا اوقع كمالك للمستودع». فالجدولُ
`deposits/unit_roles_draft.tsv` مصدرٌ **موقَّعٌ باسمه**، لا دعوى للآلة.

**وما يُنقَل من الكتاب يُنقَل حرفيًّا**: خاناتُ النحويّ التي يذكرها «باب الحرف» في
«الشخصية الإسلامية» ج٣ (البصمة `978eb9cc…`) تحمل نصَّه، وتُطابَق بايتاتُه على
الملفّ حيث وُجد. وهذه مطابقةٌ لا شرط، لأنّ الاقتباسَ يُكتَب من الملفّ نفسه.

**وما رُئي قبل الختم**: أعدادُ وقوع كلّ وحدةٍ من الـ١١٢ (ملفُّ الوحدة في الختم
السابق)، والوحداتُ الأولى من الألفاظ (ج٤ هناك). **ولم يُعَدّ موضعُ أيّ وحدةٍ آخرَ
اللفظ**. والجدولُ الموقَّع كُتب من المحفوظ قبل أيّ عدٍّ لموضع.

**والشرطان الماديّان** يختبران أنّ الدورَ الخاصَّ الذي أسنده الجدولُ الموقَّع
للوحدة الساكنة هو غالبُ وقوعها لا نادرُه:

- **ك٣ — ميمُ الجمع لاحقة**: الجدولُ يجعل «مْ» ميمَ الجمع في آخر الضمائر (هُمْ،
  كُمْ، تُمْ). فنصيبُ وقوعات «مْ» التي هي آخرُ وحدةٍ في لفظها لا يقلّ عن النصف.
- **ك٤ — تاءُ التأنيث الساكنة لاحقة**: الجدولُ يجعل «تْ» تاءَ التأنيث لاحقةَ
  الماضي (فعلَتْ). فنصيبُ وقوعات «تْ» آخرًا لا يقلّ عن النصف.

وقد توقّعتُ بالتفكير لا بالعدّ أنّ ك٣ يتحقّق بسعة (عليهم، لكم، أنتم)، وأنّ ك٤
أقربُ إلى الحدّ لأنّ التاءَ الساكنة تقع وسطًا في «فَتْح» و«أَتْبَع» ونحوهما.
"""

from __future__ import annotations

from fractions import Fraction

from algebra.signified import Direction, Oracle, Prediction, seal

ORACLE = Oracle(
    name="الـ١١٢ مصنَّفةً كلُّها — جدولٌ وقّعه صاحبُ المستودع",
    source=(
        "quran-simple-enhanced.txt — البصمة 37633090…؛ وdeposits/unit_roles_draft.tsv "
        "موقَّعًا؛ و«الشخصية الإسلامية» ج٣ — البصمة 978eb9cc…"
    ),
    extraction=(
        "يُبنى السجلُّ كما في ختم a581ddb9 ثمّ تُملأ كلُّ خانةٍ UNCLASSIFIED من "
        "الجدول الموقَّع إن كان سطرُ توقيعه «موقَّع»، ومصدرُها «جدولٌ وقّعه صاحبُ "
        "المستودع»؛ وخاناتُ النحويّ التي يذكرها باب الحرف تحمل نصَّ الكتاب ومصدرُها "
        "«منقول من الكتاب»؛ والخانةُ الصامتة كما عُرّفت هناك؛ واللفظُ ما فصلته "
        "الفراغاتُ بعد طرح الوسم <sel>؛ ووحداتُه ما يُخرجه run_cv_peel منه؛ "
        "والوحدةُ آخرًا هي آخرُ ما يُخرجه التقشير من اللفظ؛ والنصيبُ عددُ وقوعات "
        "الوحدة آخرًا على عدد وقوعاتها كلّها في التيّار؛ وأعدادُ وقوع الوحدات "
        "والوحداتُ الأولى رُئيت قبل الختم، ومواضعُ الآخر لم تُرَ"
    ),
)

PREDICTIONS = (
    Prediction(
        identifier="ك١",
        statistic="خاناتٌ صامتةٌ في السجلّ",
        threshold=Fraction(0),
        direction=Direction.AT_MOST,
        falsifies=("الآلةَ: خانةٌ صامتةٌ بعد الملء دورٌ ضاع بين الجدول والسجلّ"),
    ),
    Prediction(
        identifier="ك٢",
        statistic="خاناتٌ UNCLASSIFIED في السجلّ",
        threshold=Fraction(0),
        direction=Direction.AT_MOST,
        falsifies=(
            "دعوى التصنيف التامّ: خانةٌ بقيت غيرَ مصنَّفةٍ بعد التوقيع فالجدولُ "
            "الموقَّع لم يغطِّ ما قيل إنّه غطّاه"
        ),
    ),
    Prediction(
        identifier="ك٣",
        statistic="نصيبُ وقوعات «مْ» التي هي آخرُ وحدةٍ في لفظها",
        threshold=Fraction(1, 2),
        direction=Direction.AT_LEAST,
        falsifies=(
            "دورَ ميم الجمع في الجدول الموقَّع غالبًا: إن كان أكثرُ «مْ» وسطًا "
            "فميمُ الجمع دورٌ من أدوارها لا غالبُها"
        ),
    ),
    Prediction(
        identifier="ك٤",
        statistic="نصيبُ وقوعات «تْ» التي هي آخرُ وحدةٍ في لفظها",
        threshold=Fraction(1, 2),
        direction=Direction.AT_LEAST,
        falsifies=(
            "دورَ تاء التأنيث الساكنة في الجدول الموقَّع غالبًا: إن كان أكثرُ "
            "«تْ» وسطًا فهي تاءُ بنيةٍ أكثرَ منها لاحقة"
        ),
    ),
)

DIGEST = "f23fc0cd6d24af4b022e236cfeaaca5e74aa419bc71a576890bf42c5f81da518"
"""يُثبَّت بعد أوّل اشتقاق، ولا يُمَسّ بعدَه."""


def test_the_seal_is_recomputed_from_the_written_conditions() -> None:
    """البصمةُ تُشتَقّ من الشروط لا تُنقَل."""

    assert seal(ORACLE, PREDICTIONS) == DIGEST


def test_two_conditions_guard_the_registry_and_two_the_claim() -> None:
    """ك١ وك٢ عن السجلّ، وك٣ وك٤ عن المادّة."""

    machine = {"ك١", "ك٢"}
    matter = {"ك٣", "ك٤"}
    assert machine | matter == {one.identifier for one in PREDICTIONS}
    assert not machine & matter
    for one in PREDICTIONS:
        assert one.falsifies.strip()


def test_what_was_seen_before_the_seal_is_declared() -> None:
    """أعدادُ الوقوع رُئيت ومواضعُ الآخر لم تُرَ — مُعلَنٌ في الاستخراج."""

    assert "ومواضعُ الآخر لم تُرَ" in ORACLE.extraction
