"""**ختمٌ قبل النظر**: من البتّات إلى الطبقات — صعودٌ حرٌّ وهبوطٌ مرصودٌ بالرسم،
والعكس.

**لم يُعَدّ شيءٌ بهذا الشرط بعد.**

**العِلّة**: قال صاحبُ المستودع: «المطلوب أن يبحث من البتّات عن المسار البنائيّ
الهرميّ صعودًا
حرًّا وهبوطًا مرصودًا والعكس، ونراقب: هل يتقبّل بالبتّ التالي وحده». واختار بتّاتِ
الترميز
الثنائيّ، والرصدَ بطبقات الرسم وحده.

**التصميم**:
- **التيّار**: كلُّ وحدةٍ من الـ١١٢ سبعُ بتّات: خمسٌ للحرف (رتبتُه بين الحروف الثمانية
والعشرين بترتيب يونيكود) واثنتان للحال (فتحة ٠٠، ضمّة ٠١، كسرة ١٠، سكون ١١)؛
  والمصحفُ
  كلُّه تيّارٌ واحدٌ **بلا فراغٍ ولا وقفٍ ولا حدّ آية**.
- **ترتيبان للبتّات** (هندسةٌ عكسيّة: أيُّ ترتيبٍ تتقبّله اللغة أبكر؟): الحرفُ
  أوّلًا ثم الحال،
  والحالُ أوّلًا ثم الحرف.
- **اتّجاهان**: من أوّل التيّار إلى آخره (صعود)، ومن آخره إلى أوّله (العكس).
- **الصعودُ الحرّ**: المتعلِّمُ لا يرى إلّا البتّات. عند كلّ موضعٍ بين بتّتين يرى ٢١
  بتًّا قبله
  وk بتًّا بعده، ويحكم: أهنا حدٌّ؟ يتعلّم من الآيات الزوجيّة، ويُمتحن على الفرديّة.
- **الهبوطُ المرصود**: الحدودُ الصحيحة من الرسم وحده، في خمس طبقات: الوحدة، والمقطع،
  والكلمة،
  ومقطعُ الوقف، والآية.
- **ويُراقَب**: هل يُقبَل الحدُّ بالبتّ التالي وحده (k = ١)، أم يحتاج أكثر؟

**وتوقّعي بالتفكير**: حدُّ الوحدة يُقبَل بالبتّ التالي وحده؛ وحدُّ المقطع يُقبَل
ببتّتين إذا
سبقت الحالُ الحرف، ولا يُقبَل بهما إذا سبق الحرفُ الحال؛ وحدُّ الكلمة لا يُقبَل
بالبتّ التالي
وحده، ويُعين عليه استشرافُ وحدةٍ كاملة.
"""

