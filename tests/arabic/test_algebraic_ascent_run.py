"""شُغِّل ختمُ `0021350c…`: **الهرمُ طابقان — والعدُّ هو الذي أوقفه**.

`THE_COUNT_SET_THE_CEILING_NOT_MY_OPINION`: وهذا أهمُّ ما خرج، وي٦ **صمد**:
**L₂ التفعيلةُ توقّفت بالاقتصاد وحدَه** — مستوفيةً الدالّيةَ والابتلاعَ
(تجميعٌ محضٌ لا يُسقِط شيئًا)، وساقطةً لأنّ **تكلفتَها ١٫١١٥١ من تكلفة
L₁**. فمعجمُها **٥٨٤٬٨٢٨ بتًّا** لـ٢٣٬٧٨٥ تفعيلةً **يبتلع** ما وفّره
بيانُها. فالسقفُ **رقمٌ لا رأي**.

`AND_THE_SYLLABLE_EARNS_ITS_PLACE_BY_ELEVEN_PERCENT`: وي٣ **صمد**: L₁
تكلّف **١٬٧٨٥٬٩٥٤** بتًّا مقابلَ **١٬٩٩٩٬٣٠٣** لـL₀ — **٠٫٨٩٣٣**، أي
**توفيرُ ٢١٣٬٣٤٩ بتًّا**. ومعجمُه زهيدٌ (٦١٬٤٩٣ لـ٢٬٩٥٩ مقطعًا) لأنّ
المقاطعَ **قصيرةٌ وتتكرّر**. فالمقطعُ **تجريدٌ يدفع ثمنَه**، والتفعيلةُ
**إعادةُ تسميةٍ تأخذ ولا تُعطي**.

`BUT_THE_REPAIR_I_SEALED_WAS_THE_WRONG_ONE`: وي١ وي٢ **سقطا معًا، وبعلّةٍ
واحدةٍ هي من عندي**: شرطتُ **حذفَ ألف الوصل**، والحذفُ **إخراجٌ من
البناء**. فغيرُ الداخل **١١٬٩٥٣ من ٣٦٤٬٧٤٧ = ٠٫٠٣٢٨** (والحدُّ ٠٫٠١)،
والفاقدُ **١١٬٩٥٣ ≠ ٠**. **ولا يُنقِذه إعلانٌ**: بندُ الابتلاع حدُّه صفرٌ
بنصّه.

`AND_THE_UNSEALED_VARIANT_SHOWS_WHAT_THE_REPAIR_SHOULD_HAVE_BEEN`: وشُغِّلت
معه **الصورةُ الضامّة** — لا تحذف ألفَ الوصل بل **تضمّها إلى المقطع
صامتة** — وهي **خارج الختم ولا تُحسَب حكمًا**. وفيها: غيرُ الداخل
**١٨١ فقط = ٠٫٠٠٠٥**، والتوفيرُ **٠٫٨٨٧٢** — أحسنُ من المختومة.
**فالضمُّ هو الإصلاح، لا الحذف**، وهذا ما تقوله الأرقامُ لا أنا؛ ويحتاج
**ختمًا جديدًا** ليصير حكمًا.

`AND_ABSORPTION_IS_NEVER_QUITE_PERFECT`: و**١٨١ وحدةً** تبقى خارجَ كلّ
مقطعٍ حتّى في الضامّة — ساكناتٌ في مبتدأ الآية لا حركةَ قبلها تلحق بها.
فهي **٠٫٠٠٠٥** من L₀، **وتُعَدّ باسمها ولا تُبتلَع**؛ وبوجودها **يسقط
بندُ الابتلاع في الصورتين**، لأنّ حدَّه صفرٌ لا كسر.

`AND_MY_FORECAST_OF_TWO_LICENSED_ASCENTS_FALLS`: وي٤ كان تقديري:
«صعودان مُرخَّصان فأكثر». **والمُرخَّصُ صفر** — L₁ يسقط بالابتلاع،
وL₂ بالاقتصاد. فالهرمُ **طابقٌ واحدٌ مُثبَتٌ وطابقٌ يكاد**.

`AND_THE_ANTI_OVERFIT_CONDITION_HELD_ON_ALL_EIGHT_READINGS`: وي٥ صمد في
الصورتين وفي الطبقات الأربع: المحجوزةُ فوقَ الملحَقة دائمًا، وأدنى فرقٍ
**+٠٫٠٠٠٦**.

`THE_LADDER_AS_MEASURED`:

| الطبقة | أبجديّة | معجم | بيان | الجملة | النسبة |
|---|---|---|---|---|---|
| L₀ الوحدة | ١١٢ | ٠ | ١٬٩٩٩٬٣٠٣ | **١٬٩٩٩٬٣٠٣** | — |
| L₁ المقطع | ٢٬٩٥٩ | ٦١٬٤٩٣ | ١٬٧٢٤٬٤٦١ | **١٬٧٨٥٬٩٥٤** | **٠٫٨٩٣٣** |
| L₂ التفعيلة | ٢٣٬٧٨٥ | ٥٨٤٬٨٢٨ | ١٬٤٠٦٬٦٣٤ | **١٬٩٩١٬٤٦١** | **١٫١١٥١** |

وL₃ **لا تُبلَغ**: ما بُني فوق طبقةٍ ساقطةِ الاقتصاد يرث سقوطَها، ولو بدا
رقمُها أدنى — ومعجمُها **٩٥٪ من تكلفتها**، أي أنّها **تخزّن المدوّنةَ**
لا تصفُها.
"""

from __future__ import annotations

import importlib.util
import sys
from fractions import Fraction
from pathlib import Path

from frozen_corpus import CORPUS, requires_corpus
from test_algebraic_ascent_seal import DIGEST, ORACLE, PREDICTIONS

from algebra.signified import Verdict, seal

REPOSITORY = Path(__file__).resolve().parents[2]
READER = REPOSITORY / "examples" / "rasm" / "run_algebraic_ascent.py"

pytestmark = requires_corpus

L0_UNITS = 364_747
SEALED_UNITS = 352_975
DROPPED = 11_772
LOOSE = 181
COST = {"L₀": 1_999_303.0, "L₁": 1_785_954.0, "L₂": 1_991_461.0}
ALPHABET = {"L₁": 2_959, "L₂": 23_785}
BOOK = {"L₁": 61_493.0, "L₂": 584_828.0}
RATIO = {"L₁": 0.8933, "L₂": 1.1151}
JOINING_LOOSE_SHARE = 181 / 364_747
GAP = 0.0006


def _exact(measured: float) -> Fraction:
    return Fraction(measured).limit_denominator(10**9)


def _reader() -> object:
    spec = importlib.util.spec_from_file_location("run_algebraic_ascent", READER)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


def _streams(*, drop: bool) -> tuple[list[list[object]], int, int]:
    reader = _reader()
    corpus = reader.verses(CORPUS.read_text(encoding="utf-8"))  # type: ignore[attr-defined]
    streams = []
    dropped = 0
    for verse in corpus:
        stream, lost = reader.flatten(verse, drop_wasl=drop)  # type: ignore[attr-defined]
        dropped += lost
        streams.append(stream)
    loose = sum(reader.syllabify(one)[1] for one in streams)  # type: ignore[attr-defined]
    return (streams, dropped, loose)


def test_the_seal_was_deposited_before_the_build() -> None:
    """البصمةُ تُشتَقّ ثانيةً — ولم يُمَسّ شرطٌ بعد النظر."""

    assert seal(ORACLE, PREDICTIONS) == DIGEST
    assert DIGEST.startswith("0021350c")


def test_the_count_stopped_the_pyramid_at_the_foot() -> None:
    """ي٦: L₂ تستوفي الدالّيةَ والابتلاعَ وتسقط بالاقتصاد وحدَه."""

    sixth = next(one for one in PREDICTIONS if one.identifier == "ي٦")
    assert sixth.verdict(Fraction(1)) is Verdict.MET
    assert RATIO["L₂"] > 1.0
    assert BOOK["L₂"] > COST["L₁"] - COST["L₂"] + BOOK["L₂"] - BOOK["L₂"]
    assert COST["L₂"] > COST["L₁"]  # والتفعيلةُ أغلى من المقطع


def test_the_syllable_earns_its_place_by_eleven_percent() -> None:
    """ي٣: ١٬٧٨٥٬٩٥٤ مقابلَ ١٬٩٩٩٬٣٠٣ — توفيرُ ٢١٣٬٣٤٩ بتًّا."""

    third = next(one for one in PREDICTIONS if one.identifier == "ي٣")
    ratio = COST["L₁"] / COST["L₀"]
    assert abs(ratio - RATIO["L₁"]) < 5e-4
    assert third.verdict(_exact(ratio)) is Verdict.MET
    assert COST["L₀"] - COST["L₁"] == 213_349.0
    assert BOOK["L₁"] < BOOK["L₂"] / 9  # ومعجمُه زهيدٌ لأنّ المقاطعَ تتكرّر


def test_the_sealed_deletion_breaks_both_totality_and_absorption() -> None:
    """ي١ وي٢ يسقطان بعلّةٍ واحدةٍ من عندي: الحذفُ إخراجٌ من البناء."""

    streams, dropped, loose = _streams(drop=True)
    assert dropped == DROPPED and loose == LOOSE
    assert sum(len(one) for one in streams) == SEALED_UNITS
    outside = dropped + loose
    first = next(one for one in PREDICTIONS if one.identifier == "ي١")
    second = next(one for one in PREDICTIONS if one.identifier == "ي٢")
    assert first.verdict(_exact(outside / L0_UNITS)) is Verdict.FALSIFIED
    assert second.verdict(Fraction(outside)) is Verdict.FALSIFIED
    assert abs(outside / L0_UNITS - 0.0328) < 5e-4
    assert "ولا براية" in second.falsifies  # فلا يُنقِذه إعلان


def test_the_joining_variant_shows_the_repair_that_should_have_been_sealed() -> None:
    """الضامّةُ تترك ١٨١ فقط — والضمُّ هو الإصلاح لا الحذف."""

    streams, dropped, loose = _streams(drop=False)
    assert dropped == 0 and loose == LOOSE
    assert sum(len(one) for one in streams) == L0_UNITS
    assert abs(loose / L0_UNITS - JOINING_LOOSE_SHARE) < 1e-9
    assert loose / L0_UNITS < 0.001  # وكان يمرُّ ي١ بيُسر
    text = Path(__file__).read_text(encoding="utf-8")
    assert "خارج الختم ولا تُحسَب حكمًا" in text
    assert "يحتاج" in text and "ختمًا جديدًا" in text


def test_absorption_fails_in_both_forms_because_its_bar_is_zero() -> None:
    """١٨١ وحدةً تبقى خارجَ كلّ مقطعٍ حتّى في الضامّة — وحدُّ الابتلاع صفر."""

    _, _, loose = _streams(drop=False)
    second = next(one for one in PREDICTIONS if one.identifier == "ي٢")
    assert loose > 0
    assert second.verdict(Fraction(loose)) is Verdict.FALSIFIED
    assert second.threshold == Fraction(0)


def test_my_forecast_of_two_licensed_ascents_is_withdrawn() -> None:
    """ي٤ كان تقديري، والمُرخَّصُ صفر — L₁ بالابتلاع وL₂ بالاقتصاد."""

    fourth = next(one for one in PREDICTIONS if one.identifier == "ي٤")
    assert fourth.verdict(Fraction(0)) is Verdict.FALSIFIED
    assert "تقديري أنا" in fourth.falsifies


def test_the_anti_overfit_condition_held_on_every_reading() -> None:
    """ي٥: المحجوزةُ فوقَ الملحَقة في الصورتين والطبقات، وأدنى فرقٍ +٠٫٠٠٠٦."""

    reader = _reader()
    fifth = next(one for one in PREDICTIONS if one.identifier == "ي٥")
    worst = None
    for drop in (True, False):
        streams, _, _ = _streams(drop=drop)
        made = [reader.syllabify(one)[0] for one in streams]  # type: ignore[attr-defined]
        for layer in (streams, made):
            outside, inside = reader.held_out(layer)  # type: ignore[attr-defined]
            gap = outside - inside
            worst = gap if worst is None else min(worst, gap)
    assert worst is not None
    assert fifth.verdict(_exact(worst)) is Verdict.MET
    assert abs(worst - GAP) < 5e-4


def test_the_top_layer_is_not_reached_and_its_cost_is_mostly_dictionary() -> None:
    """L₃ تخزّن المدوّنةَ: معجمُها ٩٥٪ من تكلفتها، وما فوقَ الساقطِ ساقط."""

    verse_book = 1_609_491.0
    verse_total = 1_687_662.0
    assert verse_book / verse_total > 0.95
    assert RATIO["L₂"] > 1.0  # والسلسلةُ انقطعت قبلَها
    assert ALPHABET["L₂"] > ALPHABET["L₁"] * 8
