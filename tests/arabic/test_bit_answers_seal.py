def test_the_seal_is_recomputed_from_the_written_conditions() -> None:
    """البصمةُ تُشتَقّ من الشروط لا تُنقَل."""

    assert seal(ORACLE, PREDICTIONS) == DIGEST


def test_the_vocabulary_is_closed_and_its_gap_is_declared_not_hidden() -> None:
    """المفرداتُ مغلقةٌ، والمؤجَّلُ مكتوبٌ في الختم لا مطويٌّ في الشفرة."""

    assert "**وواحدةٌ منها وحدَها بُنِي لها" in (__doc__ or "")
    assert "يُرى غيابُ مُجيبها" in (__doc__ or "")
    assert "`PROVE` و`GUESS`" in (__doc__ or "")
    assert len(PREDICTIONS) == 7


def test_the_finite_domain_is_what_licenses_the_complete_count() -> None:
    """التمامُ مشروطٌ بتناهي المجال — والحدُّ مكتوبٌ مع الدعوى."""

    text = " ".join((__doc__ or "").split())
    assert "استدلالٌ تامٌّ على كائنٍ متناهٍ" in text
    assert "لا يُقال منه" in text
    assert "٢٥٦ بايتة" in ORACLE.name
    assert WHOLE == 8 * 256


def test_what_was_seen_before_the_seal_is_written_in_it() -> None:
    """ما جُرِّب قبل الختم يُعلَن — ولا يُقال «لم يُشغَّل شيء» وقد شُغِّل."""

    assert "شُغِّلت الآلةُ على موضوعٍ واحدٍ هو البايتةُ" in (__doc__ or "")
    assert "ولا يُستخرَج من موضوعٍ واحدٍ توزيعٌ" in (__doc__ or "")
