"""**تسجيلٌ سابقٌ للنظر**: لامُ الناقص بالمناوبة المرصودة — و∅ فيها معدود.

**وهذا الختمُ بوّابةٌ لا شاهد**: كُتِب ودُفِع **قبل أن يُكتَب سطرٌ واحدٌ من
آلة القياس، وقبل أن يُعَدّ في المدوّنة عددٌ واحدٌ من أعداده**. وذلك مكتوبٌ
ههنا كي يُفحَص بتاريخ الدفع لا بقولي. وهو **الفرقُ بينه وبين `c46dfbe3…`**:
ذاك كُتِب بعد رؤية مخرَجه وأقرَّ بذلك فسُمّي شاهدًا، وهذا يسبق مخرَجَه.

**الأوراكلُ هو المدوّنةُ وحدَها** (`37633090…`): لا جدولَ جذورٍ يُستشار، ولا
وسمَ صرفيًّا يدخل من خارج بايتاتها. والفصلُ بين الفعل وغيرِه **بالمناوبة
المرصودة**، كما في الأجوف: إطارٌ يُرى بوجهَين في البايتات نفسِها.

**والمناوبةُ ههنا لامٌ ظاهرةٌ ⟷ لامٌ محذوفة**:
- **الوجهُ الظاهر**: صامتان أصليّان تتلوهما لامٌ معتلّةٌ مكتوبة — إمّا
  حرفَ مدٍّ في آخر اللفظ (`دَعَا` · `رَمَى` · `سَعَى` · `تَلَا`)، وإمّا واوًا
  أو ياءً ساكنةً يتلوها ضميرُ رفعٍ متّصل (`دَعَوْتُ` · `رَمَيْنَا`).
- **الوجهُ المحذوف**: الصامتان نفسُهما تتلوهما **تاءُ التأنيث الساكنة بلا
  لام** (`دَعَتْ` · `رَمَتْ` · `سَعَتْ`) — واللامُ مطروحةٌ من الرسم، فهي
  الشاهدُ ∅ بموضعه.

**والفصلُ عن السالم بعدّ الصوامت**: `كَتَبَتْ` ثلاثةُ صوامتَ قبل تاء
التأنيث، و`دَعَتْ` صامتان — فالثالثُ محذوفٌ لا مكتوب. وهو بعينه الفصلُ
الذي أقام إطارَ الأجوف، لا استثناءً جديدًا يُفصَّل ههنا.

**والألفُ المقصورةُ تُردُّ إلى الألف بقرارٍ مُعلَنٍ قبل العدّ**: «ى» رسمٌ
للألف في آخر اللفظ لا شاهدٌ خامسٌ — وإلّا انقسم الشاهدُ الواحدُ على صورتَي
رسمه فبدا أضعفَ ممّا هو. **ويُطبَع عددُها خامًا** كي لا يُخفى القرار.

**وفضاءُ الشاهد مُعلَنٌ قبل العدّ**: {ا، و، ي، ∅} — وما خرج عنه **متطفّلٌ
يُسمّى بعينه ويُحصى، ولا يُكنَس قبل العدّ**. وهذا درسُ الـ٢٠٧ نونًا: عدّادٌ
يمنع شرطُه ما يعدّه **متطابقةٌ منطقيّةٌ لا فحص**. فمُرشِّحُ الأُطُر ههنا
**لا يذكر حروفَ العلّة ألبتّة** — شرطُه المناوبةُ وحدَها.

**والرقمُ الحاسم**: عددُ الموادّ المناوِبة المرصودة. وفي قياس الإعلال
السابق أنّ جدولَ الناقص ثمنُه ٣٣٥ بتًّا، وأنّ المولِّدَ المُعلَن ٤٥ بتًّا
يستورد اختيارًا ثلاثيًّا لكلّ مادّةٍ **لم يُحسَب ثمنُه**؛ فنقطةُ التعادل
(٣٣٥ − ٤٥) ÷ log₂٣ = **١٨٣ مادّة**. فإن جاوزت الموادُّ ذلك فالجدولُ
المستورَدُ أغلى ممّا وفّره القانون.

**وحدُّ هذا الرقم مُعلَنٌ قبل أن يُقاس**: المقيسُ ههنا **الموادُّ المشهودةُ
بالمناوبة في هذه المدوّنة**، وهي **حدٌّ أدنى** لموادّ اللغة لا جردٌ لها.
فإن جاوز الحدُّ الأدنى ١٨٣ **انقفل السؤالُ بالإيجاب لا محالة**؛ وإن لم
يجاوزه **بقي السؤالُ مفتوحًا** ولا يُقرأ عدمُ المجاوزة جوابًا — والمدوّنةُ
ليست اللغة. وهذا مكتوبٌ **قبل العدّ** كي لا يُفسَّر الرقمُ بعد رؤيته.
"""

