"""**ختمٌ قبل النظر**: دورةُ الحال على الخاتمة — ثابتٌ ومتبدّل، بادٍ وغائب.

**لم يُشغَّل شيءٌ بعد.**

**السؤالُ المطروح**: قيل إنّ مفتاحَ الجملة والكلمة هو **ما يثبت حالُه وما
يتبدّل**، و**العلاماتُ الأصليّةُ والفرعيّة**، و**دورةُ الظاهر والمقدَّر**.
وهذه أسماءُ **أبوابٍ نحويّة**، ولا تُشتَقُّ من البايتات. **فما يُقاس ههنا
بتّاتٌ لا أبواب**، وهذه حدودُه مكتوبةً قبل النظر:

- **ثباتُ الحال** — هيكلٌ (حروفٌ بلا علاماتٍ مُدغَمة) لا تتبدّل عليه العلامةُ
  الأخيرة في وقوعاته كلِّها. **وهذا عدٌّ لا حُكمُ باب**: قد يثبت حالُ هيكلٍ
  لأنّ بابَه يقتضيه، وقد يثبت لأنّه لم يقع إلّا في موضعٍ واحد. **فالقيدُ
  مكتوبٌ**: لا يُعَدُّ إلّا ما وقع **خمسَ مرّاتٍ فأكثر**.

- **الحالُ البادي والغائب** — حرفُ خاتمةٍ لا تُرى عليه علامةٌ ألبتّة في
  المجمَّد كلِّه: **خانةُ الحال عنده خالية**، والخلوُّ **يُصنَّف ولا يُصفَّر**.
  **ولا يُقال إنّ ثَمَّ حالًا غيرَ مكتوب** — يُقال إنّه **غيرُ مكتوب**.

- **الثلاثةُ وما سواها** — نصيبُ الخواتم التي علامتُها من الثلاث
  (`َ` `ُ` `ِ`) مقابلَ ما سواها. **عدُّ علاماتٍ لا تصنيفُ أصالةٍ ونيابة.**

**وما لا يُشتَقُّ لا يُدَّعى**: **الأصليّةُ والفرعيّة** لا تُقرآن من
البايتات — تحتاجان جدولَ أبوابٍ مُودَعًا، **وليس في المستودع جدول**. فهذا
**خلوٌّ مُصنَّفٌ** لا نتيجةٌ صفرٌ، ولا يُسَدُّ بتخمين. وكذلك **المبنيُّ
والمعرب**: ما يُعرَض ههنا **قابليّةٌ للقراءة** لا قراءة، **وإيداعُ القراءة
فعلُ صاحب المستودع لا فعلي**.

**وماركوف**: حالُ الخاتمة سلسلةٌ داخلَ السطر — `p(حالٌ تالٍ | حالٌ سابق)` —
والمعلوماتُ المتبادلةُ `I = H(التالي) − H(التالي | السابق)` **بالهامش
الأيمن** لا الأيسر، وهو الخللُ الذي أُصلِح قبلُ.

**وinduction on**: مبرهنتان مُصانتان عند **كلّ حال**: الشرطُ لا يرفع
الإنتروبيا (`H(التالي | السابق) ≤ H(التالي)`)، و`log₂ التباديل ≤ N·H`.
**وinduction FOR**: الحلقةُ تشهد عليهما **سطرًا سطرًا** وتُقابِل العدّاداتِ
بالأسطر.

**والبايتاتُ تُشرَّح ولا تُكتَب**: الألفاظُ والهياكلُ شرائحُ من السطر،
**ولا حرفَ عربيٍّ يُكتَب بيدٍ في القياس**. ولا اسمَ بابٍ نحويٍّ يدخل السجلَّ
ولا الوثيقة: **علاماتٌ ومواضعُ وبتّات.**
"""

