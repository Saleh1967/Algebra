        identifier="ن٣",
        statistic="دقّةُ التوليد بالجوار مقسومةً على دقّة الضابط العشوائيّ",
        threshold=Fraction(5),
        direction=Direction.AT_LEAST,
        falsifies="أنّ بنيةَ الجوار بين الجذور والقوالب تولّد ما سيرد",
