"""**ختمٌ قبل النظر**: أيُّ البتّات يعيش بعد رفع مواضع الوقف؟

**لم يُشغَّل شيءٌ بعد.**

**لِمَ هذا التشغيل**: بلغ السلّمُ في `041cdcf4…` اثنتي عشرةَ بتّةً، وكانت
**أكبرُها بتّةَ موضعٍ** («أآخرُ السطر؟») بربحٍ محجوزٍ `٠٫٠٥٦٩`. فإن كان حدُّ
السطر موضعَ وقفٍ فإنّ خانةَ «بلا علامة» — وهي أكبرُ خانةٍ بنصيب `٠٫٣١٠٨` —
**قد تكون مسكونةً بالوقف لا بالبناء**. **وحينئذٍ يكون بعضُ كسب البتّات
الأخرى أثرًا للوقف لا للجوار.**

**فيُرفَع كلُّ موضعٍ آخرِ سطرٍ ويُعاد القياسُ على الباقي**، بالأسئلة
**نفسِها وبترتيبها نفسِه** كما أُودِعت — **لا يُعاد اختيارٌ جشعٌ**، لأنّ
إعادةَ الاختيار تُبدِّل السلّمَ فتصير المقابلةُ بين شيئين.

**وما لا يُدَّعى، ويُكتَب قبل النظر كي لا يُدَّعى بعده**: هذا التشغيلُ
**يفصل الوقفَ عن غيره ولا يُثبِت أنّ غيرَه إعراب**. فما بقي من كسبٍ بعد
رفع الوقف **إفادةٌ عن صنفِ علامةٍ مكتوبةٍ في مواضعَ غيرِ أواخرِ الأسطر**،
**وليس إفادةً عن حكم بابٍ نحويّ** — وذلك يحتاج جدولًا مُودَعًا **ليس في
المستودع**. **فلا يُقرَأ هذا السجلُّ برهانًا لغويًّا ألبتّة.**

**وما يُمنَع ههنا منعًا**: ما مُنِع في `041cdcf4…` بعينه — لا قائمةَ
مُودَعة، ولا اسمَ بابٍ ولا علامةٍ ولا يونيكود (المحرفُ شريحةٌ ونقطةُ
ترميز)، ولا شيءَ من بايتات الموضع المسؤولِ عنه.

**والمسندُ يُصرَّح به في كلّ طرحٍ** — كما أوجب العطل ٢٤: مقادير المجال (أ)
على مسندها، ومقادير (ب) على مسندها، **ولا يُطرَح مقدارٌ من مقدارٍ عبرَ
المجالين**. والفرقُ الذي يُعرَض فرقُ **كسبٍ مقيسٍ في كلّ مجالٍ على نفسه**.

**وماركوف**: المجال (ب) **تقييدُ مسندٍ** لا تكتيلُ سياق؛ فالأسئلةُ هي هي،
والسلسلةُ هي هي، **والمقيَّدُ هو المواضعُ المسؤولُ عنها**. **وinduction
on**: المبرهنتان مُصانتان في المجالين — التنقيحُ لا يرفع الإنتروبيا
الملحَقة، و`log₂ التباديل ≤ N·H` بعد ألفِ لفظ. **وinduction FOR**: الحلقةُ
تشهد عليهما **درجةً درجةً وفي المجالين**.

**والحدُّ الحسابيُّ الذي يُقفِل نفسَه**: أسطرُ المجمَّد `٦٬٢٣٦`، وفي كلّ
سطرٍ موضعٌ أخيرٌ واحد، **فالمرفوعُ `٦٬٢٣٦` والباقي `٧٢٬٠٠٩`** — وهو مسندُ
الأزواج المقيسُ في `4289fc6c…` بعينه. **فإن خالف العددُ فالآلةُ أخطأت.**
"""

