"""**ختمٌ قبل النظر**: أدوارُ حروف «سألتمونيها» — أيحسمها الموقعُ والحالُ وحدَهما؟

**لم يُشغَّل شيءٌ بعد**، ولم يُعَدّ حرفٌ من التسعة على المدوّنة قبل كتابة هذه
الشروط.

**العِلّة**: الوحدةُ من الـ١١٢ حرفٌ في حال، والحرفُ **لا يستقلّ بمعنى** — هو
الدالُّ قبل أن يكون دالًّا. لكنّ لحروف «سألتمونيها» **أدوارًا في بنية
اللفظ** لا يحملها غيرُها: قد يكون الحرفُ أصليًّا، أو زائدًا في الوزن، أو
لاصقةً تصريفيّة، أو كلمةً ملتصقة. وقلتُ إنّ **موقعَ الوحدة في اللفظ وحالَها
يرجّحان الدورَ ولا يحسمانه**، وإنّ الحسمَ يحتاج قائمةً مُودَعة — وهو بابُ
«الكلمة المفردة» الباقي `UNCLASSIFIED` في السلّم `426f7fc8…`. وهذا الختمُ
يجعل «يرجّحان ولا يحسمان» **أعدادًا تسقط**.

`THE_TEN_ARE_NINE_IN_THE_112`: وقبل النظر، بقراءة `run_cv_peel` لا بعدّ: الطيُّ
يجمع أسرةَ الألف (ا ء أ إ آ ؤ ئ ى) في «ا». فالهمزةُ والألفُ من «سألتمونيها»
**وحدةٌ واحدة** في فضاء الـ١١٢، والحروفُ **تسعةٌ لا عشرة**. ويطوي التاءَ
المربوطة في «ه»، فتدخل تاءُ التأنيث المربوطة في أدوار الهاء.

**والجدولُ مسوّدةٌ غيرُ موقَّعة** في `deposits/letter_roles_draft.tsv`: لكلّ حرفٍ
من التسعة اثنتا عشرة خانة (ثلاثة مواضع × أربع حالات)، وفي كلّ خانةٍ الأدوارُ
الممكنة وشواهدُها. **صاغته الآلةُ من معرفةٍ نحويّةٍ منقولة**، وبصمتُه في
الاستخراج، فتبديلُ خانةٍ بعد النظر يُغيّر البصمة. **ويُقاس أثرُه ولا يُرقّي
مستوى الكلمة**، والتوقيعُ فعلُ صاحب المستودع.

**وما لا يقيسه هذا الختم**: الدورَ **الصحيح** في كلّ موضع. فلا مرجعَ مُودَعٌ
لأدوار المواضع؛ والمقيسُ **عددُ الأدوار الممكنة** في الخانة التي يقع فيها
الموضع — أي ما يبقى على مَن لا يعرف إلّا الموقعَ والحال. **وخطأُ الجدول
يدخل الأعداد**، ولا يعرفه الحسابُ إلّا في خانةٍ فارغةٍ امتلأت (ر١).
"""

