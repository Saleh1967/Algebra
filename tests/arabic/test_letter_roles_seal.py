def test_the_seal_is_recomputed_from_the_written_conditions() -> None:
    """البصمةُ تُشتَقّ من الشروط لا تُنقَل."""

    assert seal(ORACLE, PREDICTIONS) == DIGEST


def test_the_deposited_table_is_the_one_sealed() -> None:
    """الجدولُ المُودَع هو المختوم بايتةً بايتة — وبصمتُه في المصدر."""

    assert hashlib.sha256(TABLE.read_bytes()).hexdigest() == TABLE_DIGEST
    assert TABLE_DIGEST in ORACLE.source


def test_the_table_has_twelve_cells_for_each_of_the_nine() -> None:
    """تسعةُ حروفٍ × اثنتا عشرة خانة = ١٠٨ صفًّا، ولا دورَ خارجَ الأربعة."""

    rows = [
        line.split("\t")
        for line in TABLE.read_text(encoding="utf-8").splitlines()
        if line.strip() and not line.startswith("#")
    ][1:]
    assert len(rows) == 108
    letters = {row[0] for row in rows}
    assert letters == set("استهمونيل")
    for row in rows:
        assert len(row) == 5
        roles = row[3]
        assert roles == "—" or set(roles.split("،")) <= set("أزلم")
    assert "غيرُ موقَّعة" in TABLE.read_text(encoding="utf-8")


def test_one_condition_guards_the_table_and_four_the_claim() -> None:
    """ر١ عن الجدول، وأربعةٌ عن «يرجّحان ولا يحسمان»."""

    assert {one.identifier for one in PREDICTIONS} == {"ر١", "ر٢", "ر٣", "ر٤", "ر٥"}
    for one in PREDICTIONS:
        assert one.falsifies.strip()
