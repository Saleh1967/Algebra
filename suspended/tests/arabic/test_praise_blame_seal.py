"""**ختمٌ قبل النظر**: لوازمُ مسوّدةٍ منقولةٍ، مقيسةً في البايتات.

**لم يُشغَّل شيءٌ بعد.**

**ما يُختَم**: أُودِعت في `deposits/praise_blame_rule.md` **مسوَّدةٌ غيرُ
موقَّعة** نُقِلت عن مقالٍ خارجيّ. **ولستُ أنا مَن يوقّعها**، ولا يدخل
المستودعَ منها حكمٌ نحويّ. وإنّما تُشتَقّ منها **لوازمُ في البايتات**
وتُقاس، فإن سقطت **سقطت بأرقامها**.

**واللازمُ الوحيدُ المقيس**: أنّ لصورةٍ مُودَعةٍ **أثرًا في حقل الحال عند
الموضع الذي يليها**. ولا يُقاس إعرابٌ ولا فاعليّةٌ ولا ابتداءٌ ولا تقدير،
**ولا يُدَّعى نفيُ شيءٍ من ذلك ولا إثباتُه**.

**والصورُ تُقرأ من الإيداع بنمطٍ ولا تُكتَب في الشيفرة**، وتُعرَض **شرائحَ
من المجمَّد بضبطها** لا حروفًا تُركَّب. وما لا يوجد منها **يُطبَع باسمه**
ولا يُطوى.

**والتصعيد بتّةً بتّة**: يُشرَط حقلُ الحال بخمس درجاتٍ متتاليةٍ **كلُّ
درجةٍ تزيد ما تعرفه الآلة**:

- **د٠**: بلا شرط — `H(الحال)`.
- **د١**: **بتّةٌ واحدة** — أتالٍ لصورةٍ مُودَعةٍ أم لا.
- **د٢**: هويّةُ الصورة.
- **د٣**: الصورةُ والموضعُ النسبيُّ منها (الأوّلُ أم الثاني).
- **د٤**: وحالُ الموضع السابق معها.

**وكلُّ درجةٍ تُقاس ملحَقةً ومحجوزة**: فالنزولُ داخلَ العيّنة **مضمونٌ
بالمبرهنة**، والنزولُ على المحجوز **وحدَه خبر**. وموضعُ الانقلاب — إن وقع —
**هو حدُّ ما تحمله المادّة**، لا حدُّ ما تحمله القراءة.

**وinduction on**: مبرهنتان مُصانتان عند كلّ درجةٍ وكلّ حال: الشرطُ لا يرفع
الإنتروبيا، و`log₂ التباديل ≤ N·H`. **وinduction FOR**: الحلقةُ تشهد عليهما
**سطرًا سطرًا** وتُقابِل العدّاداتِ بالأسطر. **وطرفاهما يُؤخَذان بعد ألفِ
لفظ** لا عند أوّل الحلقة — إصلاحًا لِما مرَّ بطرفٍ تافهٍ في `7773c03f…`.

**وحدُّ اللفظ هو المُصحَّح** من `494465d1…`: متتاليةٌ بلا فراغٍ فيها محرفٌ
عربيٌّ واحدٌ على الأقلّ. **ولا يُعاد الخطأُ الثالثُ والعشرون.**

**وما لا يفصل فيه هذا الختم**: الأعاريبُ الأربعةُ للمخصوص المتأخّر
**لا تفترق في البايتات ألبتّة** — الحروفُ واحدةٌ والعلاماتُ واحدة.
**فلا يُرجَّح بينها، ولا يُدَّعى الترجيح.**
"""

