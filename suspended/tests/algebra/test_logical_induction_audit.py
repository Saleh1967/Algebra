"""حلقةُ الاستقراء المنطقيّ: **البرهانُ صحيح، والتجربةُ لا تشهد له**.

**ما وصل**: وثيقةٌ ومعها أرشيفُ مراجع، بلا شيفرةٍ ولا أثر. فأُعيد بناءُ
التجربة كما وُصِفت وفُحِصت. ومادّةُ هذا الملفّ **مبنيّةٌ باليد**، فيجري في
كلّ شجرة.

`THE_INVARIANT_AND_ITS_DOUBLE_INDUCTION_ARE_CORRECT`: القانونُ
`(R−G) ≡ (R₀−G₀) mod 3` **صحيح**، وبرهانُه المزدوجُ سليمٌ حالةً حالة:
المانحان R,G يُبقيان الفرقَ، وR,B يُنقِصانه ثلاثةً، وG,B يزيدانه ثلاثة.
ولا اعتراضَ على §٣ ولا §٤.

`AND_THE_SIX_MASKS_ARE_ONE_LAW_AND_HERE_IS_WHY`: ودعوى «ستّةُ أقنعةٍ
لقانونٍ واحد» **صحيحةٌ ببرهان**: بثبات المجموع `R+G+B ≡ s (mod 3)` يلزم
`(G−B) ≡ (R−G) − s` و`(R−B) ≡ 2(R−G) − s`. فالفروقُ الثلاثةُ يعيّن بعضُها
بعضًا، وبإشارتين تصير ستًّا. مفحوصٌ ههنا على الحالات كلِّها.

`BUT_THE_THIRTEEN_CANDIDATES_ARE_NOT_REPRODUCIBLE`: و«١٣ مرشَّحًا» **لا
يُعاد**: فضاءُ المسح غيرُ مُعلَن. وبثلاثة فضاءاتٍ طبيعيّةٍ يخرج **١١** و**٢٨**
و**٧٦** — ولا واحدٌ منها ثلاثةَ عشر. والعددُ دالّةٌ في الفضاء لا في المادّة،
فإعلانُ الإغلاق شرطُ قراءةٍ لا زينة.

`THE_ZERO_POINT_NINE_PER_CENT_GAP_IS_A_SHORT_SAMPLE_NOT_A_MIXING_MEASURE`:
و«١١٦/١١٧ = مقياسُ المزج» غيرُ صحيح: بالبحث الشامل **الحالاتُ السبعَ عشرةَ
ومئةً كلُّها مبلوغة**، وتشغيلٌ بخمسة آلاف خطوةٍ يزورها جميعًا. فالفجوةُ
**نقصُ عيّنةٍ يمحوه التطويل**، لا خاصّةٌ في السلسلة. ومتبقٍّ يمحوه إعادةُ
تشغيلٍ ليس متبقّيًا.

`AND_FIFTY_THOUSAND_STEPS_DID_NO_WORK_AT_ALL`: وأحدُّ ما خرج: **عشرُ خطواتٍ
تُعطي ما تُعطيه خمسون ألفًا**. فالكاذبون الناجون **صفرٌ عند كلّ طول** —
عند ٧ حالاتٍ مزارةٍ وعند ١١٧. والسببُ أنّ فضاء المرشَّحات صيغٌ خطّيّةٌ
صلبة، تُحسَم بحفنة نقاط. فبندُ «خمسون ألفَ خطوةٍ بصفر انتهاك» **يمرّ
مجّانًا**: لا يبدّل حكمًا، ولا يحمل ثقلًا شاهديًّا.

`THE_SIMULATION_TESTS_THE_CODE_NOT_THE_MATHEMATICS`: بل أعمقُ من ذلك:
الانتهاكُ **ممتنعٌ بالبناء**، إذ الحركاتُ الثلاثُ كلُّها تحفظ الفئة. فصفرُ
الانتهاكات نتيجةٌ لازمةٌ من تعريف الحركة، ومحاكاةٌ تبحث عنه **تفحص
المُنفِّذَ لا المبرهنة**. ولذلك قيمةٌ حقيقيّةٌ — تُمسِك عطلَ شيفرةٍ — ولكنّها
ليست شاهدًا على الرياضيّات.

`A_POSTERIOR_OVER_A_DECIDABLE_PROPOSITION_IS_THE_WEAKER_TOOL`: و«القناعةُ
البيزيّة ٠٫٧٥ ← ٠٫٩٩٩٩٨٣» تحديثُ لابلاس لا مُستقرِئٌ منطقيّ. وفضاءُ الحالات
**٣٥١ حالةً منتهية**، والخاصّةُ تُحسَم بالمسح الشامل في أجزاءٍ من الثانية.
فاحتمالٌ على قضيّةٍ **قابلةٍ للحسم** أضعفُ من حسمها، واستدعاءُ آلةِ
المستقرئ المنطقيّ — وهي لمن عجز عن الحسم — في موضعٍ يُحسَم بالقوّة الغاشمة
**نقلٌ في غير موضعه**.

`THE_RESTARTS_MAKE_THE_LAW_UNFALSIFIABLE_AT_THE_SEAM`: والحالةُ العالقةُ
**واحدةٌ**: `(25,0,0)` — لا حركةَ منها. فكلُّ إعادةِ إطلاقٍ منها تعود إلى
الفئة نفسِها (وإلّا فقد بُدِّلت التجربةُ لا خُرِق القانون). فالانتهاكُ عند
الإطلاق **ممتنعٌ بسياسة الإطلاق**، ويُعلَن ولا يُعَدّ شاهدًا.

`AND_THE_CLOSURE_WAS_DECLARED_SO_THE_COUNT_REPLICATES_WHERE_IT_MATTERS`:
**وأُعلِن الفضاءُ بعدُ**، فأُعيد العدّ: غيرُ البديهيّة **ثلاثون عندهم
وثلاثون عندنا** — تطابقٌ تامّ. والبديهيّةُ ستٌّ وسبعون عندهم وستٌّ وأربعون
عندنا، فالفضاءُ لم يتّحد بعدُ في طرفه الأعمى. **وذلك الطرفُ إفادتُه صفر**
بنصّ صيغتهم، فالخلافُ محصورٌ فيما لا يُفيد.

`THE_THIRTY_MASKS_INDUCE_ONE_PARTITION_AND_THAT_IS_A_STRONGER_PROOF`:
ودعوى «قانونٌ واحدٌ بثلاثين قناعًا» **مبرهَنةٌ تقسيمًا لا جبرًا**: الثلاثون
تفرض على الفضاء كلِّه **تقسيمًا واحدًا** بكتلٍ ١١٧/١١٧/١١٧ — تقسيمٌ متمايزٌ
واحدٌ لا غير. وذلك أقوى من التكافؤ بحساب البواقي، إذ يُقام على الخانات
نفسِها.

`AND_SATURATION_AT_THREE_STATES_SHARPENS_MY_OWN_TEN`: وقلتُ في الدورة
الماضية «عشرُ خطواتٍ تكفي»، والمقيسُ الآن **ثلاثُ حالاتٍ متمايزة**:
`|K|` = ١٧٠ عند حالتين، و**٧٦** عند ثلاث، ثمّ لا ينزل أبدًا. فعدُّهم
`t = 3` يوافق هذا متى عُدَّت حالةُ البدء مشاهَدًا — واختلافُ الواحد
اصطلاحُ ترقيمٍ يُعلَن ولا يُختلَف فيه.

`SO_WHAT_IS_NOT_SWALLOWED_IS_THE_DECLARED_CLOSURE`: وجوابُ سؤالهم الأخير —
«ما الذي لا يُبتلَع في الانتقال من الشاهد إلى القانون؟» — مقيسٌ ههنا: ليست
**قابليّةَ التكذيب**، فتلك ممتنعةٌ في هذه التجربة أصلًا. الذي لا يُبتلَع هو
**إغلاقُ فضاء المرشَّحات**: الأثرُ لا يحمل شيئًا (عشرٌ = خمسون ألفًا)،
والعملُ كلُّه في الفضاء المُعلَن. ولذلك سقط «١٣» حين غاب إعلانُه.
"""

from __future__ import annotations

import math
import random
from collections import deque

TOTAL = 25
START = (9, 8, 8)
STATES = [(r, g, TOTAL - r - g) for r in range(TOTAL + 1) for g in range(TOTAL - r + 1)]


def moves(state: tuple[int, int, int]) -> list[tuple[int, int, int]]:
    """قواعدُ التحويل الثلاث: مانحان يُعطيان واحدًا، والثالثُ يأخذ اثنين."""

    red, green, blue = state
    out: list[tuple[int, int, int]] = []
    if red >= 1 and green >= 1:
        out.append((red - 1, green - 1, blue + 2))
    if red >= 1 and blue >= 1:
        out.append((red - 1, green + 2, blue - 1))
    if green >= 1 and blue >= 1:
        out.append((red + 2, green - 1, blue - 1))
    return out


def _reachable(start: tuple[int, int, int]) -> set[tuple[int, int, int]]:
    seen, queue = {start}, deque([start])
    while queue:
        state = queue.popleft()
        for nxt in moves(state):
            if nxt not in seen:
                seen.add(nxt)
                queue.append(nxt)
    return seen


REACHABLE = _reachable(START)


def _sweep(
    states: list[tuple[int, int, int]],
    coefficients: range,
    moduli: range,
) -> set[tuple[int, int, int, int]]:
    out: set[tuple[int, int, int, int]] = set()
    for modulus in moduli:
        for first in coefficients:
            for second in coefficients:
                for third in coefficients:
                    if (first % modulus, second % modulus, third % modulus) == (
                        0,
                        0,
                        0,
                    ):
                        continue
                    values = {
                        (first * red + second * green + third * blue) % modulus
                        for red, green, blue in states
                    }
                    if len(values) == 1:
                        out.add((first, second, third, modulus))
    return out


def _trace(length: int, seed: int = 7) -> set[tuple[int, int, int]]:
    rng = random.Random(seed)
    state, visited = START, {START}
    for _ in range(length):
        nxt = moves(state)
        state = START if not nxt else rng.choice(nxt)
        visited.add(state)
    return visited


def test_the_invariant_holds_under_every_rule_from_every_state() -> None:
    """البرهانُ الداخليُّ مفحوصٌ على الحالات كلِّها لا على ثلاثٍ مكتوبة."""

    for state in STATES:
        before = (state[0] - state[1]) % 3
        for nxt in moves(state):
            assert (nxt[0] - nxt[1]) % 3 == before
            assert sum(nxt) == TOTAL


def test_the_six_masks_are_one_law_because_the_sum_is_fixed() -> None:
    """`(G−B) ≡ (R−G) − s` و`(R−B) ≡ 2(R−G) − s` — فالفروقُ متعيّنةٌ ببعضها."""

    residue = TOTAL % 3
    for red, green, blue in STATES:
        first = (red - green) % 3
        assert (green - blue) % 3 == (first - residue) % 3
        assert (red - blue) % 3 == (2 * first - residue) % 3


def test_the_candidate_count_depends_entirely_on_an_undeclared_space() -> None:
    """١١ و٢٨ و٧٦ بثلاثة فضاءات — ولا واحدٌ منها ثلاثةَ عشر."""

    counts = {
        len(_sweep(sorted(REACHABLE), range(0, 3), range(2, 5))),
        len(_sweep(sorted(REACHABLE), range(0, 4), range(2, 6))),
        len(_sweep(sorted(REACHABLE), range(-2, 3), range(2, 8))),
    }
    assert counts == {11, 28, 76}
    assert 13 not in counts


def test_the_six_non_trivial_forms_do_come_out_as_claimed() -> None:
    """وفي أضيق الفضاءات: خمسٌ بديهيّةٌ وستٌّ غيرُ بديهيّة — والستّةُ تصدق."""

    found = _sweep(sorted(REACHABLE), range(0, 3), range(2, 5))
    trivial = {
        one
        for one in found
        if len({one[0] % one[3], one[1] % one[3], one[2] % one[3]}) == 1
    }
    assert len(found) == 11
    assert len(trivial) == 5
    assert len(found - trivial) == 6
    assert all(one[3] == 3 for one in found - trivial)


def test_every_state_of_the_class_is_reachable_so_the_gap_is_a_short_sample() -> None:
    """١١٧ من ١١٧ بالبحث الشامل، وخمسةُ آلافِ خطوةٍ تزورها كلَّها."""

    in_class = [
        one for one in STATES if (one[0] - one[1]) % 3 == (START[0] - START[1]) % 3
    ]
    assert len(in_class) == 117
    assert len(REACHABLE) == 117
    assert not set(in_class) - REACHABLE
    assert len(_trace(5_000)) == 117
    # وعند ألفٍ تظهر الفجوةُ المعلَنةُ نفسُها — فهي طولُ أثرٍ لا مزج
    assert len(_trace(1_000)) == 116


def test_ten_steps_decide_what_fifty_thousand_decide() -> None:
    """صفرُ كاذبين عند كلّ طول — فبندُ «خمسين ألفًا» يمرّ مجّانًا."""

    truth = _sweep(sorted(REACHABLE), range(-2, 3), range(2, 8))
    for length in (10, 30, 1_000, 50_000):
        survivors = _sweep(sorted(_trace(length)), range(-2, 3), range(2, 8))
        assert survivors == truth, length
    assert len(_trace(10)) < 10 < len(REACHABLE)


def test_a_violation_is_impossible_by_construction_so_zero_is_not_evidence() -> None:
    """الحركاتُ الثلاثُ تحفظ الفئةَ كلُّها، والعالقُ واحدٌ — والإطلاقُ يعيد إليها."""

    stuck = [one for one in REACHABLE if not moves(one)]
    assert stuck == [(25, 0, 0)]
    assert (stuck[0][0] - stuck[0][1]) % 3 == (START[0] - START[1]) % 3
    # ولا حركةَ في الفضاء كلِّه تغادر الفئة
    assert all(
        (nxt[0] - nxt[1]) % 3 == (one[0] - one[1]) % 3
        for one in STATES
        for nxt in moves(one)
    )


def test_the_proposition_is_decidable_by_exhaustion_so_a_posterior_is_weaker() -> None:
    """٣٥١ حالةً منتهية: المسحُ الشاملُ يحسم، والاحتمالُ دونه."""

    assert len(STATES) == 351 == 27 * 26 // 2
    assert len({(one[0] - one[1]) % 3 for one in STATES}) == 3
    decided_by_exhaustion = all(sum(one) == TOTAL for one in STATES)
    assert decided_by_exhaustion


def test_the_informativeness_of_the_law_and_of_its_trivial_masks() -> None:
    """`log₂(351/117) = 1.5850` بت للقانون، وصفرٌ للبديهيّ — أقنعةُ الصفر."""

    assert abs(math.log2(len(STATES) / 117) - 1.5850) < 1e-4
    assert math.log2(len(STATES) / len(STATES)) == 0
    assert len(STATES) == 3 * 117


def test_the_survivor_set_saturates_at_three_distinct_states() -> None:
    """١٧٠ عند حالتين، و٧٦ عند ثلاث — ولا ينزل بعدها أبدًا."""

    rng = random.Random(7)
    state, visited = START, [START]
    sizes = []
    for _ in range(12):
        nxt = moves(state)
        state = START if not nxt else rng.choice(nxt)
        visited.append(state)
        sizes.append(
            (
                len(set(visited)),
                len(_sweep(sorted(set(visited)), range(-2, 3), range(2, 8))),
            )
        )
    truth = len(_sweep(sorted(REACHABLE), range(-2, 3), range(2, 8)))
    assert sizes[0] == (2, 170)
    assert sizes[1] == (3, truth) == (3, 76)
    assert all(one[1] == truth for one in sizes[1:])
    # وهو أضيقُ ممّا قلتُه أوّلًا (عشرُ خطوات) — والتضييقُ يُسجَّل
    assert 3 < 10


def test_the_thirty_masks_induce_exactly_one_partition_of_the_whole_space() -> None:
    """تقسيمٌ واحدٌ بكتلٍ ١١٧/١١٧/١١٧ — فالتكافؤُ مُقامٌ على الخانات."""

    found = _sweep(sorted(REACHABLE), range(-2, 3), range(2, 8))
    trivial = {
        one
        for one in found
        if len({one[0] % one[3], one[1] % one[3], one[2] % one[3]}) == 1
    }
    masks = found - trivial
    assert len(masks) == 30

    partitions = set()
    for first, second, third, modulus in masks:
        table: dict[int, set[tuple[int, int, int]]] = {}
        for state in STATES:
            key = (first * state[0] + second * state[1] + third * state[2]) % modulus
            table.setdefault(key, set()).add(state)
        partitions.add(frozenset(frozenset(one) for one in table.values()))
    assert len(partitions) == 1
    assert sorted(len(one) for one in next(iter(partitions))) == [117, 117, 117]


def test_a_partition_preserving_merge_loses_nothing_and_a_losing_one_is_a_seam() -> (
    None
):
    """التكتّلُ الحافظُ للتقسيم إغلاقٌ، والخاسرُ له لَحْم — وجهان لشرطٍ واحد."""

    keeping = 30  # ثلاثون قناعًا تنهار إلى قانونٍ واحدٍ بلا فقد
    losing = 0  # ولا قناعَ يفرض تقسيمًا ثانيًا
    assert keeping > 0 and losing == 0
    assert math.log2(len(STATES) / 117) > 0  # والإفادةُ محفوظةٌ في الانهيار
