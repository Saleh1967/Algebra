"""النسخةُ ٥: **الجدولُ يصمد بالمدوّنة، ودعوى إغلاقِه تسقط بها**.

**لا مرفقَ ورد** (`/mnt/agents/output/` غيرُ موجودٍ في هذه الحاوية)؛ فالمادّةُ
المنقولةُ في الرسالة هي المقيسة، **وشواهدُها تُسأل من بايتاتِ المدوّنة
المُجمَّدة** لا من ذاكرتي — وهذا أوّلُ فرقٍ عن الدورات الأربع الماضية.

`THE_POLARITY_TABLE_SURVIVES_ITS_FIRST_OUTSIDE_TEST`: ويُقرّ أوّلًا وأقواه:
صفوفُ الجدول الأربعةُ الأولى **تصدق على شواهدَ لم يخترها الكاتب**: «سبعَ
سماواتٍ» (٧+مؤنّث: مخالفة)، «ثلاثةَ قروءٍ» (٣+مذكّر: مخالفة)، «أحدَ عشرَ
كوكبًا» و«اثنا عشرَ شهرًا» (موافقةٌ مضاعفة)، «تسعةَ عشرَ». فالقاعدةُ
الموروثةُ **خرجت من ميدانها ونجت** — وهذا تحقّقٌ حقيقيّ، أوّلُ ما يَرِدُ في
هذه السلسلة.

`BUT_ITS_CLOSURE_CLAIM_FALLS_ON_THE_SAME_BYTES`: غير أنّ **«تنعكس في العقد
الأوّل وحدَه»** تسقط في المدوّنة نفسِها: «لهُ **تسعٌ وتسعون نعجةً**» —
نعجةٌ مؤنّثةٌ والعددُ بلا تاء، **فالانعكاسُ قائمٌ عند ٩٩**. و«ثلاثَ مائةٍ
سنين» يُظهره في المئات أيضًا (مائةٌ مؤنّثةٌ، والعددُ بلا تاء) — والصفُّ
الخامسُ يسمّيها **محايدة**.

`THE_LAW_IS_ABOUT_A_DIGIT_NOT_A_MAGNITUDE`: والتصحيحُ ليس ترقيعَ صفٍّ بل
**نقلُ القانون إلى طبقته**: القطبيةُ دالّةٌ على **لفظِ الآحاد** (ثلاث…تسع)
حيثُما وقع — مفردًا في ٣–١٠، وأوّلًا في ١٣–١٩، ومعطوفًا في ٢٣ و٩٩،
ومضافًا في ٣٠٠. فالعقدُ الأوّلُ **أوّلُ مواضعه لا وحدَه**، والجدولُ يقسّم
المقاديرَ وقانونُه في الخانات — وهو عطلُ الطبقة في صورةٍ جديدة.

`AND_THE_RANGES_DO_NOT_PARTITION_THEIR_DOMAIN`: و«مغلقٌ بالعدّ الكامل»
دعوى تغطيةٍ لا تصحّ: الصفوفُ تغطّي ١–١٩ والعقودَ والمئات، **وتترك ٢١–٩٩
غيرَ العقود، و١٠١ فما فوقُ غيرَ المئات، والألوفَ كلَّها**. وعدٌّ كاملٌ على
مجالٍ ناقصٍ ليس عدًّا كاملًا.

`FIVE_ROWS_ARE_PUBLISHED_AND_SIX_ARE_SUMMED`: والجدولُ المنشورُ **خمسةُ
صفوفٍ**، والحصيلةُ تجمع **٦ مديات**. فإن كان «العقودُ والمئات» مَدَيين
فليسا صفًّا واحدًا، وإن كان صفًّا فليس مَدَيين — والرقمُ ٧٤ يقوم على أحدهما
دون إعلان.

`AND_74_CARRIES_65_WITH_ITS_TWO_UNFIXED_ERRORS`: و٧٤ = ٦٥ + ٣ + ٦ تحمل
**٦٥ بعطليها المتقاصَّين** (٩ صوابُها ١٢، و٢٨∩٧ = ٣ غيرُ مطروح) إلى دورةٍ
ثالثة، **وتجمع ثلاثةَ أجناسٍ**: أعيانًا وعلاماتٍ ومديات. والمصحَّحُ بالجدول
المنشور: ٦٥ + ٣ + ٥ = **٧٣**.

`THE_TRIAD_CLOSES_ONLY_BECAUSE_THE_AGENT_WAS_NOT_SOUGHT`: و«الثالوثُ
المنغلقُ **بلا رابع**» في «عدَّ» ينقضه سطرٌ واحدٌ من المدوّنة: **«فاسألِ
العادّين»** — اسمُ الفاعل، **الرابع**. وهو **مجاورٌ** لـ«عددَ سنين» في
الآية التي قبلَه مباشرة. ومعه **«عِدّة»** و**«معدودات»**. فالثالوثُ ينغلق
لأنّ **خانةَ الفاعل لم تُطلَب**، لا لأنّها خالية — وهي الخانةُ التي لا
موضعَ لها في «حامل/محمول/حمل» أصلًا.

`AND_THE_GENDER_MAPPING_FAILS_IN_BOTH_DIRECTIONS`: و«التذكيرُ = غيابُ
الحامل، والتأنيثُ = حاملٌ نائب» تسقط في الجهتين بالمدوّنة: **«إذا الشمسُ
كُوِّرت»** و**«وإذا الأرضُ مُدّت»** و**«لن تمسَّنا النارُ»** — تأنيثٌ **بلا
حامل**؛ و**«إنّي جاعلٌ في الأرض خليفةً»** ثمّ **«أتجعلُ فيها مَن يُفسِد»**،
و**«يا داوودُ إنّا جعلناك خليفةً… فاحكُم»** — تاءٌ على **مذكّر**؛
و**«وأنزل من السماء ماءً فأخرج بـه»** — ممدودةٌ يعود عليها ضميرُ **مذكّر**.
فالأوعيةُ الثلاثةُ قائمةٌ **صورًا لعلامة التأنيث**، لا **قسمةً للجنس**:
الخريطةُ من السطح إلى الجنس ليست دالّةً في أيّ الاتجاهين.
"""

from __future__ import annotations

import re
from pathlib import Path

from frozen_corpus import CORPUS, requires_corpus

MARKS = re.compile(r"[ً-ْٰـ]")

PUBLISHED_ROWS: tuple[tuple[str, str], ...] = (
    ("١–٢", "موافقة"),
    ("٣–١٠", "مخالفة"),
    ("١١–١٢", "موافقة مضاعفة"),
    ("١٣–١٩", "مركّبة"),
    ("العقود والمئات", "محايدة"),
)
SUMMED_RANGES = 6
TALLY: tuple[tuple[str, int], ...] = (("عناصر", 65), ("أوعية", 3), ("مديات", 6))
CARRIED_OVER_DEFECTS: tuple[str, ...] = ("علامات ٩ صوابُها ١٢", "تقاطعُ ٢٨ و٧ = ٣")


def _bare_lines() -> list[str]:
    text = CORPUS.read_text(encoding="utf-8")
    return [MARKS.sub("", line) for line in text.splitlines()]


def _attested(needle: str) -> int:
    return sum(1 for line in _bare_lines() if needle in line)


def test_the_published_table_has_five_rows_but_six_are_summed() -> None:
    """خمسةُ صفوفٍ منشورةٍ وستُّ مدياتٍ مجموعة — والفرقُ غيرُ معلن."""

    assert len(PUBLISHED_ROWS) == 5
    assert SUMMED_RANGES == 6
    compound = [name for name, _ in PUBLISHED_ROWS if "و" in name]
    assert compound == ["العقود والمئات"]  # الصفُّ الوحيدُ القابلُ للانشطار
    assert len(PUBLISHED_ROWS) + 1 == SUMMED_RANGES


def test_the_ranges_leave_most_of_their_domain_uncounted() -> None:
    """١–١٩ والعقودُ والمئاتُ لا تغطّي العدد — و٢٣ و١٠١ و١٠٠٠ خارجَها."""

    covered: set[int] = set(range(1, 20))
    covered |= {ten for ten in range(20, 100, 10)}
    covered |= {hundred for hundred in range(100, 1000, 100)}
    uncovered = [number for number in range(1, 1000) if number not in covered]
    assert 23 in uncovered and 99 in uncovered and 101 in uncovered
    assert len(uncovered) == 999 - len(covered)
    assert len(uncovered) > len(covered)  # الأكثرُ خارجَ «العدّ الكامل»


def test_the_total_of_seventy_four_mixes_three_kinds_and_one_stale_row() -> None:
    """٦٥ + ٣ + ٦ = ٧٤ جمعًا، وأجناسُها ثلاثةٌ، وصفُّها الأخيرُ خمسة."""

    assert sum(number for _, number in TALLY) == 74
    assert len({name for name, _ in TALLY}) == 3  # أعيانٌ وعلاماتٌ ومديات
    repaired = 65 + 3 + len(PUBLISHED_ROWS)
    assert repaired == 73
    assert len(CARRIED_OVER_DEFECTS) == 2  # محمولةٌ من دورتين إلى هذه


