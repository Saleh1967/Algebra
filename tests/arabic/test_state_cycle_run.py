def test_the_two_proven_bounds_hold_and_their_extremes_are_trivial() -> None:
    """ح٣ وح٤ مبرهنتان — وطرفاهما عند أوّل الحلقة، فيُعادان بعد ألف."""

    least = float(_grab(r"أدنى \(H\(التالي\) − H\(التالي\|السابق\)\) = (\S+)"))
    most = float(_grab(r"أقصى \(log₂ التباديل − N·H\) = (\S+)"))
    assert _one("ح٣").verdict(_exact(least)) is Verdict.MET  # type: ignore[attr-defined]
    assert _one("ح٤").verdict(_exact(most)) is Verdict.MET  # type: ignore[attr-defined]
    assert least == 0.0 and most == 0.0  # طرفان تافهان، ويُقال ذلك
    settled = float(_grab(r"أدنى فرقٍ بعد ألف = (\S+)"))
