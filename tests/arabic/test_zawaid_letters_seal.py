"""**ختمٌ قبل النظر**: «سألتمونيها» — أهي وحدها حروفُ الزيادة؟ وماركوف بالمجموعات.

**لم يُعَدّ شيءٌ بعد.**

**العِلّة**: ختمُ `72b39b4c…` سأل عن أدوار حروف «سألتمونيها» فسقط شرطُه الأوّل في
الآلة (الشدّة أوّلَ اللفظ)، فبطلت شروطُه الباقية ولم تُختبَر الدعوى نفسُها.
والجدولُ الذي وقّعه صاحبُ المستودع يقول في الاشتقاقيّ: حروفُ «سألتمونيها»
تكون أصلًا وزائدة، **وغيرُها أصليٌّ لا يُزاد إلا تكريرًا**. وهذه دعوى تُختبَر
على البايتات دون جدول جذور: إن لم يُزَد في البنية غيرُ التسعة، فحروفُ اللفظ
من غيرها لا تتجاوز حروفَ الجذر ومعها الملتصقاتُ القليلة.

**مجموعاتُ الوظيفة ثلاث** (من الجدول الموقَّع، بالحرف بعد الطيّ):

- **ز — الزائدُ الممكن**: ا س ل ت م و ن ي ه («سألتمونيها» تسعةً بعد الطيّ).
- **م — الملتصقُ غيرُ الزائد**: ب ف ك (حروفُ معانٍ وضمائرُ تلتصق باللفظ ولا
  تدخل الوزن).
- **أ — الأصليُّ وحده**: الستّة عشر الباقية.

**والشروطُ ثلاثة**:

- **س١ — سقفُ غير الزائد**: في الألفاظ ذات سبعة أحرفٍ فأكثر، نصيبُ ما لا
  يتجاوز فيه حروفُ م وأ خمسةً لا يقلّ عن ٠٫٩٩. والخمسةُ: جذرٌ رباعيٌّ وملتصق،
  أو ثلاثيٌّ وملتصقان.
- **س٢ — والسقفُ ليس أثرَ الطول**: ذلك النصيبُ يزيد بعُشرٍ على الأقلّ على ما
  يعطيه سحبُ الحروف مستقلّةً بنسبة م وأ في المصحف كلّه (توزيعٌ ذو حدّين).
- **س٣ — ماركوف: الحالُ الابتدائيّة**: نصيبُ الألفاظ التي يبدأ حرفُها الأوّل
  من أ يقلّ عن نصيب أ في الحروف كلّها بنصف عُشرٍ على الأقلّ — لأنّ السوابق
  (ال، و، ف، ب، حروفُ المضارعة، ميمُ مَفعَل) كلُّها من ز وم.

**وما رُئي قبل الختم**: أعدادُ الوحدات الـ١١٢ في ختم `a581ddb9…` (ومنها نسبُ
الحروف مجموعةً في الإملائيّ، ولم تُجمَع على هذه المجموعات)، ونتائجُ الأزواج
الدنيا والعامل. **ولم يُعَدّ حرفٌ بحسب هذه المجموعات، ولا موضعُه من اللفظ.**
"""

from __future__ import annotations

from fractions import Fraction

from algebra.signified import Direction, Oracle, Prediction, seal

ORACLE = Oracle(
    name="حروفُ الزيادة ومجموعاتُ الوظيفة في اللفظ",
    source=(
        "quran-simple-enhanced.txt — البصمة 37633090…؛ والمجموعاتُ من "
        "deposits/unit_roles_draft.tsv الموقَّع"
    ),
    extraction=(
        "يُطرح الوسم <sel> فراغًا، واللفظُ ما فصلته الفراغات بتكراره؛ وحروفُه "
        "وحداتُ run_cv_peel.peel بعد طرح البنيويّ وذيل التنوين والشطر الأوّل "
        "من الشدّة، فالحرفُ المكتوب يُعَدّ مرّة؛ وز: ا س ل ت م و ن ي ه، "
        "وم: ب ف ك، وأ: ما سواها من الثمانية والعشرين؛ وسقفُ س١ عددُ حروف م "
        "وأ في اللفظ؛ ومقامُ س١ وس٢ الألفاظُ ذات سبعة أحرفٍ فأكثر؛ والمتوقَّعُ "
        "في س٢ متوسّطُ احتمال ألّا يتجاوز ذو الحدّين خمسةً بطول اللفظ ونسبةِ "
        "م وأ في حروف المصحف كلّه؛ ومقامُ س٣ الألفاظُ ذات حرفين فأكثر، وحالُها "
        "الابتدائيّةُ مجموعةُ حرفها الأوّل؛ وأعدادُ الوحدات الـ١١٢ رُئيت قبل "
        "الختم، والعدُّ بهذه المجموعات لم يُرَ"
    ),
)

PREDICTIONS = (
    Prediction(
        identifier="س١",
        statistic="نصيبُ الألفاظ الطويلة التي لا تتجاوز حروفُ م وأ فيها خمسة",
        threshold=Fraction(99, 100),
        direction=Direction.AT_LEAST,
        falsifies=(
            "دعوى الجدول الموقَّع في الاشتقاقيّ: إن تجاوز غيرُ الزائد خمسةً في "
            "أكثرَ من واحدٍ من مئة فحرفٌ من خارج «سألتمونيها» يدخل البنية زائدًا"
        ),
    ),
    Prediction(
        identifier="س٢",
        statistic="ذلك النصيبُ ناقصًا ما يعطيه ذو الحدّين",
        threshold=Fraction(1, 10),
        direction=Direction.AT_LEAST,
        falsifies=(
            "أنّ السقفَ من البنية: إن لم يزد على السحب المستقلّ بعُشر فالخمسةُ "
            "سقفٌ يعطيه تواترُ الحروف لا حدُّ الجذر"
        ),
    ),
    Prediction(
        identifier="س٣",
        statistic="نصيبُ أ في الحروف كلّها ناقصًا نصيبَها حرفًا أوّل",
        threshold=Fraction(1, 20),
        direction=Direction.AT_LEAST,
        falsifies=(
            "أنّ أوّلَ اللفظ موضعُ السوابق: إن لم يقلّ الأصليُّ وحده في الحرف الأوّل "
            "فالسوابقُ لا تحكم الحالَ الابتدائيّة"
        ),
    ),
)

DIGEST = "aaf77e3da2dffe379f11658afd90987d426e9ada530616bb96695b0f2440ed54"
"""يُثبَّت بعد أوّل اشتقاق، ولا يُمَسّ بعدَه."""


def test_the_seal_is_recomputed_from_the_written_conditions() -> None:
    """البصمةُ تُشتَقّ من الشروط لا تُنقَل."""

    assert seal(ORACLE, PREDICTIONS) == DIGEST


def test_three_conditions_on_the_letters_of_increase() -> None:
    """ثلاثةٌ عن المادّة، ولكلٍّ نصُّ سقوط."""

    assert {one.identifier for one in PREDICTIONS} == {"س١", "س٢", "س٣"}
    for one in PREDICTIONS:
        assert one.falsifies.strip()


def test_what_was_seen_before_the_seal_is_declared() -> None:
    """العدُّ بالمجموعات لم يُرَ — مُعلَنٌ في الاستخراج."""

    assert "والعدُّ بهذه المجموعات لم يُرَ" in ORACLE.extraction
