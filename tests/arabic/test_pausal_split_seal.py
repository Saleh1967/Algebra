def test_six_conditions_refute_the_machine_and_six_are_mine() -> None:
    """ستٌّ تردُّ الآلةَ، وستٌّ دعاوٍ لي معرَّضةٌ للسقوط."""

    machine = {"و١", "و٢", "و٣", "و٤", "و٥", "و٦"}
    mine = {one.identifier for one in PREDICTIONS} - machine
    assert len(mine) == 6, sorted(mine)
    for one in PREDICTIONS:
        if one.identifier in mine - {"و١٢"}:
            assert "دعواي" in one.falsifies, one.identifier
