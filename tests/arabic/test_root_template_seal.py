DIGEST = "7a042f97aca49108b09ca6bab03ec708719e9190a7cc158be4869b96af36728b"
"""يُثبَّت بعد أوّل اشتقاق، ولا يُمَسّ بعدَه."""


def test_the_seal_is_recomputed_from_the_written_conditions() -> None:
    """البصمةُ تُشتَقّ من الشروط لا تُنقَل."""

    assert seal(ORACLE, PREDICTIONS) == DIGEST


def test_one_machine_check_and_three_claims() -> None:
    """ن٠ فحصُ آلة، ون١–ن٣ دعاوى رياضيّة."""

    assert [one.identifier for one in PREDICTIONS] == ["ن٠", "ن١", "ن٢", "ن٣"]
    assert "والعدُّ على الشروط لم يُرَ" in ORACLE.extraction
