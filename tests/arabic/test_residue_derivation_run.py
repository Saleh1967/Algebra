from __future__ import annotations

import importlib.util
import sys
from fractions import Fraction
from pathlib import Path

from frozen_corpus import CORPUS, requires_corpus
from test_residue_derivation_seal import DIGEST, ORACLE, PREDICTIONS

from algebra.signified import Verdict, seal

REPOSITORY = Path(__file__).resolve().parents[2]
READER = REPOSITORY / "examples" / "rasm" / "run_residue_derivation.py"

pytestmark = requires_corpus

PLACES = {
    "حامل": 65_641,
    "مربوطة": 17_306,
    "سكون": 118_095,
    "تنوين": 12_994,
    "شدّة": 27_580,
}
BEST = {
    "حامل": (1, 0.3811),
    "مربوطة": (1, 0.1535),
    "سكون": (1, 0.1866),
    "تنوين": (2, 0.3015),
    "شدّة": (1, 0.0558),
}
AT_ZERO = {
    "حامل": 0.8570,
    "مربوطة": 0.5466,
    "سكون": 0.5133,
    "تنوين": 0.9074,
    "شدّة": 0.3111,
}
AT_THREE = {
    "حامل": 1.3597,
    "مربوطة": 0.5015,
    "سكون": 0.5555,
    "تنوين": 0.5914,
    "شدّة": 0.2742,
}
PUBLISHED = 93_453
NOW = 55_160
HALVING = 46_726


def _exact(measured: float) -> Fraction:
    return Fraction(measured).limit_denominator(10**9)


def _reader() -> object:
    spec = importlib.util.spec_from_file_location("run_residue_derivation", READER)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


def _corpus() -> object:
    reader = _reader()
    return reader.verses(CORPUS.read_text(encoding="utf-8"))  # type: ignore[attr-defined]


def test_the_seal_was_deposited_before_the_run() -> None:
    """البصمةُ تُشتَقّ ثانيةً — ولم يُمَسّ شرطٌ بعد النظر."""

    assert seal(ORACLE, PREDICTIONS) == DIGEST
    assert DIGEST.startswith("92b81796")


def test_every_channel_falls_and_none_is_independent() -> None:
    """الخمسُ كلُّها تنزل بالجوار — فلا قناةَ مستقلّةً عن الـ١١٢."""

    reader = _reader()
    corpus = _corpus()
    for key, (order, expected) in BEST.items():
        measured, _, places = reader.held_out(corpus, key, order)  # type: ignore[attr-defined]
        assert places == PLACES[key], key
        assert abs(measured - expected) < 5e-4, key
        assert measured < AT_ZERO[key], key  # أنزلُ من الرتبة صفر قطعًا


def test_the_sealed_halving_is_not_reached() -> None:
    """٥٥٬١٦٠ فوقَ ٤٦٬٧٢٦ — فأكثرُ من نصف البقايا خبرٌ لا يُشتَقّ."""

    second = next(one for one in PREDICTIONS if one.identifier == "و٢")
    total = sum(PLACES[key] * value for key, (_, value) in BEST.items())
    assert abs(total - NOW) < 10  # الجدولُ بأربع خانات، فالفرقُ تقريبُ نشر
    assert second.verdict(_exact(total)) is Verdict.FALSIFIED
    assert HALVING < total < PUBLISHED  # نزلت ولم تبلغ النصف


def test_my_own_reading_of_the_tied_taa_is_withdrawn() -> None:
    """و٤ كان قولي، والمقيسُ ٠٫١٥٣٥ دون ٠٫٢٠ — فيُسحَب تصنيفي."""

    fourth = next(one for one in PREDICTIONS if one.identifier == "و٤")
    _, measured = BEST["مربوطة"]
    assert fourth.verdict(_exact(measured)) is Verdict.FALSIFIED
    assert "يسقط تصنيفي لها" in fourth.falsifies
    assert measured < 0.20


def test_the_shadda_misses_the_pure_rule_line_and_is_not_rounded() -> None:
    """٠٫٠٥٥٨ ليست ٠٫٠٥ — وحدٌّ يُقرَّب بعد النظر ليس حدًّا."""

    third = next(one for one in PREDICTIONS if one.identifier == "و٣")
    lowest = min(value for _, value in BEST.values())
    assert abs(lowest - 0.0558) < 5e-5
    assert third.verdict(_exact(lowest)) is Verdict.FALSIFIED
    assert Fraction(5, 100) < _exact(lowest) < Fraction(6, 100)


def test_the_ladder_rises_where_the_data_runs_out_as_the_seal_foretold() -> None:
    """الكرسيُّ يرتفع من ٠٫٣٨١١ إلى ١٫٣٥٩٧ — ونفادُ المادّة مُشخَّصٌ سلفًا."""

    first = next(one for one in PREDICTIONS if one.identifier == "و١")
    worst = min(AT_ZERO[key] - AT_THREE[key] for key in AT_ZERO)
    assert first.verdict(_exact(worst)) is Verdict.FALSIFIED
    assert "نفادَ المادّة" in first.falsifies
    assert AT_THREE["حامل"] > AT_ZERO["حامل"]  # أعلى من الرتبة صفر أصلًا


def test_the_machine_condition_held_across_every_reading() -> None:
    """و٥: المحجوزةُ لا تنزل تحت الملحَقة في العشرين رقمًا."""

    reader = _reader()
    corpus = _corpus()
    fifth = next(one for one in PREDICTIONS if one.identifier == "و٥")
    worst = None
    for key in PLACES:
        for order in (0, 1):
            outside, _, _ = reader.held_out(corpus, key, order)  # type: ignore[attr-defined]
            plugged = reader.inside(corpus, key, order)  # type: ignore[attr-defined]
            gap = outside - plugged
            worst = gap if worst is None else min(worst, gap)
    assert worst is not None
    assert fifth.verdict(_exact(worst)) is Verdict.MET
    assert worst >= 0


def test_the_residue_share_drops_and_is_published_as_an_upper_bound() -> None:
    """٠٫٠٢٦٤ لا ٠٫٠٤٣٩ — والبسطُ محجوزٌ والمقامُ ملحَق، فهو حدٌّ أعلى."""

    body = 2_035_933
    share = NOW / (body + NOW)
    assert abs(share - 0.0264) < 5e-4
    assert share < PUBLISHED / (body + PUBLISHED)
    assert share < 0.03


