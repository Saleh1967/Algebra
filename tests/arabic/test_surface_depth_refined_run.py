def test_after_looking_the_residue_is_mostly_a_tanwin_written_on_the_alif() -> None:
    """٢٬٢٧٩ من ٢٬٧٣٣ حرفٌ يليه «اً» — تشخيصٌ بعد النظر، لا شرطٌ ولا نجاح."""

    reader = _reader()
    letters, _ = reader.letters_of(_text())
    kinds = reader.classify(letters, reader.REFINED)
    found: Counter[str] = Counter()
    for index, kind in enumerate(kinds):
        if kind != reader.RESIDUE:
            continue
        one = letters[index]
        after = reader._same_token(letters, index, 1)
        before = reader._same_token(letters, index, -1)
        doubled = after is not None and reader.SHADDA in after.marks
        if after is not None and after.glyph == "ا" and reader.FATHATAN in after.marks:
            found["قبل «اً»"] += 1
        elif (
            one.glyph == "ل" and doubled and before is not None and before.glyph == "ل"
        ):
            found["لامٌ بعد «لِـ» قبل مشدّد"] += 1
        elif one.glyph == "ل" and one.last:
            found["لامٌ آخرَ اللفظ قبل مشدّد"] += 1
        else:
            found["غيرُ ذلك"] += 1
    assert dict(found) == AFTER_LOOKING
    assert sum(OTHER_AS_PRINTED) == AFTER_LOOKING["غيرُ ذلك"]
    share = Fraction(AFTER_LOOKING["قبل «اً»"], RESIDUE)
    assert abs(float(share) - AFTER_LOOKING_SHARE) < 5e-5


