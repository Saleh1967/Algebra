"""**ختمٌ قبل النظر**: الحركةُ الأخيرة يقرّرها عاملٌ في لفظٍ آخر.

**لم يُشغَّل شيءٌ بعد مقيّدًا بالعامل.**

**العِلّة**: قاسَ مقامٌ آخر (مصنِّف hamil) توزيعَ الحركات في الوحدة الأخيرة من
اللفظ وفي داخله قبل أن يُختَم له شرط، فوجد الفتحةَ تنزل في الآخِر والضمّةَ
والكسرةَ تصعدان: داخلًا ٦١٫١٪ و١٧٫٠٪ و٢١٫٨٪، وآخرًا ٥٠٫٣٪ و٢٤٫٢٪ و٢٥٫٥٪.
**وهذا وصفٌ لا تفسير**: سلسلةُ ماركوف تُحصي احتمالَ الحركة بشرط الموضع ولا
تقول لماذا. **والتفسيرُ المقترَح** أنّ الحركةَ الأخيرة **قرارٌ** من المتكلّم
في النسبة (فاعليّةٍ أو مفعوليّةٍ أو جرّ) يجري على قالبٍ منقولٍ بالتواتر، وأنّ
العاملَ الذي يحمل القرارَ لفظٌ غيرُ اللفظ الذي تقع عليه الحركة.

**فالترتيبُ هنا** — استقراءٌ على الاستقراء، ثمّ لغاية، ثمّ من المادّة:

- **على الاستقراء**: التوزيعُ المقيس آنفًا رُئي قبل الختم، فلا يُختَم عليه؛ ولا
  يُقبَل تفسيرٌ لا يتنبّأ بما لم يُرَ.
- **لغاية**: التفسيرُ يتنبّأ بأنّ التوزيعَ ينقلب بحسب العامل الذي قبل اللفظ،
  وهذا لم يُعَدّ قطّ.
- **من المادّة**: العدُّ بعد الختم.

**والشروطُ ثلاثة**، كلُّها على اللفظ الذي يلي عاملًا منفصلًا في سطره، وعلى ما
ظهرت على آخره حركة:

- **ت١ — الجرّ**: بعد حرف جرٍّ منفصل (مِنْ، فِي، عَنْ، إِلَى، عَلَى) نصيبُ
  الكسرة لا يقلّ عن النصف. توقّعتُه بالتفكير فوق النصف، مع نقصٍ من الضمائر
  المتّصلة («مِنْ رَبِّكَ» آخرُها فتحةُ الكاف) ومن المبنيّ.
- **ت٢ — النصب بعد «إِنَّ»**: نصيبُ الفتحة لا يقلّ عن ثلاثة أرباع. وأعلم أنّ
  بعضَه يأتي من مبنيٍّ آخرُه فتحة («الَّذِينَ») لا من النصب، فالسطحُ وحده لا
  يفرّق — وهذا عيبٌ في الشرط يُعلَن قبل العدّ.
- **ت٣ — انقلاب التوزيع**: نصيبُ الكسرة بعد حرف الجرّ يزيد على نصيبها بعد
  «إِنَّ» بثلاثة أعشارٍ على الأقلّ.
"""

from __future__ import annotations

from fractions import Fraction

from algebra.signified import Direction, Oracle, Prediction, seal

ORACLE = Oracle(
    name="الحركةُ الأخيرة بشرط العامل المنفصل قبل اللفظ",
    source="quran-simple-enhanced.txt — البصمة 37633090…",
    extraction=(
        "يُطرح الوسم <sel> فراغًا، واللفظُ ما فصلته الفراغات في سطره؛ ووحداتُه ما "
        "يُخرجه run_cv_peel.peel؛ وهيكلُه حروفُ وحداته غيرِ البنيويّة بلا ذيل "
        "التنوين؛ والعاملُ لفظٌ منفصلٌ هيكلُه «من» أو «في» ووحدتُه الأولى كسرة، "
        "أو «عن» أو «علا» ووحدتُه الأولى فتحة، أو «الا» ووحدتُه الأولى كسرة "
        "(إِلَى، وإِلَّا هيكلُها «اللا» فتخرج)، فهذه حروفُ الجرّ؛ أو هيكلُه "
        "«انن» ووحدتُه الأولى كسرة وفيه شدّة، فهذه «إِنَّ»؛ واللفظُ المحكومُ هو "
        "اللفظُ الذي يليه مباشرةً في سطره؛ وحركتُه الأخيرة حالُ آخرِ وحدةٍ فيه "
        "بعد طرح الوحدات البنيويّة في آخره وذيل التنوين، فإن كانت فتحةً أو ضمّةً "
        "أو كسرةً فهي الحركة، وإلّا فلا حركةَ ظاهرةً ويخرج اللفظ من المقام؛ "
        "والنصيبُ عددُ الحركة المسمّاة على عدد ما ظهرت حركتُه؛ وتوزيعُ الحركات "
        "داخلَ اللفظ وآخرَه على المصحف كلّه رُئي قبل الختم من مقامٍ آخر، "
        "والتوزيعُ بشرط العامل لم يُرَ"
    ),
)

PREDICTIONS = (
    Prediction(
        identifier="ت١",
        statistic="نصيبُ الكسرة في آخر اللفظ الذي يلي حرفَ جرٍّ منفصلًا",
        threshold=Fraction(1, 2),
        direction=Direction.AT_LEAST,
        falsifies=(
            "التفسيرَ بالعامل في الجرّ: إن لم تغلب الكسرةُ بعد حرف الجرّ فالحركةُ "
            "الأخيرة لا يقرّرها العاملُ الذي قبلها في هذا الباب"
        ),
    ),
    Prediction(
        identifier="ت٢",
        statistic="نصيبُ الفتحة في آخر اللفظ الذي يلي «إِنَّ» منفصلة",
        threshold=Fraction(3, 4),
        direction=Direction.AT_LEAST,
        falsifies=(
            "التفسيرَ بالعامل في النصب: إن لم تغلب الفتحةُ بعد «إِنَّ» غلبةً "
            "ظاهرة فأثرُ الناسخ لا يبلغ الوحدةَ الأخيرة غالبًا"
        ),
    ),
    Prediction(
        identifier="ت٣",
        statistic="نصيبُ الكسرة بعد حرف الجرّ ناقصًا نصيبَها بعد «إِنَّ»",
        threshold=Fraction(3, 10),
        direction=Direction.AT_LEAST,
        falsifies=(
            "القولَ بأنّ التوزيعَ ينقلب بالعامل: إن لم يتباعد التوزيعان فالموضعُ "
            "وحده يصف الحركةَ الأخيرة ولا حاجةَ إلى العامل"
        ),
    ),
)

DIGEST = "c35956ef7961cabd0f6470e06146c6ef1be23c39becd89d460dab78dc380ccc4"
"""يُثبَّت بعد أوّل اشتقاق، ولا يُمَسّ بعدَه."""


def test_the_seal_is_recomputed_from_the_written_conditions() -> None:
    """البصمةُ تُشتَقّ من الشروط لا تُنقَل."""

    assert seal(ORACLE, PREDICTIONS) == DIGEST


def test_all_three_conditions_are_about_the_governor() -> None:
    """الثلاثةُ عن المادّة، ولكلٍّ نصُّ سقوط."""

    assert {one.identifier for one in PREDICTIONS} == {"ت١", "ت٢", "ت٣"}
    for one in PREDICTIONS:
        assert one.falsifies.strip()


def test_what_was_seen_before_the_seal_is_declared() -> None:
    """التوزيعُ بلا عاملٍ رُئي، وبالعامل لم يُرَ — مُعلَنٌ في الاستخراج."""

    assert "والتوزيعُ بشرط العامل لم يُرَ" in ORACLE.extraction
