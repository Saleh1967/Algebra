"""النسخةُ ٤: **٦٥ صحيحةٌ بخطأين يتقاصّان**، وF13 ينقضه جردُ صاحبه.

**لا مرفقَ ورد**؛ والمادّةُ مبنيّةٌ باليد.

`THE_DEFINITENESS_MAPPING_IS_A_REAL_GAIN`: ويُقرّ أوّلًا: **المعرفةُ اسمٌ
أُغلقت إحالتُه، والنكرةُ اسمٌ لم تُغلق بعد**، و«رجلٌ… الرجلُ» **فتحُ دَينٍ
ثمّ سداده** — بنيةُ الاستفهام والجواب بعينها. هذا وصلٌ صحيحٌ ومتّسقٌ مع
كلّ ما سبق، وأفضلُ ما في النسخة.

`THE_TALLY_IS_RIGHT_BY_TWO_CANCELLING_ERRORS`: و«٨ + ٢ + ٢٨ + ٩ + ١١ + ٧ =
٦٥» صحيحةُ الجمع، وفيها عطلان **يتقاصّان**: «٩» صُحِّحت إلى **١٢** منذ
دورتين ولم تُحدَّث (ناقصٌ ٣)؛ والنصُّ نفسُه يقول إنّ **ثلاثًا من السبعة هي
مبنيّاتُ الإحالة الـ٢٨ نفسُها** — فالجمعُ يُضاعِفها (زائدٌ ٣). والمصحَّح
`8+2+28+12+11+7−3` = **٦٥** أيضًا. فالرقمُ صحيحٌ **لا بحساب**، وصحّةُ
النتيجة مع فساد الطريق ليست تحقّقًا.

`AND_THE_SUM_MIXES_MEMBERS_WITH_CLASSES`: والأخطر أنّ المجموع يخلط
**أفرادًا بأصناف**: ٨ و٢ و٢٨ و١٢ أفرادٌ معدودة، و١١ (مواضعُ وأدوارٌ ونسب)
و٧ (المعارف) **أصنافٌ**. فعددٌ بلا وحدةٍ واحدة — وهو عطلُ الوحدات في
صورته الرابعة بعد: خلطِ بتٍّ بعدّ، وجمعٍ في وحدةٍ لا تُجمَع، وΔ بلا طبقة.

`A_WITNESS_TRUE_OF_EVERY_NOUN_DISTINGUISHES_NONE`: و«اليومُ جميلٌ / جئتُ
اليومَ» شاهدٌ صحيحُ الوصف **عديمُ التمييز**: «الرجلُ جميلٌ / رأيتُ الرجلَ»،
«البيتُ جميلٌ / رأيتُ البيتَ». فالتبديلُ يقع في **كلّ اسمٍ معرب** — وهو
**تعريفُ الإعراب** لا خبرٌ عن الزمن. فلا يُبنى عليه «النصبُ موضعُ الزمن
المحمول».

`AND_TWO_RAFS_ARE_NOT_ONE_PHENOMENON`: و«الرفعُ علامةُ الإفادة الحرّة»
يجمع رفعَ المبتدأ (اسميّ) ورفعَ المضارع (فعليّ) تحت اسمٍ واحد — وهو
**الصورةُ الثالثةُ** من عطل «٤ = ٤»: اشتراكُ الاسم لا يُثبِت اتّحادَ
الظاهرة. و«لا عاملَ في الابتداء» **مذهبٌ** (والبصريّون يجعلونه عاملًا
معنويًّا)، فيُعلَن فرضًا لا يُساق واقعًا.

`F13_IS_REFUTED_BY_ITS_AUTHORS_OWN_LIST_OF_FOUR`: وF13 — «إعادةُ تعيين
موضع الحالة **مع حفظ موضع الحامل**» — يصدق في **كان** و**كاد**، و**ينقلب
في إنّ** (الاسمُ منصوبٌ والخبرُ مرفوع)، و**يسقط في ظنّ** (كلاهما منصوب).
والأربعةُ هي النواسخُ التي سمّاها الكاتبُ نفسُه في دورةٍ سابقة — فالنقضُ
من جرده هو. والصحيحُ: القاعدةُ لـ**كان وأخواتها** لا للنواسخ عامّةً.
"""

from __future__ import annotations

TALLY = {
    "ربط": 8,
    "استفهام": 2,
    "إحالة": 28,
    "علامات": 9,
    "مواضع+أدوار+نسب": 11,
    "معارف": 7,
}
CORRECTED_MARKERS = 12
OVERLAP = 3
MEMBERS = ("ربط", "استفهام", "إحالة", "علامات")
CLASSES = ("مواضع+أدوار+نسب", "معارف")
NASIKH = {
    "كان": ("مرفوع", "منصوب"),
    "كاد": ("مرفوع", "منصوب"),
    "إنّ": ("منصوب", "مرفوع"),
    "ظنّ": ("منصوب", "منصوب"),
}


def test_the_published_total_is_right_by_two_cancelling_errors() -> None:
    """٦٥ بجمعهم، و٦٥ بالمصحَّح — والطريقان مختلفان."""

    assert sum(TALLY.values()) == 65
    repaired = sum(TALLY.values()) - TALLY["علامات"] + CORRECTED_MARKERS - OVERLAP
    assert repaired == 65
    # والعطلان متساويان في المقدار متعاكسان في الجهة
    assert CORRECTED_MARKERS - TALLY["علامات"] == OVERLAP == 3


def test_the_sum_adds_members_to_classes() -> None:
    """٨ و٢ و٢٨ و١٢ أفراد، و١١ و٧ أصناف — فالمجموعُ بلا وحدة."""

    assert set(MEMBERS) | set(CLASSES) == set(TALLY)
    assert not set(MEMBERS) & set(CLASSES)
    assert sum(TALLY[one] for one in CLASSES) == 18
    assert len(MEMBERS) == 4 and len(CLASSES) == 2


def test_the_time_noun_witness_holds_of_every_inflected_noun() -> None:
    """التبديلُ في كلّ اسمٍ معرب — فالشاهدُ لا يميّز الزمن."""

    nouns = ("اليوم", "الرجل", "الكتاب", "البيت")
    raised = {f"{one}ُ جميلٌ" for one in nouns}
    lowered = {f"رأيتُ {one}َ" for one in nouns}
    assert len(raised) == len(lowered) == len(nouns)
    time_nouns = {"اليوم"}
    assert time_nouns < set(nouns)  # جزءٌ منها، والحكمُ يعمّها
    assert len(set(nouns) - time_nouns) == 3


def test_f13_holds_for_kana_inverts_for_inna_and_fails_for_zanna() -> None:
    """المحفوظُ اثنان من أربعة — والأربعةُ جردُ الكاتب نفسِه."""

    preserved = [one for one, (carrier, _) in NASIKH.items() if carrier == "مرفوع"]
    assert sorted(preserved) == sorted(["كان", "كاد"])
    assert NASIKH["إنّ"] == ("منصوب", "مرفوع")  # مقلوب
    assert NASIKH["ظنّ"] == ("منصوب", "منصوب")  # كلاهما تبدّل
    assert len(preserved) == 2 < len(NASIKH)


def test_two_raf_positions_are_not_shown_to_be_one_phenomenon() -> None:
    """رفعُ المبتدأ اسميّ ورفعُ المضارع فعليّ — واشتراكُ الاسم ليس اتّحادًا."""

    raf = {"المبتدأ": "اسم", "الخبر": "اسم", "المضارع": "فعل"}
    assert len(set(raf.values())) == 2
    assert raf["المبتدأ"] != raf["المضارع"]
    madhhab = "الابتداءُ عاملٌ معنويّ عند البصريّين"
    assert "عامل" in madhhab  # فـ«لا عامل» مذهبٌ يُعلَن لا واقعٌ يُساق
