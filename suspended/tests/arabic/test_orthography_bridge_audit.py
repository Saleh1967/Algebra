"""جسرُ الإملاء: **الأصنافُ مؤكَّدةٌ بالجرد، والسقفُ يسقط ثالثةً، و٢٤٨ تُناقض ما بُنيت عليه**.

**لا مرفقَ ورد**، فالمقيسُ هو المنقولُ في الرسالة؛ وج5 **غيرُ قابلٍ
للتشغيل ههنا** لأنّ قواعدَ التصنيف في المداخل الواحدِ والثلاثين، وهي في
الوثيقة لا في الرسالة — فتُوسَم `UNRUN` وتُصنَّف ولا تُصفَّر.

`THE_BARE_POSITIONS_ARE_CLASSES_NOT_NOISE_AND_THAT_IS_NOW_MEASURED`: ويُقرّ
أوّلًا وأقواه — الدعوى **مؤكَّدةٌ بالعدّ**: من ٨٠٬٤٧٧ عُريًا، **٦٠٬٨٨٧
(٠٫٧٥٦٦) على حروف المدّ الثلاثة** ا (٤٠٬٨١٨) و (١٠٬٠٨٠) ي (٩٬٩٨٩)؛
والتاليان **ل (٦٬٢٠٣)** و**ن (٥٬٦٠٢)** — ولامُ التعريف المدغمةُ ونونُ
التوكيد أصنافٌ تُسمّى كما سُمّيت الأولى. فالعُري **ليست موزَّعةً عشواء**،
وهذه أوّلُ دعوى بنيويّةٍ في السلسلة **يؤكّدها جردٌ لم تطلبه**.

`AND_THE_CARRIED_MADD_IS_DETERMINED_TO_TWO_THOUSANDTHS_OF_A_BIT`: ودعوى
«صفرِ بتٍّ شرطيّ» لألف المدّ **تصمد مقيسةً**: ألفٌ بعد فتحةٍ في **٢٥٬٥١٣**
موضعًا، و`H(حالة) = ٠٫٠٠٢٢ بت`، والعُري **٠٫٩٩٩٨** منها. والشاذُّ **أربعةُ
مواضعَ باسمها**: ألفُ التنوين. فالصوابُ «**٠٫٠٠٢٢ مقيسةً بأربعة شواذَّ
مسمّاة**» لا «صفرٌ بالبناء» — والمقيسُ أقوى من المُدَّعى، لأنّه يحمل شاذَّه.

`BUT_248_CONTRADICTS_THE_RUN_IT_IS_BUILT_ON`: و«الفضاءُ يثبت **٢٤٨**»
تُناقض التشغيلَ الذي تستند إليه: الصفرُ في `dd8d366` خرج على **٣٢ × ٨ =
٢٥٦**، والثانيةُ والثلاثون هي **الهمزةُ حرفًا** بنصّ R2. ولو أُسقطت لصار
الساقطُ **١٧٬٦٥٦** (٩٬١١٥ أ + ٥٬١٠٨ إ + ١٬٥٧٨ ء + ١٬١٨٢ ئ + ٦٧٣ ؤ) بدل
الصفر. فإمّا ٢٥٦ ومعها الصفر، وإمّا ٢٤٨ وقد سقط الصفرُ معها.

`AND_LOG_TWO_OF_THREE_IS_A_CEILING_BELOW_ITS_MEASUREMENT_AGAIN`: و«سقفُها
النظريُّ log₂(3) = ١٫٥٨٥٠» **دون المقيس**: على **أواخر الكلم وحدَها**
`H(حالة|حرف) = ١٫٧٣٨٥`. وعلّتُه أنّ آخرَ الكلمة ليس خيارًا ثلاثيًّا: حركةٌ
× (منوَّن/غيرُ منوَّن) مع السكون والعُري **ثمانيةُ احتمالات**، فسقفُه
**log₂(8) = ٣٫٠٠٠٠**. وهذه **ثالثُ مرّةٍ** يُنشَر فيها سقفٌ أدنى من مقيسه
بعد log₂(196) وقبلَه — والعطلُ واحد: سقفُ فضاءٍ مُتخيَّلٍ يُسنَد إلى فضاءٍ
واقع.

`AND_THE_ENDINGS_CARRY_A_FIFTH_OF_THE_GAP_NOT_THE_GAP`: والأثمنُ: «الفجوةُ
هناك هي Δضبط **بعينها**» **تسقط بالعدّ**. أواخرُ الكلم ٧٨٬٢٤٥ موضعًا
بـ١٫٧٣٨٥ بتًّا = ١٣٦٬٠٢٨ بتًّا؛ وكلُّ المواضع ٣٣٢٬٨٣٧ بـ١٫٩٥١٨ = ٦٤٩٬٦٣٢.
فنصيبُ الأواخر **٠٫٢٠٩٤** — **خُمسٌ لا كلّ**. بل الموضعُ الأخيرُ **أقلُّ**
إفادةً من متوسّط المواضع (١٫٧٣٨٥ < ١٫٩٥١٨): **فأكثرُ الضبط في جوف الكلمة
لا في آخرها**، والإعرابُ ليس موضعَ الدَّين بل خُمسُه.

`AND_THE_CLASSES_ARE_COUNTED_FOUR_AND_FIVE_AND_SIX_IN_ONE_PAGE`: والأصنافُ
تُعَدّ ثلاثَ مرّاتٍ بثلاثة أعداد: **أربعةٌ** في وصف الحالة (ظاهرة/مدّ/مضمَر/
بناء)، و**خمسةٌ** في البرهان («الأصناف الخمسة المغلقة»)، و**ستّةٌ** في
ماركوف (وlog₂(6) = ٢٫٥٨٥٠ يثبّتها)، و**أربعةٌ** في ج5 (م/ض/ب/ص). فعطلُ
العدّ في صورته المألوفة، في وثيقةٍ انضباطُها المعلن «لا عدَّ مُعلَنًا غيرَ
معروض».

`AND_THE_ENTRY_COUNT_ITSELF_IS_EXHIBITED_AND_ADDS_UP`: ويُقرَّ بالمقابل:
٤ + ٤ + ٦ + ١٢ + ٥ = **٣١** — جمعٌ صحيحٌ **ومعروضٌ سطرًا سطرًا** بشهادة
الرسالة. فالبندُ السابعُ طُبِّق حيث أُعلن، وخولف حيث عُدَّت الأصناف.
"""

from __future__ import annotations

import importlib.util
import math
import sys
from fractions import Fraction
from pathlib import Path

from frozen_corpus import CORPUS, requires_corpus

REPOSITORY = Path(__file__).resolve().parents[2]
READER = REPOSITORY / "examples" / "rasm" / "run_bare_census.py"

pytestmark = requires_corpus

BARE = 80_477
MADD_SHARE = 0.7566
ALIF_AFTER_FATHA = 25_513
ALIF_ENTROPY = 0.0022
ALL_POSITIONS = 332_837
FINAL_POSITIONS = 78_245
ALL_GAP = 1.9518
FINAL_GAP = 1.7385
FINAL_SHARE = 0.2094
SPACE_WITHOUT_HAMZA_LOSES = 17_656
CLASS_COUNTS = {"وصفُ الحالة": 4, "البرهان": 5, "ماركوف": 6, "ج5": 4}
ENTRIES = (4, 4, 6, 12, 5)


def _reader() -> object:
    spec = importlib.util.spec_from_file_location("run_bare_census", READER)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


def _units() -> list[tuple[str, str]]:
    reader = _reader()
    audit = reader._audit()  # type: ignore[attr-defined]
    text = CORPUS.read_text(encoding="utf-8").replace("<sel>", " ")
    return audit.rasm_units(text)  # type: ignore[attr-defined,no-any-return]


def test_the_bare_positions_concentrate_on_the_letters_of_madd() -> None:
    """ثلاثةُ أرباعِ العُري على ا و ي — فهي أصنافٌ لا عشواء."""

    reader = _reader()
    census = reader.bare_census(_units())  # type: ignore[attr-defined]
    assert sum(census.values()) == BARE
    madd = sum(census[letter] for letter in "اوي")
    assert abs(madd / BARE - MADD_SHARE) < 5e-4
    assert census["ا"] == 40_818
    assert census["ل"] == 6_203 and census["ن"] == 5_602  # وصنفان يُسمّيان


def test_the_carried_madd_is_determined_to_two_thousandths_of_a_bit() -> None:
    """ألفٌ بعد فتحة: ٠٫٠٠٢٢ بت، وأربعةُ شواذَّ هي ألفُ التنوين."""

    reader = _reader()
    alif = reader.after_fatha(_units(), "ا")  # type: ignore[attr-defined]
    assert sum(alif.values()) == ALIF_AFTER_FATHA
    assert abs(reader.entropy(alif) - ALIF_ENTROPY) < 5e-4  # type: ignore[attr-defined]
    assert alif[""] == 25_509
    odd = {state: number for state, number in alif.items() if state}
    assert odd == {"ً": 4}  # مسمًّى: ألفُ التنوين
    assert reader.entropy(alif) > 0  # type: ignore[attr-defined]  # فليس صفرًا بالبناء


def test_the_two_hundred_forty_eight_space_contradicts_the_zero_fallout() -> None:
    """٢٤٨ تُسقِط الهمزةَ حرفًا، فيصير الساقطُ ١٧٬٦٥٦ بدل الصفر."""

    reader = _reader()
    audit = reader._audit()  # type: ignore[attr-defined]
    text = CORPUS.read_text(encoding="utf-8").replace("<sel>", " ")
    units = audit.emit(text)  # type: ignore[attr-defined]
    without = {one for one in audit.DECLARED_LETTERS if one != "ء"}  # type: ignore[attr-defined]
    assert len(without) == 31
    lost = sum(
        1
        for letter, state in units
        if letter not in without or state not in audit.DECLARED_STATES  # type: ignore[attr-defined]
    )
    assert lost == SPACE_WITHOUT_HAMZA_LOSES
    assert 31 * 8 == 248 and 32 * 8 == 256


def test_the_declared_ceiling_falls_below_its_measurement_a_third_time() -> None:
    """log₂(3) = ١٫٥٨٥٠ والمقيسُ على الأواخر ١٫٧٣٨٥، والسقفُ الحقُّ ٣٫٠٠٠٠."""

    reader = _reader()
    text = CORPUS.read_text(encoding="utf-8").replace("<sel>", " ")
    finals = reader.final_units(text)  # type: ignore[attr-defined]
    assert len(finals) == FINAL_POSITIONS
    measured = reader.conditional(finals)  # type: ignore[attr-defined]
    assert abs(measured - FINAL_GAP) < 5e-4
    assert math.log2(3) < measured < math.log2(8)
    # وهي ثالثةُ مرّة: log2(196) كان دون ٦٫٢٨١٩ في سقف الأبجديّة الواقعة
    assert math.log2(196) < 8.4471


def test_the_endings_carry_a_fifth_of_the_gap_not_all_of_it() -> None:
    """١٣٦٬٠٢٨ بتًّا من ٦٤٩٬٦٣٢ — والموضعُ الأخيرُ أقلُّ إفادةً من المتوسّط."""

    reader = _reader()
    text = CORPUS.read_text(encoding="utf-8").replace("<sel>", " ")
    units = _units()
    finals = reader.final_units(text)  # type: ignore[attr-defined]
    whole = reader.conditional(units) * len(units)  # type: ignore[attr-defined]
    ending = reader.conditional(finals) * len(finals)  # type: ignore[attr-defined]
    assert abs(ending / whole - FINAL_SHARE) < 5e-4
    assert Fraction(20, 100) < Fraction(int(ending / whole * 10_000), 10_000)
    assert FINAL_GAP < ALL_GAP  # فأكثرُ الضبط في جوف الكلمة


def test_the_classes_are_counted_three_ways_in_one_page() -> None:
    """أربعةٌ وخمسةٌ وستّة — ولog₂(6) يثبّت الستّة فليست سهوَ كتابة."""

    assert set(CLASS_COUNTS.values()) == {4, 5, 6}
    assert abs(math.log2(6) - 2.5850) < 5e-4
    assert CLASS_COUNTS["وصفُ الحالة"] == CLASS_COUNTS["ج5"] == 4
    assert sum(ENTRIES) == 31  # والجمعُ المعروضُ صحيح


def test_the_classifier_is_unrun_not_zero() -> None:
    """ج5 يُبَتّ بالعدّ — والقواعدُ ليست ههنا، فتُصنَّف ولا تُقدَّر."""

    deposit = REPOSITORY / "deposits" / "orthography_bridge.md"
    assert not deposit.exists()  # لم تَرِد الوثيقة
    assert BARE == 80_477  # والمادّةُ حاضرةٌ متى وردت القواعد
