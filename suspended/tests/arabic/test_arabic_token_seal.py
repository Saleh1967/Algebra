"""**ختمٌ قبل النظر**: حدُّ اللفظ مُصحَّحًا — إعادةُ ختم `7773c03f…`.

**لم يُشغَّل شيءٌ بعد.**

**الخللُ المُصحَّح**: في `7773c03f…` كتبتُ حدَّ اللفظ «**أطولُ متتاليةٍ بلا
فراغ**»، **ووسمُ الترقيم في المدوّنة متتاليةٌ بلا فراغ**. فدخل **٤٬٢٨٧**
لفظًا ليس فيها حرفٌ عربيٌّ واحدٌ — **٥٫٢٪ من الألفاظ** — في كلّ عدٍّ هناك:
في حقل الحال، وفي حروف الخاتمة، وفي سلسلة ماركوف. وظهر ذنَبُ الوسم `>`
في جدول «حروفٍ لا تحمل حالًا» **كأنّه حرفُ خاتمة**.

**والتصحيح**: اللفظُ متتاليةٌ بلا فراغٍ **فيها محرفٌ واحدٌ على الأقلّ اسمُه
في يونيكود يبدأ بـ`ARABIC`**. وما سواها يُسقَط **ويُعَدُّ ويُطبَع** ولا
يُبتلَع.

**والسجلُّ الأوّلُ يبقى كما هو**: لا يُحذَف ولا يُعاد تفسيرُه، **والشرطُ
التاسعُ ساقطٌ ويبقى ساقطًا**. وإنّما يُقابَل السجلّان.

**وههنا فرقٌ يجب أن يُقال قبل النظر**: من شروط هذا الختم ما هو **نتيجةُ
حسابٍ يمكن أن يُجرى على السجلّ الأوّل بلا تشغيل** — فليس تنبّؤًا، وإنّما
**فحصٌ أنّ التصحيحَ فعل ما يجب وحدَه**. وهي: **ط٢ وط٣ وط١٠ وط١١**.
**وما لا يُعلَم إلّا بالتشغيل**: **ط٦ وط٧ وط٨ وط٩ وط١٢** — لأنّ إسقاطَ
الوسم **يَصِل جارَين كانا مفصولين**، فتتبدّل السلسلةُ تبدّلًا لا يُحسَب
بالطرح. **وهذا التمييزُ مكتوبٌ قبل النظر كي لا يُدَّعى التنبّؤُ لما هو
طرحٌ.**

**وطرفا المبرهنتين لا يُؤخَذان من أوّل الحلقة**: في `7773c03f…` مرَّ ح٣
وح٤ **بطرفين تافهين** يقعان حيث الحقلُ خانةٌ واحدة. **فالشرطان ههنا
يُؤخَذان بعد ألفِ لفظ**، حيث تشهد المبرهنتان شهادةً غيرَ خاوية.

**ولا اسمَ بابٍ نحويٍّ يدخل**: علاماتٌ ومواضعُ وبتّات. والأصليّةُ
والفرعيّةُ والمبنيُّ والمعربُ **خلوٌّ مُصنَّفٌ** كما في الختم الأوّل.
"""

