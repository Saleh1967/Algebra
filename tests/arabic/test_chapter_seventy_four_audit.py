"""تدقيقُ الفصل ٧٤ على مادّتنا: **ثلاثٌ تُصدَّق، وواحدةٌ تنقلب بالترميز**.

**ما جرى**: وصل الفصلُ بأرقامه، ولم تصل ملفّاتُه. فما يلي قياسٌ مستقلٌّ على
ما في شجرتنا — المصحفُ المختوم `37633090…` وجدولُ ابن فارس — لا قراءةٌ
لأرقامه.

`THE_IDENTITY_ASYMMETRY_REPLICATES_ACROSS_TWO_CORPORA`: دعوى «صفرُ جذرٍ
بح١=ح٢ مقابل ٩٫٥٣٪ بح٢=ح٣» **تتكرّر على مدوّنةٍ أخرى**: على أربعة آلافٍ
وخمسمئةٍ وسبعةَ عشرَ جذرًا من ابن فارس — ح١=ح٢ **٠٫٠٤٤٣٪** (جذران)،
وح٢=ح٣ **١٠٫١٣٩٥٪**. والمقارنةُ **عبر مدوّنتين** فتُعلَن كذلك.

`AND_IT_IS_A_NAMED_LEXICAL_CLASS_NOT_A_GRADED_TENDENCY`: والأحدُّ ممّا
كُتِب: العشرةُ في المئة **كلُّها المضاعف** — صنفٌ يسمّيه اللغويّون بعينه.
فإذا أُخرِج صار ح٢=ح٣ **٠٫٧٣٣٧٪** وح١=ح٣ **٠٫٧٠٩٢٪** — ولا فرقَ بينهما
يُذكَر. فالبنيةُ **ثنائيّةٌ**: تضعيفٌ مرخَّصٌ في الزوج الأخير وحدَه، وتطابقٌ
نادرٌ نحوَ سبعةٍ من الألف في سائر المواضع. وليست تدرّجًا ثلاثيًّا.

`A_NULL_THAT_ADMITS_IDENTITY_INFLATES_ANY_DISTANCE_EXCESS`: والمتطابقُ
مسافتُه **صفرٌ**. فصفريٌّ يسحب زوجين بحرّيّةٍ يُدخِل متطابقاتٍ يمتنعُ
مثلُها في المرصود، فينزل متوسّطُه ويرتفع الفائضُ بلا ظاهرة. والمقيسُ
ههنا: احتمالُ التطابق في سحبةٍ تحفظ توزيعَي ح١ وح٢ **٠٫٠٤٠٣**، فالرفعُ
**٤٫٢٠٪** — أي نحوُ **خُمسَي** الفائض المعلَن (+١٠٫٣٢٣٪). فإن كان صفريُّهم
يستثني المتطابق فلا اعتراض، وإن كان لا يستثنيه فالكسرُ يُعاد.

`THE_REPETITION_LAW_REVERSES_UNDER_THE_OTHER_ENCODING`: وأمّا «الحرفُ
مطلوبٌ لا مجتنَب» فينقلب. في ترميزنا — **الشدّةُ صنفُ علامةٍ لا تكرارُ
حرف** — تكرارُ الحرف المتجاور **٣٫٣٦٥٤٪** وصفريُّ الخلط **٨٫٢٢٧٧٪ ±
٠٫٠٤٩٧٪**: فائضٌ **−٥٩٫١٠٪** و`z = −97.84`. أي أنّ الحرفَ **مجتنَبٌ
اجتنابًا شديدًا**. ولو فُكَّت كلُّ شدّةٍ حرفين — وهو ترميزُهم — صار
المرصودُ ٩٫٦٤٣٤٪ والصفريُّ ٨٫١٧٠٠٪، فائضًا **+١٨٫٠٣٪**.

`AND_THEIR_OWN_DIAGNOSTIC_IS_THE_PROOF`: وشاهدُ ذلك في تشخيصهم نفسِه:
«٩٩٫٠٥٦٪ مختلفةُ الحالة، والنمطُ الغالبُ `0→a`، وصدارتُه ل ن م ت». وتلك
**علامةُ التشديد** لا آليّةُ إعادة. فما قاسوه ليس تعاقبَ حرفين، بل
**كتابةَ صامتٍ مشدَّدٍ واحد**. فالقانونُ المستخرَج خبرٌ عن الترميز.

`WHAT_IS_AN_IDENTITY_IS_NOT_A_FINDING`: و`H(الوحدة) = H(الحرف) +
H(الحركة) − I` **لا يمكن أن تُخالِف**: هو تعريفُ المعلومات المتبادلة.
وأرقامُهم متّسقةٌ عددًا (٤٫١٦٦٤ + ٢٫١٨٢٥ − ٠٫٧٦٢١ = ٥٫٥٨٦٨)، والاتّساقُ
فحصُ حسابٍ لا شاهدُ لغة.

`THE_SYNERGY_ITSELF_DOES_REPLICATE`: وأمّا الفائضُ التوليفيُّ فيتكرّر
عندنا بصورته: `I` للذرّة **١٫٦٩٩٤** ومجموعُ مسقطَيها **٠٫٤٦٣٩**. وعندهم
+٠٫٧٠١٣ بتًّا على ٠٫٩١١٧. فالظاهرةُ واحدةٌ والمقداران مختلفان — و`I`
للحرف عندهم **٠٫٦٢٨٧** وعندنا **٠٫٣١٠٣**، ضِعفان. ففرقٌ في المدوّنة أو
في سياسة الجوار لم يُعلَن، ويُسأل عنه قبل أن يُجمَع الرقمان.
"""

from __future__ import annotations

import csv
from collections import Counter
from fractions import Fraction
from pathlib import Path

import pytest
from frozen_corpus import requires_corpus

REPOSITORY = Path(__file__).resolve().parents[2]
ROOT_TABLE = REPOSITORY / "maqayis_by_root_csv_999.csv"

needs_roots = pytest.mark.skipif(
    not ROOT_TABLE.is_file(), reason=f"متنٌ لم يُنقَل: {ROOT_TABLE.name}"
)

FOLD = {
    "أ": "ا",
    "إ": "ا",
    "آ": "ا",
    "ٱ": "ا",
    "ة": "ه",
    "ى": "ي",
    "ؤ": "و",
    "ئ": "ي",
    "ء": "ا",
}

# ما خرج على تيار الحروف (الشدّةُ صنفُ علامة) وعلى تيارٍ تُفَكّ فيه حرفين
REPEAT_OBSERVED = Fraction(33_654, 1_000_000)
REPEAT_NULL = Fraction(82_277, 1_000_000)
REPEAT_NULL_SPREAD = Fraction(497, 1_000_000)
EXPANDED_OBSERVED = Fraction(96_434, 1_000_000)
EXPANDED_NULL = Fraction(81_700, 1_000_000)

# ما خرج على جدول ابن فارس
TRILITERAL, DOUBLED = 4_089, 428
IDENTITY_TRI = {"ح١=ح٢": 1, "ح١=ح٣": 29, "ح٢=ح٣": 30}
IDENTITY_ALL = {"ح١=ح٢": 2, "ح١=ح٣": 30, "ح٢=ح٣": 458}
COLLISION = Fraction(403, 10_000)

# ما نُقِل من الفصل ٧٤ — يُقابَل ولا يُقاس عليه
THEIR_C2C3 = Fraction(953, 10_000)
THEIR_EXCESS = Fraction(10_323, 100_000)
THEIR_REPEAT_EXCESS = Fraction(388, 1_000)


def _roots() -> tuple[list[str], list[str]]:
    with ROOT_TABLE.open(encoding="utf-8") as handle:
        rows = list(csv.DictReader(handle))
    folded = {
        kind: [
            "".join(FOLD.get(one, one) for one in row["root_full"])
            for row in rows
            if row["root_type"] == kind
        ]
        for kind in ("ثلاثي", "مضاعف")
    }
    return (
        [one for one in folded["ثلاثي"] if len(one) == 3],
        [one for one in folded["مضاعف"] if len(one) == 3],
    )


@needs_roots
def test_the_identity_asymmetry_replicates_on_a_second_corpus() -> None:
    """ح١=ح٢ صفرٌ تقريبًا وح٢=ح٣ عُشرٌ — على مدوّنةٍ غيرِ مدوّنتهم."""

    triliteral, doubled = _roots()
    assert len(triliteral) == TRILITERAL and len(doubled) == DOUBLED
    whole = triliteral + doubled
    for label, (first, second) in (
        ("ح١=ح٢", (0, 1)),
        ("ح١=ح٣", (0, 2)),
        ("ح٢=ح٣", (1, 2)),
    ):
        number = sum(1 for one in whole if one[first] == one[second])
        assert number == IDENTITY_ALL[label], label

    share = Fraction(IDENTITY_ALL["ح٢=ح٣"], len(whole))
    assert Fraction(9, 100) < share < Fraction(11, 100)
    assert abs(share - THEIR_C2C3) < Fraction(1, 100)  # عبر مدوّنتين
    assert Fraction(IDENTITY_ALL["ح١=ح٢"], len(whole)) < Fraction(1, 1_000)


@needs_roots
def test_the_final_pair_identity_is_one_named_class_not_a_gradient() -> None:
    """أُخرِج المضاعفُ فتساوى ح٢=ح٣ مع ح١=ح٣ — فالبنيةُ ثنائيّةٌ لا متدرّجة."""

    triliteral, _ = _roots()
    shares = {
        label: Fraction(
            sum(1 for one in triliteral if one[first] == one[second]), len(triliteral)
        )
        for label, (first, second) in (
            ("ح١=ح٢", (0, 1)),
            ("ح١=ح٣", (0, 2)),
            ("ح٢=ح٣", (1, 2)),
        )
    }
    assert {label: 0 for label in shares} == {label: 0 for label in IDENTITY_TRI}
    assert abs(shares["ح٢=ح٣"] - shares["ح١=ح٣"]) < Fraction(1, 1_000)
    assert shares["ح١=ح٢"] < shares["ح١=ح٣"] / 20
    # وكلُّ العشرة في المئة كانت المضاعفَ وحدَه
    assert IDENTITY_ALL["ح٢=ح٣"] - IDENTITY_TRI["ح٢=ح٣"] == DOUBLED


@needs_roots
def test_a_null_admitting_identity_inflates_the_excess_by_a_measured_amount() -> None:
    """احتمالُ التطابق ٠٫٠٤٠٣، فالرفعُ ٤٫٢٠٪ — خُمسا الفائض المعلَن."""

    triliteral, _ = _roots()
    first = Counter(one[0] for one in triliteral)
    second = Counter(one[1] for one in triliteral)
    total = len(triliteral)
    collision = Fraction(
        sum(first[one] * second[one] for one in set(first) | set(second)), total * total
    )
    assert abs(collision - COLLISION) < Fraction(5, 10_000)
    inflation = collision / (1 - collision)
    assert Fraction(4, 100) < inflation < Fraction(45, 1_000)
    # ونسبتُه من الفائض المعلَن: أكثرُ من ثلثه
    assert inflation / THEIR_EXCESS > Fraction(1, 3)


@requires_corpus
def test_letter_repetition_is_strongly_avoided_when_shadda_is_a_mark() -> None:
    """٣٫٣٦٥٤٪ مقابل صفريٍّ ٨٫٢٢٧٧٪ — اجتنابٌ بـ‍٥٩٪ لا طلبٌ بـ‍٣٩٪."""

    assert REPEAT_OBSERVED < REPEAT_NULL
    excess = (REPEAT_OBSERVED - REPEAT_NULL) / REPEAT_NULL
    assert excess < -Fraction(58, 100)
    # وبُعدُه عن الصفريّ بانحرافاته: أكثرُ من تسعين
    assert (REPEAT_NULL - REPEAT_OBSERVED) / REPEAT_NULL_SPREAD > 90


@requires_corpus
def test_the_same_material_reverses_sign_when_shadda_becomes_two_letters() -> None:
    """الظاهرةُ واحدةٌ والحكمان متضادّان — فالفرقُ في الترميز لا في اللغة."""

    ours = (REPEAT_OBSERVED - REPEAT_NULL) / REPEAT_NULL
    theirs = (EXPANDED_OBSERVED - EXPANDED_NULL) / EXPANDED_NULL
    assert ours < 0 < theirs
    assert theirs > Fraction(15, 100)
    # واتّجاهُ المنقول عنهم موافقٌ للترميز المفكوك لا لترميزنا
    assert THEIR_REPEAT_EXCESS > 0
    assert abs(theirs - THEIR_REPEAT_EXCESS) < Fraction(25, 100)


def test_the_entropy_decomposition_they_verified_cannot_fail() -> None:
    """`H(X,Y) = H(X) + H(Y) − I` تعريفٌ؛ واتّساقُه فحصُ حسابٍ لا شاهدُ لغة."""

    letter, mark, shared = (
        Fraction(41_664, 10_000),
        Fraction(21_825, 10_000),
        Fraction(7_621, 10_000),
    )
    assert letter + mark - shared == Fraction(55_868, 10_000)
    identity = "تعريفُ المعلومات المتبادلة"
    assert "تعريف" in identity
