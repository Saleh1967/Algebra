DIGEST = "c46dfbe33e05a4dfd7e1ecc33f3e59e147b71eaad0379396d0d97469b6e4cc3c"
"""يُثبَّت بعد أوّل اشتقاق، ولا يُمَسّ بعدَه."""


def test_the_seal_is_recomputed_from_the_written_conditions() -> None:
    """البصمةُ تُشتَقّ من الشروط لا تُنقَل."""

    assert seal(ORACLE, PREDICTIONS) == DIGEST


def test_the_prior_sight_of_the_output_is_declared_not_hidden() -> None:
    """رأيتُ المخرَجَ قبل الختم، وذلك مكتوبٌ في متنه — ولا أدّعي غيرَه."""

    assert __doc__ is not None
    assert "فرأيتُ مخرَجَها" in __doc__
    assert "ليس تسجيلًا سابقًا" in __doc__
    assert "منقولةٌ من" in __doc__


def test_every_threshold_is_borrowed_from_the_claim_it_tests() -> None:
    """الحدُّ مكتوبٌ في دعوى الخصم: نصفٌ للغلبة، وصفرٌ للصفر، و٠٫٣٠ للضغط."""

    by_name = {one.identifier: one for one in PREDICTIONS}
    assert by_name["ش٣"].threshold == Fraction(1, 2)
    assert by_name["ش٤"].threshold == Fraction(1, 2)
    assert by_name["ش٥"].threshold == Fraction(0)
    assert by_name["ش٦"].threshold == Fraction(3, 10)
    assert by_name["ش٥"].direction is Direction.AT_MOST
    assert by_name["ش٦"].direction is Direction.AT_MOST


def test_the_counter_of_the_conditional_zero_does_not_name_the_weak() -> None:
    """عدّادُ ش٥ لا يذكر العلّةَ في شرطه — وإلّا فالصفرُ من الشرط لا البايتات."""

    assert "لا يذكر العلّةَ في شرطه" in ORACLE.extraction
    intruders = next(one for one in PREDICTIONS if one.identifier == "ش٥")
    assert "مشتقًّا من المُرشِّح لا من البايتات" in intruders.falsifies


def test_the_deletion_is_one_of_four_declared_before_any_count() -> None:
    """∅ في فضاء الشاهد المُعلَن قبل العدّ، لا يُضاف بعد رؤية الرقم."""

    assert "(ا و ي ∅)" in ORACLE.extraction
    assert "قبل العدّ" in ORACLE.extraction
    assert len(PREDICTIONS) == 7
