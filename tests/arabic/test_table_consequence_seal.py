def test_six_refute_the_machine_and_six_are_consequences_of_the_table() -> None:
    """ستٌّ تردُّ الآلةَ، وستٌّ **لوازمُ الجدول** لا دعاوٍ لي."""

    machine = {"ج١", "ج٢", "ج٣", "ج٤", "ج٥", "ج١٢"}
    consequences = {one.identifier for one in PREDICTIONS} - machine
    assert consequences == {"ج٦", "ج٧", "ج٨", "ج٩", "ج١٠", "ج١١"}
    for one in PREDICTIONS:
        if one.identifier in consequences:
            assert "لازم" in one.falsifies, one.identifier
            assert "الجدول" in one.falsifies, one.identifier
