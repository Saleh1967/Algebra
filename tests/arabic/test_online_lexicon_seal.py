"""**ختمٌ قبل النظر**: بناءُ المعجم فوريًّا (online) — هل الخوارزميةُ الفوريّةُ
تنافسيّة؟

**لم يُعَدّ شيءٌ بهذا الشرط بعد.**

**العِلّة**: سأل صاحبُ المستودع: إذا بُنيت اللغةُ من الوحدات الـ112 أو من الصفر،
عنصرًا بعد عنصرٍ
كالترتيب بالإدراج، فكيف يكون الحلّ، وهل هو تنافسيّ؟ وفي ختم 9390b473 كان قرارُ العامل
فوريًّا أمثل (يُحسم عند وصول اللفظ التالي)، وسقط قرارُ «هنا ضمير» (٠٫٤٧١٥) لأنّه
يحتاج علمًا لا يراه
الاختيارُ المحلّيّ: الوضع. **فالسؤالُ هنا**: إذا بُني ذلك العلمُ (المعجم) فوريًّا من
الألفاظ
التي مرّت وحدها، فكم يبلغ من المعجم الكامل الذي يرى المصحفَ كلّه؟

**القرار**: ضميرٌ في آخر الاسم أم لا، وأيُّها — بمعجم: يُختار أطولُ ضميرٍ من ضمائر
الجدول
الموقَّع يبقى قبله جذعٌ **ورد في المعجم لفظًا تامًّا**؛ وإن لم يوجد فلا ضمير.
- **غيرُ الفوريّ**: المعجمُ هياكلُ ألفاظ المصحف كلّه.
- **الفوريّ**: المعجمُ هياكلُ الألفاظ التي سبقت هذا الموضعَ بترتيب المصحف، لا غير.
- **والحَكَم** QAC، على مجتمع ج١ في ختم 9390b473 نفسه.

**وتوقّعي بالتفكير**: يرتفع غيرُ الفوريّ كثيرًا فوق ٠٫٤٧١٥؛ والفوريُّ تنافسيٌّ
بنسبةٍ ثابتةٍ
قريبةٍ من الواحد، ويقترب منه في آخر المصحف أكثرَ من أوّله.
"""

from __future__ import annotations

from fractions import Fraction

from algebra.signified import Direction, Oracle, Prediction, seal

ORACLE = Oracle(
    name="المعجمُ الفوريّ وغيرُ الفوريّ لقرار الضمير، والحَكَمُ QAC",
    source=(
        "quran-simple-enhanced.txt — البصمة 37633090…؛ "
        "وdeposits/jarr_exceptions_draft.tsv موقَّعًا؛ "
        "وquran-morphology.txt من mustafa0x/quran-morphology عند 8f38b39"
    ),
    extraction=(
        "المجتمعُ مجتمعُ ج١ في ختم 9390b473 بتعريفه "
        "(الآياتُ المتطابقة، وكلمةُ QAC اسمٌ "
        "ذو حالةٍ بلا فعل، والهيكلُ ينتهي بضميرٍ من ضمائر الجدول أقصرَ منه بحرفين "
        "فأكثر)، والصوابُ أن يساوي الاختيارُ ضميرَ QAC اللاحق (أو لا ضميرَ فيهما). "
        "والهيكلُ skeleton(units(اللفظ)) من run_jazm_zero. والاختيارُ بمعجمٍ L: أطولُ "
        "ضميرٍ p من ضمائر الجدول ينتهي به الهيكلُ ويبقى قبله جذعٌ طولُه حرفان فأكثر "
        "وهو في L؛ وإلّا فلا ضمير. وL غيرُ الفوريّ: هياكلُ ألفاظ المصحف كلّها (بعد طرح "
        "<sel>). وL الفوريّ عند موضعٍ: هياكلُ الألفاظ قبله بترتيب الأسطر ثم الألفاظ. "
        "ف١: حصّةُ صواب غير الفوريّ. ف٢: حصّةُ صواب الفوريّ مقسومةً على حصّة صواب غير "
        "الفوريّ (النسبةُ التنافسيّة). ف٣: تلك النسبةُ "
        "في الربع الأخير من مواضع المجتمع "
        "بترتيبها ناقصًا النسبةَ في الربع الأوّل (والربعُ "
        "بعدد المواضع، والباقي في الأخير)؛ "
        "والعدُّ على QAC لم يُرَ"
    ),
)

PREDICTIONS = (
    Prediction(
        identifier="ف١",
        statistic="حصّةُ صواب قرار الضمير بالمعجم الكامل",
        threshold=Fraction(17, 20),
        direction=Direction.AT_LEAST,
        falsifies=(
            "أنّ المعجمَ (الوضع) وحده يحسم قرارَ الضمير "
            "الذي أخطأه الاختيارُ المحلّيّ"
        ),
    ),
    Prediction(
        identifier="ف٢",
        statistic="النسبةُ التنافسيّة: صوابُ الفوريّ على صواب غير الفوريّ",
        threshold=Fraction(9, 10),
        direction=Direction.AT_LEAST,
        falsifies="أنّ بناءَ المعجم فوريًّا تنافسيٌّ بنسبةٍ ثابتةٍ قريبةٍ من الواحد",
    ),
    Prediction(
        identifier="ف٣",
        statistic="النسبةُ التنافسيّة في الربع الأخير ناقصًا الربع الأوّل",
        threshold=Fraction(0),
        direction=Direction.AT_LEAST,
        falsifies="أنّ الفوريَّ يتعلّم: يقترب من الأمثل كلّما طال ما مرّ به",
    ),
)

DIGEST = "363ee517cf8fc8e9c74d5271aad26408b78d021cae90dc412ca0bee78f545c89"
"""يُثبَّت بعد أوّل اشتقاق، ولا يُمَسّ بعدَه."""


def test_the_seal_is_recomputed_from_the_written_conditions() -> None:
    """البصمةُ تُشتَقّ من الشروط لا تُنقَل."""

    assert seal(ORACLE, PREDICTIONS) == DIGEST


def test_three_conditions() -> None:
    """ف١ الأمثل، وف٢ التنافس، وف٣ التعلّم."""

    assert [one.identifier for one in PREDICTIONS] == ["ف١", "ف٢", "ف٣"]
    assert "والعدُّ على QAC لم يُرَ" in ORACLE.extraction
