"""**ختمٌ قبل النظر**: الأزواجُ الدنيا — لفظان تتطابق حروفُهما وتختلف حالٌ واحدة.

**لم يُشغَّل شيءٌ بعد.**

**العِلّة**: الوحدةُ الواحدة من الـ١١٢ لا تفيد وحدها (ج٥ في ختم `a581ddb9…`:
لا لفظَ من حرفٍ واحدٍ عليه حركة). لكنّ الحالَ إذا اقترنت بحروفٍ ثابتة قد
تفرّق بين لفظين. فأصغرُ انتقالٍ يُغيّر المعنى تغييرُ حالٍ واحدةٍ والحروفُ
باقية. **وقال صاحبُ المستودع** إنّ هذا التغيير يقع غالبًا في موضعين: **الوحدة
الأخيرة**، أي الإعراب؛ أو **الوحدتين الأوليين**، أي هيئة الفعل وأدوات الربط
(فَعَلَ وفُعِلَ، أَنْ وإِنْ، مَنْ ومِنْ).

**وما رُئي قبل الختم**: توزيعُ الحركات داخل اللفظ وآخرَه (من مقامٍ آخر)،
وختمُ الحركة بعد العامل `c35956ef…`. **ولم يُعَدّ زوجٌ أدنى قطّ.**

- **ز١**: نصيبُ الأزواج التي يقع اختلافُها في الموضعين لا يقلّ عن الثلثين.
- **ز٢**: هذا النصيبُ يزيد بعُشرٍ على الأقلّ على نصيبه لو وقع الاختلافُ في أيّ
  موضعٍ من اللفظ بالتساوي. **فالموضعان الثلاثة يغطّون اللفظ القصير كلَّه**، ولذلك
  لا يكفي ز١ وحده: قد يصدق لأنّ الألفاظ قصيرة لا لأنّ الاختلاف يقصد الموضعين.
"""

from __future__ import annotations

from fractions import Fraction

from algebra.signified import Direction, Oracle, Prediction, seal

ORACLE = Oracle(
    name="الأزواجُ الدنيا: موضعُ الحال الوحيدة المختلفة",
    source="quran-simple-enhanced.txt — البصمة 37633090…",
    extraction=(
        "يُطرح الوسم <sel> فراغًا، واللفظُ ما فصلته الفراغات؛ ويُقشَّر بـ"
        "run_cv_peel.peel وتُطرح الوحداتُ البنيويّة؛ فنمطُ اللفظ متتاليةُ حروفه "
        "ومتتاليةُ أحواله، والأنماطُ المختلفة هي المجتمع؛ والزوجُ الأدنى نمطان "
        "حروفُهما متطابقةٌ عددًا وترتيبًا وأحوالُهما تختلف في موضعٍ واحدٍ فقط؛ "
        "والموضعُ الأخير آخرُ وحدةٍ ليست ذيلَ تنوين؛ والموضعان الأوّلان الوحدةُ "
        "الأولى والثانية؛ والنصيبُ المقيس عددُ الأزواج التي موضعُ اختلافها أحدُ "
        "هذه المواضع على عدد الأزواج؛ والنصيبُ بالتساوي متوسّطُ نسبة المواضع "
        "المسمّاة المتمايزة إلى عدد المواضع الممكنة في كلّ زوج، والممكنةُ "
        "وحداتُ اللفظ عدا ذيل التنوين؛ وتوزيعُ الحركات داخل اللفظ وآخرَه "
        "وختمُ c35956ef رُئيا قبل الختم، والأزواجُ الدنيا لم تُعَدّ"
    ),
)

PREDICTIONS = (
    Prediction(
        identifier="ز١",
        statistic="نصيبُ الأزواج الدنيا التي يقع اختلافُها في الأخير أو الأوّلين",
        threshold=Fraction(2, 3),
        direction=Direction.AT_LEAST,
        falsifies=(
            "قولَ صاحب المستودع إنّ الحالَ المفرِّقة تقع غالبًا في الإعراب أو في "
            "هيئة الفعل: إن لم يبلغ الثلثين فالتفريقُ منتشرٌ في اللفظ"
        ),
    ),
    Prediction(
        identifier="ز٢",
        statistic="النصيبُ المقيس ناقصًا النصيبَ لو وقع الاختلافُ بالتساوي",
        threshold=Fraction(1, 10),
        direction=Direction.AT_LEAST,
        falsifies=(
            "أنّ الموضعين مقصودان: إن لم يزد المقيسُ على التساوي بعُشرٍ فغلبتُهما "
            "أثرُ قِصَر الألفاظ لا قصدُ التفريق"
        ),
    ),
)

DIGEST = "152cd28ece13857f3a93721db4d25125761af06cd61f5448c8aa8ba4c5f89e3d"
"""يُثبَّت بعد أوّل اشتقاق، ولا يُمَسّ بعدَه."""


def test_the_seal_is_recomputed_from_the_written_conditions() -> None:
    """البصمةُ تُشتَقّ من الشروط لا تُنقَل."""

    assert seal(ORACLE, PREDICTIONS) == DIGEST


def test_both_conditions_are_written_with_their_fall() -> None:
    """ز١ وز٢، ولكلٍّ نصُّ سقوط."""

    assert {one.identifier for one in PREDICTIONS} == {"ز١", "ز٢"}
    for one in PREDICTIONS:
        assert one.falsifies.strip()


def test_what_was_seen_before_the_seal_is_declared() -> None:
    """ما رُئي مُعلَن، والأزواجُ لم تُعَدّ."""

    assert "والأزواجُ الدنيا لم تُعَدّ" in ORACLE.extraction
