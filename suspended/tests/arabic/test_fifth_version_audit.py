@requires_corpus
def test_the_reversal_is_attested_outside_the_first_decade() -> None:
    """«تسعٌ وتسعون نعجةً» و«ثلاثَ مائةٍ سنين» — والانعكاسُ عند ٩٩ و٣٠٠."""

