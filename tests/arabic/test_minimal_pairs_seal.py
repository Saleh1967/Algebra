"""**ختمٌ قبل النظر**: الأزواجُ الدنيا — أين يقع اختلافُ الحال الواحد؟

**لم يُعَدّ زوجٌ واحدٌ بعد.**

**العِلّة**: الوحدةُ الواحدة من الـ١١٢ لا تفيد وحدها (ج٥ في ختم `a581ddb9…`
صمد: لا لفظَ من حرفٍ واحدٍ عليه علامة). والإفادةُ تتحقّق من الانتقال المرخَّص:
حرفٌ يقترن بحال، ولفظٌ يقترن بلفظ. **والزوجُ الأدنى** لفظان تتطابق حروفُهما
ويختلفان في حال وحدةٍ واحدةٍ فقط. فهو أصغرُ تجربةٍ يعزل بها العقلُ ما تفيده
الحالُ وحدها: يُمسك الدالَّ كلَّه ثابتًا إلا وحدة، فما تغيّر من المدلول يُنسَب
إليها.

**والدعوى** (من صاحب المستودع): الاختلافُ يقع غالبًا في **الوحدة الأخيرة** —
الإعراب — أو في **الوحدتين الأوليين** — هيئة الفعل (فَعَلَ وفُعِلَ، يَفعل
ويُفعل).

**وفي الدعوى فخّ يُسَدّ قبل العدّ**: في لفظٍ من ثلاث وحداتٍ أو أربع تغطّي
الأوليان والأخيرة المواضعَ كلَّها أو جلَّها، فتصدق الدعوى بالبناء لا بالمادّة.
فالشروطُ على الألفاظ ذات **خمس وحداتٍ فأكثر**، ومعها مقارنةٌ بما يعطيه
الموضعُ وحده لو وقع الاختلافُ في أيّ وحدةٍ بالتساوي.

- **م١**: نصيبُ الأزواج التي يقع اختلافُها في الأولى أو الثانية أو الأخيرة لا
  يقلّ عن ثلاثة أرباع. توقّعتُه بالتفكير قرابةَ ٠٫٨٥.
- **م٢**: ذلك النصيبُ يزيد على ما يعطيه التساوي بخُمسٍ على الأقلّ.
- **م٣**: الوحدةُ الأخيرة **وحدها** أكثرُ المواضع اختلافًا، أي نصيبُها لا يقلّ عن
  نصيب أيّ موضعٍ آخر.

**وما رُئي قبل الختم**: توزيعُ الحركات داخلَ اللفظ وآخرَه (من مقامٍ آخر)،
ونتائجُ ختم `c35956ef…` (الحركة الأخيرة تتبع العامل). **ولم يُرَ شيءٌ عن
الأزواج.**
"""

from __future__ import annotations

from fractions import Fraction

from algebra.signified import Direction, Oracle, Prediction, seal

ORACLE = Oracle(
    name="الأزواجُ الدنيا في الحال — موضعُ الاختلاف",
    source="quran-simple-enhanced.txt — البصمة 37633090…",
    extraction=(
        "يُطرح الوسم <sel> فراغًا، واللفظُ ما فصلته الفراغات؛ ووحداتُه ما يُخرجه "
        "run_cv_peel.peel بعد طرح الوحدات البنيويّة وذيل التنوين، فالتنوينُ حالُ "
        "وحدته والشدّةُ وحدتان والعُريُ سكون؛ ويُعَدّ كلُّ لفظٍ مختلفِ الوحدات "
        "صنفًا واحدًا مهما تكرّر؛ والزوجُ الأدنى صنفان متساويا العدد متطابقا "
        "الحروف موضعًا موضعًا، يختلفان في حال موضعٍ واحدٍ فقط؛ وطولُ الزوج عددُ "
        "وحداته؛ والمقامُ الأزواجُ التي طولُها خمسٌ فأكثر؛ وموضعُ الاختلاف "
        "الأوّلُ أو الثاني أو الأخير أو غيرُها؛ وما يعطيه التساوي متوسّطُ ٣ على "
        "الطول على أزواج المقام؛ ونصيبُ الموضع عددُ أزواجه على أزواج المقام؛ "
        "وتوزيعُ الحركات داخلَ اللفظ وآخرَه ونتائجُ ختم c35956ef رُئيت قبل "
        "الختم، والأزواجُ لم تُرَ"
    ),
)

PREDICTIONS = (
    Prediction(
        identifier="م١",
        statistic="نصيبُ الأزواج التي اختلافُها في الأولى أو الثانية أو الأخيرة",
        threshold=Fraction(3, 4),
        direction=Direction.AT_LEAST,
        falsifies=(
            "دعوى صاحب المستودع: إن لم تغلب الأطرافُ الثلاثة فالحالُ تفرّق "
            "الألفاظَ في وسطها كما تفرّقها في أطرافها"
        ),
    ),
    Prediction(
        identifier="م٢",
        statistic="ذلك النصيبُ ناقصًا ما يعطيه التساوي",
        threshold=Fraction(1, 5),
        direction=Direction.AT_LEAST,
        falsifies=(
            "أنّ الأطرافَ مقصودة: إن لم تزد على التساوي بخُمس فغلبتُها أثرُ "
            "قِصَر الألفاظ لا أثرُ الإعراب والهيئة"
        ),
    ),
    Prediction(
        identifier="م٣",
        statistic="نصيبُ الوحدة الأخيرة ناقصًا أكبرَ نصيبٍ لموضعٍ غيرها",
        threshold=Fraction(0),
        direction=Direction.AT_LEAST,
        falsifies=(
            "أنّ الإعرابَ أوسعُ ما تفرّق به الحال: إن سبق موضعٌ آخرُ الأخيرةَ "
            "فهيئةُ الكلمة تفرّق أكثرَ ممّا تفرّق النسبة"
        ),
    ),
)

DIGEST = "51bd90a41191c700b0e72e83c568208f3e65d0b29ce789b47b09b5b8f7ee43ff"
"""يُثبَّت بعد أوّل اشتقاق، ولا يُمَسّ بعدَه."""


def test_the_seal_is_recomputed_from_the_written_conditions() -> None:
    """البصمةُ تُشتَقّ من الشروط لا تُنقَل."""

    assert seal(ORACLE, PREDICTIONS) == DIGEST


def test_the_short_word_trap_is_closed_in_the_extraction() -> None:
    """المقامُ خمسُ وحداتٍ فأكثر، والتساوي مقيسٌ معه."""

    assert "طولُها خمسٌ فأكثر" in ORACLE.extraction
    assert "وما يعطيه التساوي" in ORACLE.extraction
    assert {one.identifier for one in PREDICTIONS} == {"م١", "م٢", "م٣"}
