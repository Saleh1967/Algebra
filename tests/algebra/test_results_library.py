def test_the_three_open_loci_each_name_one_deciding_test() -> None:
    """ثلاثةُ مواضعَ مفتوحةٍ، لكلٍّ فحصٌ واحدٌ يحسمه — ولا «أو» في واحدٍ منها."""

    loci = TREE.open_loci()
    assert len(loci) == 3
    assert [path for path, _ in loci] == [
        "ط٣ الجذرُ والمعجم ← ص١ اشتقاقٌ من بناء",
        "ط٣ الجذرُ والمعجم ← ص٢ حصرٌ تامّ",
        "ط٥ الدلالة ← ص٢ حصرٌ تامّ",
    ]
    for _, test in loci:
        assert test.strip()
        assert " أو " not in test

    with pytest.raises(ResultsError) as raised:
        TREE.assert_not_reportable_as_settled()
    assert "3 موضعًا مفتوحًا" in str(raised.value)


