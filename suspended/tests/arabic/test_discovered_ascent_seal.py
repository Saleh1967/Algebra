"""**ختمٌ قبل النظر**: الصعودُ المكتشَف — لا أقترحُ طبقةً، بل يكتشفها العدّ.

**لم يُشغَّل شيءٌ بعد.**

**لماذا تُترَك التفعيلة**: في `0021350c…` اقترحتُ **التفعيلةَ** طبقةً
فردَّها الاقتصاد (١٫١١٥١). والعلّةُ أنّها **اقتراحي**: زوجٌ من المقاطع
اعتباطًا، فمعجمُه ينفجر (٢٣٬٧٨٥ مدخلًا). فالخطأُ منهجيٌّ لا حسابيّ:
**أن أسمّي الطبقةَ ثمّ أسألَ الاقتصادَ أن يُجيزها**.

**والبديلُ أن يُقلَب الترتيب**: يُبدأ من **الـ١١٢ وحدَها**، ويُدمَج في كلّ
خطوةٍ **الزوجُ المتجاورُ الذي يوفّر أكثر**، ويُوقَف عند أوّل خطوةٍ **لا
توفّر**. فالطبقاتُ **تُكتشَف ولا تُقترَح**، و«لا يبقى بتٌّ إلّا ليسهم
بإفادة» يصير **قاعدةَ البناء** لا شرطًا عليه.

**والتكلفةُ ذات شطرين** كما في الختم السابق: معجمٌ يُهجّى **بحروف الـ١١٢**
وطولُ كلّ مدخل، وبيانٌ إنتروبيا **محجوزةً**. والدمجُ **تجميعٌ محضٌ**،
فالابتلاعُ قائمٌ بالبناء: تسلسلُ الوحدات المدموجة **يُعيد الـ١١٢ بالضبط**.

**والتيّارُ بلا فواصل**: تُحذَف علاماتُ الكلمة من مدخل الدمج، **فيجوز
للدمج أن يعبر حدَّ الكلمة**. ثمّ يُسأل: **كم من الوحدات المكتشَفة عبرته
فعلًا؟** فإن ندر العبورُ فحدُّ الكلمة **مكتشَفٌ بالاقتصاد**، لم يُلقَّن.

**والاختيارُ داخلَ العيّنة والحكمُ محجوز**: يُختار الزوجُ الأكثرُ توفيرًا
بالعدّ الملحَق (إذ الاختيارُ ليس حكمًا)، وتُقاس التكلفةُ عند كلّ نقطةِ
فحصٍ **محجوزةً** بقسمة الآيات الزوجيّة/الفرديّة — وهي وحدَها التي تُوقِف.
"""

from __future__ import annotations

from fractions import Fraction

from algebra.signified import Direction, Oracle, Prediction, seal

ORACLE = Oracle(
    name="الصعودُ المكتشَف من الـ١١٢ بالاقتصاد وحدَه",
    source="quran-simple-enhanced.txt — البصمة 37633090…",
    extraction=(
        "من تيّار L₀ (١١٢ وحدةً، `c5a1e18`) بلا فواصلِ كلمات، يُدمَج في كلّ "
        "خطوةٍ الزوجُ المتجاورُ الأكثرُ وقوعًا؛ والتكلفةُ ذات شطرين — معجمٌ "
        "يُهجّى بحروف الـ١١٢ مع طول كلّ مدخل، وبيانٌ إنتروبيا محجوزةٌ بقسمة "
        "الآيات الزوجيّة/الفرديّة — وتُقاس عند نقاط فحصٍ معلنة؛ ويُوقَف عند "
        "أوّل نقطةٍ ترتفع فيها التكلفةُ المحجوزة"
    ),
)

PREDICTIONS = (
    Prediction(
        identifier="ك١",
        statistic="عددُ نقاط الفحص التي ارتفعت فيها التكلفةُ قبلَ نقطة الوقوف",
        threshold=Fraction(0),
        direction=Direction.AT_MOST,
        falsifies=(
            "قاعدةَ البناء نفسَها: إن ارتفعت التكلفةُ ثمّ نزلت فالوقوفُ عند "
            "أوّل ارتفاعٍ اعتباطٌ، ويُعاد تعريفُ الوقوف بختمٍ جديد"
        ),
    ),
    Prediction(
        identifier="ك٢",
        statistic="التكلفةُ عند نقطة الوقوف مقسومةً على تكلفة L₀ (١٬٩٩٩٬٣٠٣)",
        threshold=Fraction(1),
        direction=Direction.AT_MOST,
        falsifies=(
            "جدوى الصعود المكتشَف أصلًا: إن لم يوفّر على الـ١١٢ فلا طبقةَ "
            "فوقها يكتشفها الاقتصاد، ويُنشَر السقفُ عند L₀"
        ),
    ),
    Prediction(
        identifier="ك٣",
        statistic="التكلفةُ عند نقطة الوقوف مقسومةً على تكلفة L₁ المقطع (١٬٧٨٥٬٩٥٤)",
        threshold=Fraction(1),
        direction=Direction.AT_MOST,
        falsifies=(
            "دعوايَ أنّ المكتشَفَ يسبق المقترَح: إن لم يبلغ المقطعَ الذي "
            "بنيتُه بيدي فالقاعدةُ اللغويّةُ خيرٌ من الاقتصاد الأعمى ههنا، "
            "ويُنشَر ذلك بلا تجميل"
        ),
    ),
    Prediction(
        identifier="ك٤",
        statistic="نصيبُ وقوعات الوحدات المكتشَفةِ التي لا تعبر حدَّ الكلمة",
        threshold=Fraction(90, 100),
        direction=Direction.AT_LEAST,
        falsifies=(
            "دعوى أنّ حدَّ الكلمة يُكتشَف بالاقتصاد: إن عبرته عُشرُ الوقوعات "
            "فأكثرُ فالدمجُ لا يرى الكلمةَ، والحدُّ يبقى مُلقَّنًا لا مكتشَفًا"
        ),
    ),
    Prediction(
        identifier="ك٥",
        statistic="أدنى (التكلفة المحجوزة − الملحَقة) على نقاط الفحص (بت)",
        threshold=Fraction(0),
        direction=Direction.AT_LEAST,
        falsifies="اتّجاهَ الانتحال؛ وهو الدرسُ الذي سقطت به نتيجتي في `ca8fd2c`",
    ),
    Prediction(
        identifier="ك٦",
        statistic="عددُ الدمجات المقبولة عند نقطة الوقوف",
        threshold=Fraction(20_000),
        direction=Direction.AT_MOST,
        falsifies=(
            "دعوى أنّ الصعودَ ينتهي: إن جاوزت الدمجاتُ عشرين ألفًا ولم تقف "
            "فالسقفُ لم يُبلَغ في هذا التشغيل، ويُوسَم UNREACHABLE لا مبلوغًا"
        ),
    ),
)

DIGEST = "620b63a2cf807f7fd810cb1dcdad7a1d5ca63e6c6fedb174a3057252453fd3b2"
"""يُثبَّت بعد أوّل اشتقاق، ولا يُمَسّ بعدَه."""


def test_the_seal_is_recomputed_from_the_written_conditions() -> None:
    """البصمةُ تُشتَقّ من الشروط لا تُنقَل."""

    assert seal(ORACLE, PREDICTIONS) == DIGEST


def test_the_method_is_inverted_from_the_previous_seal() -> None:
    """لا تُقترَح الطبقةُ ثمّ تُجاز — بل يكتشفها الاقتصادُ خطوةً خطوة."""

    assert "تُكتشَف ولا تُقترَح" in __doc__
    assert "الأكثرُ وقوعًا" in ORACLE.extraction
    assert len(PREDICTIONS) == 6


def test_two_conditions_are_aimed_at_my_own_claims() -> None:
    """ك٣ يُعرّض دعوايَ أنّ المكتشَفَ يسبق المقترَح، وك٤ دعوى اكتشاف الحدّ."""

    mine = next(one for one in PREDICTIONS if one.identifier == "ك٣")
    assert "دعوايَ" in mine.falsifies
    boundary = next(one for one in PREDICTIONS if one.identifier == "ك٤")
    assert boundary.threshold == Fraction(90, 100)
    assert "مُلقَّنًا لا مكتشَفًا" in boundary.falsifies
