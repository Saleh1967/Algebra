def grab(pattern: str, text: str) -> str:
    found = re.search(pattern, text, re.M)
    if found is None:
        raise SystemExit(f"لا شاهدَ في السجلّ لـ{pattern}")
    return found.group(1)


def eastern(one: object) -> str:
    return str(one).translate(EASTERN)


def boxes() -> dict[str, tuple[str, str, str]]:
    """السداسيّة ← (الشريحة، العدد، النصيب) — مقروءةً من سجلّ مُودَع."""

    found = re.findall(
        r"^    (\S+) U\+([0-9A-F]{4}) \| (\d+) \| نصيبٌ ([0-9.]+)$",
        LADDER.read_text(encoding="utf-8"),
        re.M,
    )
    if not found:
        raise SystemExit("لا خاناتَ في سجلّ السلّم")
    return {two: (one, three, four) for one, two, three, four in found}


def tails() -> dict[str, tuple[str, str, str]]:
    """السداسيّة ← (الشريحة، العدد، النصيب) لأقسام خانة «بلا علامة»."""

    found = re.findall(
        r"^    (\S+) U\+([0-9A-F]{4}) \| (\d+) \| نصيبٌ ([0-9.]+)$",
        MORPH.read_text(encoding="utf-8"),
        re.M,
    )
    if not found:
        raise SystemExit("لا أقسامَ في سجلّ الصورة")
    return {two: (one, three, four) for one, two, three, four in found}


