"""تدقيقُ «ذرّة الارتياد» قبل ختمها — والتدقيقُ أمسك عطلًا في آلتي أوّلًا.

**الحال**: وصلت مسوّدةُ تسجيلٍ للبناء الديكارتيّ الصوتيّ، نصُّها «مسودةُ
ختمٍ قبل فتح البايتات… وما قبله تعديلٌ مفتوح». فهذا تدقيقُها **قبل الختم**،
لا تشغيلٌ لها: لا يُقاس ههنا بندٌ من بنودها (ص-أ، ص-ب، ث١…ث٦)، وإنّما
تُفحَص **وحداتُها** بالحساب وبالمادّة — إذ وحدةٌ لا تسع مادّتَها تُبطِل ما
يُبنى عليها مهما دُقِّق.

`A_TWO_BIT_FIELD_CANNOT_HOLD_A_SEVEN_VALUED_INVENTORY`: حقلُ «القتران»
بتّان — أربعُ قيم. والمقيسُ في البايتات المختومة **سبعةُ أصناف**: فتحة
وكسرة وضمّة وسكون وشدّة وتنوين و**مجرَّد**. والأربعةُ المذكورةُ لا تغطّي
إلّا **٦٦٫٢٦٪** من المواضع؛ فالحقلُ يُسقِط ثلثَ المادّة أو يطويها صامتًا.
والطيُّ قرارٌ يُعلَن لا يُستنتَج.

`THE_113_IS_A_CEILING_COMPUTED_NOT_A_COUNT_OBSERVED`: و١١٣ = ٢٨×٤+١ **حسابٌ
لا رصد**: إذ الحاجزُ والنفَسُ والصوتُ **دوالُّ في الحرف**، فلا حرَّ بعد
تعيينه إلّا القتران. والمقيسُ على الأصناف السبعة **١٩٤ ذرّةً من سقفٍ ١٩٦**.

`AND_THE_TWO_EMPTY_CELLS_ARE_OF_TWO_DIFFERENT_KINDS`: والخاليتان (ا، شدّة)
و(غ، شدّة). والأولى **ممتنعةٌ بالبناء** — ألفُ المدّ لا تُشدَّد — والثانيةُ
**غيرُ مشهودةٍ ولا ممتنعة**. فخلوّان بجنسين، ومن عدّهما واحدًا فقد خلط
دعوى قابلةً للإبطال بفجوةٍ في المادّة.

`THE_CODE_WIDTH_HIDES_A_THIRD_NUMBER`: وتسعُ بتّاتٍ **٥١٢ نقطةَ ترميز**،
والمشروعُ منها ٢٨٨ = ١٨×٤×٢×٢. فـ**٢٢٤ نقطةً ممتنعةً بالعرض** لم تُذكَر،
و١٧٥ خانةً من ٢٨٨ خارجَ السقف ١١٣ لم تُصنَّف. والأرقامُ ثلاثةٌ لا اثنان.

`TH6_IS_A_COROLLARY_OF_TH1_NOT_A_SEVENTH_CONDITION`: وث٦ (صفرُ ثلاثيّات
قتران‑سكون‑سكون) **مستلزَمٌ منطقًا** من ث١ (صفرُ أزواج سكون‑سكون): ما خلا
من الزوج خلا من كلّ ثلاثيٍّ يحويه. فعدُّه بندًا مستقلًّا يضخّم العائلةَ،
وحدُّ العائلة يُقسَم على عددها المُعلَن.

`THE_PAN_IS_NOT_THE_VARIABLE_THAT_CHANGED_IN_SA`: وص-أ يقيس متوسّطَ |Δ|
بين **مواضع السلّم** للحرفين المتجاورين، وموضعُ الحرف دالّةٌ في الحرف وحدَه.
فالبوّابةُ (ج) — علاماتُ الضبط — **لا تدخل القياسَ ألبتّة**. فالفرقُ عن
نظيره الساقط على الرسم (٦٫٠٨١ مقابل صفريٍّ ٥٫١٥٧) مردُّه **السلّمُ** —
سبعةَ عشرَ موضعًا بقاعدة المخرج الحركيّ — لا «كفّةُ الصوت». ونسبةُ الفرق
إلى غير متغيّره تجعل النتيجةَ تُقرَأ خبرًا عن الكفّة وهي خبرٌ عن السلّم.

`A_POSITIVE_MUTUAL_INFORMATION_IS_NOT_A_CONDITION`: وص-ب يشترط أن يكون
`MI` **موجبًا**؛ والمعلوماتُ المتبادلةُ المقدَّرةُ من عيّنةٍ لا تكون سالبةً
بحالٍ، فالشرطُ يمرّ بالبناء. والعاملُ فيه «خارج نطاق التبديل» وحدَه،
فيُكتَب **مئينًا بحدٍّ** لا وصفًا.

`THE_LADDER_IS_CITED_BUT_NOT_DEPOSITED`: وو٣ يُسمّي المصدرَ والصفحاتِ
والطبعةَ والقاعدةَ، **ولا يُودِع خريطةَ الثمانية والعشرين على السبعةَ عشر**.
وهو عينُ ما أبطل خ٢ عندنا: «أحجامٌ لا حروف». فلا يُشغَّل هذا التسجيلُ
بحالٍ حتّى تُودَع الخريطةُ حرفًا حرفًا بتوقيع راويها.

`TWO_CORPORA_STAND_IN_ONE_SEAL_WITHOUT_A_DECLARATION`: وإغلاقُ التشغيل
«٧٧٬٤٢٩ صفًّا بانضمامٍ على عمود surface» **ليس من بايتات المصحف**، والمادّةُ
المُعلَنةُ في و١ بايتاتُه (٣٧٬٣٧٢ سكونًا). فمدوّنتان في ختمٍ واحد، والنقلُ
بينهما يُعلَن ولا يُطوى.

`AND_THE_AUDIT_CAUGHT_A_DEFECT_IN_MY_OWN_READER_FIRST`: وقبل هذا كلِّه:
فحصُ «كم صنفًا يسعه القتران؟» أخرج **تسعةً وعشرين حرفًا** من قارئي لا
ثمانيةً وعشرين. والعلّةُ أنّ `FOLD["ء"] = ""` ثمّ `if folded in BASE` —
و`"" in BASE` **صحيحٌ في بايثون**. فكان كلُّ همزةٍ مفردةٍ تُدخِل **رمزًا
خاويًا** في التيار: ١٬٥٧٨ رمزًا تكسر ١٬٥٧٨ جوارًا حقيقيًّا. وأُصلِح
بـ`folded and folded in BASE` في القُرّاء الأربعة.

`THE_DEFECT_MOVED_NO_VERDICT_AND_THAT_IS_MEASURED_NOT_ASSUMED`: وأُعيد
تشغيلُ ما بُني عليه: أحكامُ `9fc67498…` الخمسةُ كما هي (٠٫٠٠٨٠ و٠٫٩٨٤٠)،
وأحكامُ `5e3656d5…` كما هي (و٣ ساقطٌ ١٫٥٢٠٠)، وخ١ كما هو (٠٫٠٢٦٠ · `p`
٠٫٣٧٧٣١). والذي تحرّك **التشابهاتُ في الخانة الرابعة** ومئينُ واحدٍ من
٠٫٠١١ إلى ٠٫٠١٢. فالعطلُ حقيقيٌّ وأثرُه مقيسٌ لا مُقدَّر.
"""

from __future__ import annotations

import importlib.util
import sys
from collections import Counter
from fractions import Fraction
from pathlib import Path

from frozen_corpus import CORPUS, requires_corpus

REPOSITORY = Path(__file__).resolve().parents[2]
READER = REPOSITORY / "examples" / "rasm" / "run_marked_contrast.py"

pytestmark = requires_corpus

# ما أعلنه التسجيلُ في وحداته
DECLARED_BITS = 9
DECLARED_LADDER = 17
DECLARED_COUPLING_VALUES = 4
DECLARED_POSSIBLE = 288
DECLARED_WITNESSED = 113
DECLARED_LETTERS = 28


def _stream() -> list[tuple[str, str]]:
    spec = importlib.util.spec_from_file_location("run_marked_contrast", READER)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return list(module.read_stream(CORPUS.read_text(encoding="utf-8")))


STREAM = _stream()
CLASSES = Counter(one for _, one in STREAM)
ATOMS = {(one, kind) for one, kind in STREAM}
FOUR_NAMED = ("فتحة", "ضمّة", "كسرة", "سكون")


def test_the_coupling_field_is_too_narrow_for_the_measured_inventory() -> None:
    """سبعةُ أصنافٍ مقيسة، وبتّان لا يحملان إلّا أربعة."""

    assert len(CLASSES) == 7
    assert 2**2 == DECLARED_COUPLING_VALUES < len(CLASSES)
    assert set(FOUR_NAMED) <= set(CLASSES)
    outside = set(CLASSES) - set(FOUR_NAMED)
    assert outside == {"مجرَّد", "شدّة", "تنوين"}


def test_a_third_of_the_material_falls_outside_the_four_values() -> None:
    """الأربعةُ تغطّي ٦٦٫٢٦٪ من المواضع؛ والباقي يُطوى أو يُسقَط بقرارٍ يُعلَن."""

    total = sum(CLASSES.values())
    covered = Fraction(sum(CLASSES[one] for one in FOUR_NAMED), total)
    assert Fraction(66, 100) < covered < Fraction(67, 100)
    assert Fraction(33, 100) < 1 - covered < Fraction(34, 100)


def test_the_witnessed_count_is_a_ceiling_and_the_measured_one_is_larger() -> None:
    """١١٣ = ٢٨×٤+١ حسابٌ؛ والمقيسُ على السبعة ١٩٤ من سقفٍ ١٩٦."""

    assert DECLARED_WITNESSED == DECLARED_LETTERS * DECLARED_COUPLING_VALUES + 1
    assert len({one for one, _ in STREAM}) == DECLARED_LETTERS
    assert len(ATOMS) == 194
    assert DECLARED_LETTERS * len(CLASSES) == 196
    assert len(ATOMS) > DECLARED_WITNESSED


def test_the_two_vacancies_are_of_two_kinds_not_one() -> None:
    """(ا، شدّة) ممتنعةٌ بالبناء، و(غ، شدّة) غيرُ مشهودةٍ ولا ممتنعة."""

    missing = {
        (one, kind)
        for one in {letter for letter, _ in STREAM}
        for kind in CLASSES
        if (one, kind) not in ATOMS
    }
    assert missing == {("ا", "شدّة"), ("غ", "شدّة")}
    # وكلتاهما في عمودٍ واحد، والفرقُ في جنس الخلوّ لا في موضعه
    assert {kind for _, kind in missing} == {"شدّة"}


def test_the_code_width_hides_a_third_number() -> None:
    """٥١٢ نقطةَ ترميز، و٢٨٨ مشروعة، و٢٢٤ ممتنعةٌ بالعرض لم تُذكَر."""

    assert 2**DECLARED_BITS == 512
    assert (DECLARED_LADDER + 1) * DECLARED_COUPLING_VALUES * 2 * 2 == DECLARED_POSSIBLE
    assert 2**DECLARED_BITS - DECLARED_POSSIBLE == 224
    assert DECLARED_POSSIBLE - DECLARED_WITNESSED == 175


def test_the_sixth_theorem_is_implied_by_the_first() -> None:
    """صفرُ أزواج (سكون، سكون) يستلزم صفرَ ثلاثيّاتٍ تحويه — بلا مادّة."""

    def has_pair(run: tuple[str, ...]) -> bool:
        return any(a == b == "سكون" for a, b in zip(run, run[1:], strict=False))

    triples = (
        ("قتران", "سكون", "سكون"),
        ("سكون", "سكون", "فتحة"),
        ("فتحة", "سكون", "سكون"),
    )
    for one in triples:
        assert has_pair(one)  # كلُّ ثلاثيٍّ مرفوضٍ في ث٦ يحوي زوجَ ث١

    # ولو خلا التيارُ من الزوج لخلا من الثلاثيّ ضرورةً
    without_pairs = ("فتحة", "سكون", "ضمّة", "سكون", "كسرة")
    assert not has_pair(without_pairs)


def test_the_first_condition_never_touches_the_mark_gate() -> None:
    """موضعُ السلّم دالّةٌ في الحرف؛ فص-أ لا يقرأ علامةً واحدة."""

    bare = [one for one, _ in STREAM]
    marked = [f"{one}|{kind}" for one, kind in STREAM]
    # تتابعُ الحروف واحدٌ في التيارين، فمتوسّطُ |Δ| على السلّم واحدٌ فيهما
    assert len(bare) == len(marked)
    assert bare == [one.split("|")[0] for one in marked]
    # والمتغيّرُ الوحيدُ بين نظيرَي ص-أ هو السلّم: ١٧ موضعًا بدل المُودَع ١٦
    assert DECLARED_LADDER == 17
    from alghanem.arabic.classical_makharij_table import CLASSICAL_MAKHARIJ

    assert len(CLASSICAL_MAKHARIJ) == 16 != DECLARED_LADDER


def test_the_empty_symbol_defect_is_gone_from_the_reader() -> None:
    """لا رمزَ خاوٍ في التيار، وعدّةُ الحروف ثمانيةٌ وعشرون لا تسعة وعشرون."""

    assert not any(one == "" for one, _ in STREAM)
    assert len({one for one, _ in STREAM}) == 28
    # والعلّةُ كانت أنّ الخاويَ عضوٌ في كلّ نصّ
    assert "" in "ابت"
    assert len(STREAM) == 331_259
