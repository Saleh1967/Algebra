"""**ختمٌ قبل النظر**: الـ١١٢ وأدوارُها — جامعٌ مانعٌ لا يترك نقطةَ ترميزٍ بلا قناة.

**لم يُشغَّل شيءٌ بعد.**

**العِلّة**: طلب صاحبُ المستودع أن يُعاد بناءُ الوحدات الـ١١٢ وأدوارُها كلُّها —
الترميزيّةُ والأبجديّةُ والإملائيّةُ والصوتيّةُ والوظيفيّةُ والاشتقاقيّةُ
والصرفيّةُ والنحويّةُ والإعرابيّة، والمدلولُ وحده، والدالُّ والمدلولُ معًا —
**جامعًا مانعًا لا يترك بتًّا بلا تفسير**.

**والجامعُ المانعُ يُقال في موضعين لا في موضعٍ واحد**:

- **عند البايتات**: كلُّ نقطةِ ترميزٍ في الملفّ تُسنَد إلى قناةٍ واحدةٍ بالضبط
  — هويّةُ الوحدة، أو حالتُها، أو قناةُ باقٍ مسمّاة، أو البنية — ثمّ تُعاد
  البايتاتُ منها. فلا نقطةَ بلا قناة (جامع)، ولا نقطةَ في قناتين (مانع).
- **عند الأدوار**: كلُّ خانةٍ من الوحدات الـ١١٢ في كلّ مستوًى **لها قيمةٌ
  ومصدرٌ مسمًّى**، أو هي `UNCLASSIFIED` **وما تحتاجه مكتوبٌ**. فالتفسيرُ
  الذي لا مصدرَ له لا يُكتَب، والخانةُ التي لا قيمةَ لها لا تُترَك صامتة.

**وما لا يُكتَب في هذه الشجرة من المحفوظ**: جدولُ الصفات (حاجزُ
`SIFA_TABLE_BYTES` قائم)، وقيمُ الجُمَّل، وجدولُ الجذور. فخاناتُها
`UNCLASSIFIED` بأسبابها — وهذا هو «المانع» في الأدوار: لا يدخل الجدولَ ما لم
يجتز بابَه.

**وما رُئي قبل الختم ولا يدخل شرطًا**: جردُ نقاط الترميز في الملفّ (عددُ كلّ
حرفٍ وعلامة)، وأعدادُ ختمَي `945fd806…` و`34176d22…` وتشخيصُهما، وأنّ
أبجديّةَ الوحدات المرصودة ١١٢. فكلُّها تُعرَض وصفًا لا حكمًا.

**والشرطان الماديّان لم يُنظَر فيهما**:

- **ج٤ — لا يُبتدأ بساكن**: الوحدةُ الأولى من اللفظ حالتُها سكونٌ وحرفُها غيرُ
  الألف وليست شطرَ شدّة — نصيبُها من الوحدات الأولى لا يجاوز واحدًا من ألف.
  وقد توقّعتُ بالتفكير لا بالعدّ أنّ فواتحَ السور تقع فيه («حم»، «ق»، «ن»).
- **ج٥ — الحرفُ لا يستقلّ**: لفظٌ من حرفٍ واحدٍ **عليه علامة** لا يوجد البتّة.
  وهو أقربُ ما في البايتات إلى قول النبهاني «الحرف لا يستقلّ بمعناه»، وقولِ
  صاحب المستودع «الحرف لا يستقلّ بمعنى».
"""

