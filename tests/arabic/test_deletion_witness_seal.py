"""**ختمٌ قبل الحكم**: شاهدُ المحذوف — أفي الإطار هو أم في الحركة؟

**وما رأيتُه قبل الختم يُعلَن ههنا**: بُنِي التشغيلُ وشُغِّل على المدوّنة
المجمَّدة قبل كتابة هذا الختم، **فرأيتُ مخرَجَه**. فليس تسجيلًا سابقًا
للنظر، وادّعاءُ ذلك كذب. وإنّما هو **تقييدُ الأحكام بحدودٍ مكتوبةٍ ذاتِ
اتّجاهات** تُشتَقّ منها بصمةٌ لا تُمَسُّ بعدها.

**وأصلُ الحدود**: الوجهُ الثاني من دعوى القياس السابق — «الحذفُ
**مسترجَعٌ بالإطار**، لا بقيّةَ له» — وهي دعوى استرجاعٍ لا غلبة، فحدُّها
**الصفرُ** كما كتبها صاحبُها. وحدُّ العدميّ (`٠٫٠١`) و**عددُ الخلطات
(٢٠٬٠٠٠) وبذرتُها** مكتوبةٌ في متن التشغيل قبل تشغيله، فلا تُنتقى بعده.

**والأوراكلُ هو المدوّنةُ وحدَها**: الحركةُ مقروءةٌ من البايتات، لا
مستورَدةٌ من جدولِ جذور. ولذلك **لا يدّعي شيءٌ ههنا أنّ الحركةَ هي حرفُ
الأصل**: المقيسُ إفادتُها عن الإطار، لا تسميتُها.

**وثلاثةُ حدودٍ تملك أن تسقط**: ق١ لو استرجع الإطارُ مدَّه لبقيت دعوى
الاسترجاع قائمةً وسقط بناءُ هذا التشغيل؛ وق٣ لو اختلفت حركةُ إطارٍ واحدٍ
لسقط الشاهدُ المرشَّح؛ وق٤ لو بلغت الصدفةُ ما بلغه المرصود لكان التوحّدُ
أثرَ قِلّةٍ لا أثرَ بنية. وق٥ يُعيد القياسَ **بطرحِ ملتبسِ السابقة**، فإن
سقط ثَمَّ فالنتيجةُ قائمةٌ على التباسٍ رسميٍّ لا على مناوبة.
"""

from __future__ import annotations

from fractions import Fraction

from algebra.signified import Direction, Oracle, Prediction, seal

ORACLE = Oracle(
    name="شاهدُ المحذوف: الإطارُ أم الحركة؟",
    source="quran-simple-enhanced.txt — البصمة 37633090…",
    extraction=(
        "تُؤخَذ الأُطُرُ المناوِبةُ من `c46dfbe3…` بعينها، ثمّ يُقاس فيها "
        "أمران: **الأوّل** إنتروبيا المدّ الظاهر في السطوح الممدودة "
        "مشروطةً بالإطار — وهي دعوى الاسترجاع بالإطار؛ **والثاني** "
        "إنتروبيا حركة الجذع المقصور (ضمّةٍ أو كسرة) مشروطةً بالإطار، "
        "وهي حركةٌ **مقروءةٌ من البايتات** لا مستورَدة. ويُقصَر فحصُ "
        "التوحّد على الأُطُر ذات السطحين فأكثرَ لأنّ ذا السطح الواحد "
        "مُوحَّدٌ بالضرورة، ويُسعَّر بخلط الحركات على الأُطُر ٢٠٬٠٠٠ "
        "خلطةً ببذرةٍ مكتوبة، ثمّ يُعاد القياسُ كلُّه بطرح الأُطُر التي "
        "لا مقصورَ لها إلّا بعد قلعِ سابقة"
    ),
)

PREDICTIONS = (
    Prediction(
        identifier="ق١",
        statistic="H(المدّ الظاهر | الإطار) بالبتّات",
        threshold=Fraction(1, 10),
        direction=Direction.AT_LEAST,
        falsifies=(
            "أنّ ثَمَّ سؤالًا أصلًا: فإن أنبأ الإطارُ بمدّه فدعوى «الحذفُ "
            "مسترجَعٌ بالإطار» **قائمةٌ كما كُتِبت**، ولا حاجةَ إلى شاهدٍ "
            "آخر، ويسقط بناءُ هذا التشغيل كلِّه لا حدٌّ واحدٌ منه"
        ),
    ),
    Prediction(
        identifier="ق٢",
        statistic="حمولةُ حركة الجذع المقصور H(حركة) بالبتّات",
        threshold=Fraction(1, 2),
        direction=Direction.AT_LEAST,
        falsifies=(
            "أنّ الحركةَ تصلح شاهدًا: فموضعٌ لا يحمل شيئًا لا يُسمّى شاهدًا "
            "ولو كان منتظمًا. فإن كانت الحركةُ واحدةً في المدوّنة كلِّها "
            "فانتظامُها مع الإطار **لا خبرَ فيه**"
        ),
    ),
    Prediction(
        identifier="ق٣",
        statistic="H(حركة الجذع المقصور | الإطار) بالبتّات",
        threshold=Fraction(0),
        direction=Direction.AT_MOST,
        falsifies=(
            "دعوى أنّ الحركةَ شاهدُ المحذوف: فإن اختلفت حركةُ إطارٍ واحدٍ "
            "بين سطوحه فالحركةُ **ليست دالّةً على الإطار**، ويبقى المحذوفُ "
            "بلا شاهدٍ مقروءٍ من البايتات"
        ),
    ),
    Prediction(
        identifier="ق٤",
        statistic="نصيبُ الخلطات التي بلغت توحّدَ المرصود فأكثر",
        threshold=Fraction(1, 100),
        direction=Direction.AT_MOST,
        falsifies=(
            "أنّ التوحّدَ بنيةٌ لا قِلّة: فأكثرُ الأُطُر قليلُ السطوح، "
            "والقليلُ يتوحّد بالصدفة. فإن بلغت الخلطةُ ما بلغه المرصودُ "
            "كثيرًا فالنتيجةُ **أثرُ عدد**، ولا يُنشَر منها شيء"
        ),
    ),
    Prediction(
        identifier="ق٥",
        statistic="نصيبُ الخلطات البالغةِ، بعد طرحِ ملتبسِ السابقة",
        threshold=Fraction(1, 100),
        direction=Direction.AT_MOST,
        falsifies=(
            "أنّ النتيجةَ قائمةٌ على مناوبةٍ لا على التباسٍ رسميّ: فأربعةُ "
            "أُطُرٍ (`سَمِعْنَا` وأخواتُها) ليست جوفاءَ أصلًا. فإن سقط "
            "القياسُ بطرحها فالخبرُ **كان فيها لا في الأجوف**، ويُسمّى "
            "ذلك ولا يُكتَم"
        ),
    ),
)

DIGEST = "d957be5b0df2b3e6acbbec695fdfae40b183856865c81f1df7cc11ca274f4a51"
"""يُثبَّت بعد أوّل اشتقاق، ولا يُمَسّ بعدَه."""


def test_the_seal_is_recomputed_from_the_written_conditions() -> None:
    """البصمةُ تُشتَقّ من الشروط لا تُنقَل."""

    assert seal(ORACLE, PREDICTIONS) == DIGEST


def test_the_prior_sight_of_the_output_is_declared_not_hidden() -> None:
    """رأيتُ المخرَجَ قبل الختم، وذلك مكتوبٌ في متنه — ولا أدّعي غيرَه."""

    assert __doc__ is not None
    assert "فرأيتُ مخرَجَه" in __doc__
    assert "ليس تسجيلًا سابقًا" in __doc__


def test_the_null_is_declared_before_it_is_run() -> None:
    """عددُ الخلطات وبذرتُها مكتوبان في التشغيل — فلا يُنتقى العدميُّ بعده."""

    assert "٢٠٬٠٠٠" in ORACLE.extraction
    assert "ببذرةٍ مكتوبة" in ORACLE.extraction
    by_name = {one.identifier: one for one in PREDICTIONS}
    assert by_name["ق٤"].threshold == Fraction(1, 100)
    assert by_name["ق٥"].threshold == Fraction(1, 100)


def test_the_recovery_threshold_is_the_zero_the_claim_itself_wrote() -> None:
    """ق٣ حدُّه صفرٌ — وهو حدُّ «لا بقيّةَ له» كما كتبه صاحبُ الدعوى."""

    recovery = next(one for one in PREDICTIONS if one.identifier == "ق٣")
    assert recovery.threshold == Fraction(0)
    assert recovery.direction is Direction.AT_MOST


def test_nothing_here_claims_the_vowel_is_the_radical() -> None:
    """المقيسُ إفادةُ الحركة لا تسميتُها — ولا جدولَ جذورٍ تحمله الشجرة."""

    assert __doc__ is not None
    assert "لا يدّعي شيءٌ ههنا أنّ الحركةَ هي حرفُ" in __doc__
    assert "المقيسُ إفادتُها عن الإطار، لا تسميتُها" in __doc__
    assert "مستورَدةٌ من جدولِ جذور" in __doc__
    assert len(PREDICTIONS) == 5
