@requires_corpus
def test_the_counting_root_has_a_fourth_member_and_it_is_the_agent() -> None:
    """«فاسأل العادّين» — والآيةُ التي قبلَها «عددَ سنين»."""

    lines = _bare_lines()
    agent = [index for index, line in enumerate(lines) if "العادين" in line]
    number = [index for index, line in enumerate(lines) if "عدد سنين" in line]
    assert len(agent) == 1 and len(number) == 1
    assert agent[0] - number[0] == 1  # الرابعُ يجاور الثالث
    for other in ("معدودات", "عدة الشهور"):
        assert _attested(other) >= 1
    series = {"العدّ", "المعدود", "العدد", "العادّ", "العِدّة"}
    assert len(series) == 5 > 3  # فليس ثالوثًا بلا رابع


