def test_the_deletion_is_declared_before_any_count_and_is_bound() -> None:
    """∅ في فضاء الشواهد الأربعة، وله شرطٌ يوجب أن يقع له سطح."""

    assert "(ا و ي ∅)" in ORACLE.extraction
    assert "قبل العدّ" in ORACLE.extraction
    bound = next(one for one in PREDICTIONS if one.identifier == "ق٣")
    assert bound.direction is Direction.AT_LEAST and bound.threshold == Fraction(1)


def test_the_intruder_counter_is_forbidden_from_naming_the_weak() -> None:
    """ق٥ عدّادُه لا يذكر العلّة — وإلّا فالصفرُ من الشرط لا من البايتات."""

    assert "لا يذكر العلّةَ في شرطه" in ORACLE.extraction
    stray = next(one for one in PREDICTIONS if one.identifier == "ق٥")
    assert "تُسمّى بعينها" in stray.falsifies
    assert "٢٠٧" in stray.falsifies


def test_the_break_even_is_borrowed_and_its_reading_is_fixed_in_advance() -> None:
    """١٨٣ منقولةٌ لا مُفصَّلة، وقراءةُ الوجهين مكتوبةٌ قبل رؤية الرقم."""

    assert BREAK_EVEN == 183
    deciding = next(one for one in PREDICTIONS if one.identifier == "ق٦")
    assert deciding.threshold == Fraction(BREAK_EVEN)
    assert deciding.direction is Direction.AT_MOST
    assert __doc__ is not None
    assert "انقفل السؤالُ بالإيجاب لا محالة" in __doc__
    assert "بقي السؤالُ مفتوحًا" in __doc__
    assert "ولا يُقرأ عدمُ المجاوزة جوابًا" in __doc__


