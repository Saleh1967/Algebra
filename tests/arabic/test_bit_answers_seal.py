"""**ختمٌ قبل النظر**: الجوابُ بالبتّات على نحوٍ مُغلَقٍ يُعَدُّ كلُّه.

**ما سُئِل ومَن يُجيب**: مفرداتٌ مُغلَقةٌ ستٌّ (`VALUE` و`COST_BITS` و
`DIVIDES` و`FOLD` و`UNFOLD` و`COUNT`)، **وواحدةٌ منها وحدَها بُنِي لها
مُجيبٌ اليوم** — `COST_BITS`. والخمسُ الباقياتُ مكتوباتٌ في المفردات كي
**يُرى غيابُ مُجيبها** ولا يُظَنَّ أنّها لم تخطر. واسمان من خارج المفردات
يُجرَّبان عمدًا — `PROVE` و`GUESS` — **فالردُّ يُقاس لا يُفترَض**.

**ولمَ يُعَدُّ الكلُّ ولا يُعايَن بعضُه**: موضوعُ السؤال **بايتةٌ واحدة**،
ومجالُها متناهٍ مغلقٌ — مئتان وستٌّ وخمسون. فما يُقال ههنا **استدلالٌ تامٌّ
على كائنٍ متناهٍ**، لا استقراءٌ من عيّنة. **وهذا حدُّه كذلك**: لا يُقال منه
شيءٌ عن بايتتين ولا عن ثلاث.

**وما جُرِّب قبل الختم يُعلَن**: شُغِّلت الآلةُ على موضوعٍ واحدٍ هو البايتةُ
`200` ورُئي جوابُها ثمانيًا وثمنُها ستّةَ عشرَ، **ويُكتَب ذلك ههنا فما
رأيتُه قبل الختم لا يُخفى**. ولا يُستخرَج من موضوعٍ واحدٍ توزيعٌ ولا أكبرُ
ثمنٍ ولا شكوى.

**والفرقُ الذي يحمله هذا الختم**: أنّ **الحاسبَ غيرُ المُتحقِّق**. فالأجوبةُ
تُبنى بقسمةٍ على اثنين، ويُعاد فحصُها ببسطٍ مكتوبٍ وقصٍّ من اليسار —
**طريقان لا يتّفقان صدفةً إن أخطأ أحدُهما**. ونجاحُ الحساب وحدَه ليس
شاهدًا؛ والشاهدُ **إعادةُ الفحص من الأثر**.

**ولا دعوى لغويّةً ولا تعلّمَ ههنا**: بايتاتٌ وبتّاتٌ وأثمان. وطبقةُ
الاقتراح — أيَّ قاعدةٍ تُجرَّب أوّلًا — **ليست في هذا التشغيل أصلًا**.
"""

