    assert "لم يقع إلّا في موضعٍ واحد" in __doc__
    assert "خمسَ مرّاتٍ فأكثر" in __doc__
    assert "وقع خمسًا فأكثر" in ORACLE.extraction
    fifth = next(one for one in PREDICTIONS if one.identifier == "ح٥")
    assert "خمسِ وقوعاتٍ فأكثر" in fifth.statistic
