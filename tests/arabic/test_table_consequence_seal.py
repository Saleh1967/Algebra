"""**ختمٌ قبل النظر**: لازمٌ من الجدول المُودَع — **فإن خالف سقط الجدول**.

**لم يُشغَّل شيءٌ بعد.**

**لِمَ هذا التشغيل**: أُودِع `deposits/bridge_tables.md` وكالةً، فصار
الترخيصُ قائمًا **والمقيسُ من لوازمه صفرًا**. وجدولٌ يُودَع ولا يُختبَر
**نثرٌ لا فرض**. فيُشتَقّ منه لازمٌ ويُقاس.

**اللازمُ المُشتَقّ**: يقول الجدولُ إنّ العلامةَ الأخيرةَ **حكمُ باب** —
أي أنّ موقعَ اللفظ من التركيب هو الذي يضعها. **فيلزم عنه شيئان**:

١) **أنّ الهيكلَ الذي تتبدّل علامتُه تتبدّل لتبدّلِ موقعه**، فيكون
**الجارُ أخبرَ بعلامته** ممّا هو في عامّة المدوّنة.

٢) **وأنّ تبدّلَها ليس من بنية اللفظ نفسِه**، فتكون صورتُه — منقوصةَ
علامتِه — **أقلَّ خبرًا عنها من جاره** في ذلك المقام بعينه.

**فإن كان الجارُ لا يزيد ثمّةَ، وكانت الصورةُ لا تزال أخبرَ، فالتبدّلُ
تبدّلُ صورةٍ لا تبدّلُ موقع** — **ويسقط لازمُ الجدول**، ويُسجَّل سقوطُه.

**والقسمةُ بالبايتات لا بالأحكام**: الهيكلُ **ثابتٌ** إن لم تُرَ له إلّا
علامةٌ واحدةٌ في المجمَّد كلِّه، و**متبدّلٌ** إن رُئيت له أكثر. **ولا
يُسمّى الثابتُ مبنيًّا ولا المتبدّلُ معربًا في السجلّ** — فذلك حكمُ
الجدول، وهو المُتَّهَمُ ههنا لا الشاهد.

**والطرفُ التافهُ يُستبعَد قبل النظر**: هيكلٌ وقوعُه واحدٌ **ثابتٌ
بالضرورة**، فلا شهادةَ فيه. **فتُشترَط خمسُ وقوعاتٍ فأكثرَ**، وما دونها
**خلوٌّ يُصنَّف ويُعَدّ ولا يُصفَّر**.

**وماركوف**: القسمةُ **تقييدُ مسندٍ** لا تكتيلُ سياق؛ والأسئلةُ هي هي.
**وinduction on**: `log₂ التباديل ≤ N·H` في كلّ مسند، و`H(الحال|الهيكل)`
**صفرٌ على الثابتة بحكم البناء** — فإن لم يكن صفرًا فالقسمةُ لم تقع.
**وinduction FOR**: الحلقةُ تشهد على المسندين لا على واحد.

**والمسندُ يُصرَّح به في كلّ مقدار** (العطل ٢٤): لا يُطرَح مقدارٌ على
الثابتة من مقدارٍ على المتبدّلة، **وكلُّ مقارنةٍ داخلَ مسندها أو بين
مقدارٍ ومقدارٍ على المسند الواحد**.

**وما لا يُدَّعى**: سقوطُ اللازمِ **سقوطُ فرضٍ مُودَعٍ لا سقوطُ لغة**.
والجدولُ فرضٌ إسناديٌّ أوّليٌّ لا نقلٌ عن أحد، **فسقوطُه لا يمسُّ نحوًا
ولا ناقلًا**.
"""

