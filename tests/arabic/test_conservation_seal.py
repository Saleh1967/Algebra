"""**ختمٌ قبل النظر**: مبرهنةُ الحفظ — البناءُ الجامعُ المانعُ من البتّ إلى المصحف،
صعودًا ونزولًا، وكلُّ خطوةٍ فحصٌ مقيس.

**لم يُعَدّ شيءٌ على المدوّنة كلّها بعد**. ورُئيت الآلةُ وحدها: جدولُ الرخص (٢٢٣
انتقالًا مرخّصًا في دورة السبع: ٥٥ للحرف، و٥٦ و١١٢ للحال)، ورفضُ الرموز الستّة عشر
غير المرخّصة، والذهابُ والإيابُ على ألفاظ السطور العشرين الأولى وحدها لتصحيح الآلة.

**العِلّة**: قال صاحبُ المستودع: «أعد البناءَ الجامعَ المانعَ من الصفر، ويشمل ١١٢
صعودًا ونزولًا؛ مبرهنةُ الحفظ — البرهانُ الكامل، وكلُّ خطوةٍ منه محفوظةٌ بفحصٍ
مقيس من أوّل حرفٍ/حركةٍ/حالة؛ صعودٌ بتًّا بتًّا، انتقالاتٌ مرخّصة، لا يُرخَّص التالي
قبل استنفاد السابق، خطوةً خطوة».

**والمبرهنة**: لكلّ طبقةٍ k زوجٌ (صعودₖ، هبوطₖ) وبقيّةٌ Bₖ معلَنة، وصعودₖ ∘ هبوطₖ =
الهويّة على مرصودها. **فبالاستقراء**: الأساسُ ط١–ط٣ (الرمزُ حقنٌ على ١١٢ خانة:
رتبُ الحروف مختلفة، ورتبُ الأحوال مختلفة، والرمزُ ضمٌّ لهما)؛ والخطوةُ: إن حُفظ
ما تحت k وحُفظت k فوقه، حُفظ التركيب. فالمصحفُ = صعود(البتّات، B₄…B₇). **والبرهانُ
بالإنشاء؛ والفحوصُ تشهد أنّ الآلةَ هي البرهان** — لا دعوى لغويّة فيها.
**والدعاوى اللغويّة** أربع: أنّ الخاناتِ كلَّها مستعملة (جامعٌ في الوحدة)، وأنّ
الألفاظَ كلَّها تُبنى بلا ذرّاتٍ تقريبًا (جامعٌ في اللفظ)، وأنّ المخلوطَ يُرفض
بالعوامل وحدها، ثمّ بمخزن الجذور (مانعٌ في اللفظ).

**وتوقّعي بالتفكير**: فحوصُ الحفظ كلُّها تثبت، والسلّمُ يبلغ ط٧؛ وح٢ يثبت؛ وح٤
يثبت؛ **وح٥ يسقط** (الخانةُ تقبل أيَّ حرفٍ بحاله، فالشكلُ وحده لا يمنع)؛ وح٦ يثبت
(مخزنُ الجذور يمنع ما لم يُعهد).
"""

