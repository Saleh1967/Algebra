"""**ختمٌ قبل النظر**: الاتّجاهُ في البتّات — نقلٌ وسهمُ زمنٍ، بلا اسم.

**لم يُشغَّل شيءٌ بعد.**

**السؤالُ المطروح**: سُئِلتُ عن الفاعليّة والمفعوليّة والسببيّة
والمسبَّبيّة. **وهذه أسماءُ أبوابٍ لا تُشتَقّ من البايتات**، ولا أوقّعها.
**ولها صورةٌ في البتّات لا تحتاج اسمًا**، وهي المقيسُ ههنا وحدَها:

- **أيُّ المجريين يُنبئ عن الآخر؟** — ولها مقدارٌ مُعرَّفٌ: **النقل**
  `T(أ ⟶ ب) = I(بₜ ؛ أₜ₋₁ | بₜ₋₁)` — ما يزيده ماضي `أ` على ماضي `ب`
  **في التنبّؤ بـ`ب`**. **وهو ليس السببيّة**: لا تدخّلَ في نصٍّ مجمَّد،
  **فلا تُشتَقّ سببيّةٌ من ارتباطٍ مهما بلغ**. وهذا **مكتوبٌ قبل النظر**.

- **وأللنصّ سهمٌ في بتّاته؟** — يُقاس **بقلب ترتيب السطر** وإعادة القياس.
  فإن تساوى المقيسان **فلا سهمَ في البتّات**، وإن اختلفا **فالاختلافُ
  نفسُه هو السهم**، ويُنشَر بمقداره.

**والمجريان مأخوذان من المجمَّد وحدَه**: `ح` حالُ خاتمة اللفظ (ثمانُ
خانات)، و`ر` حرفُ خاتمته. **ولا قائمةَ مُودَعةٌ ولا اسمُ بابٍ ولا اسمُ
علامةٍ ولا اسمُ يونيكود** — المحرفُ **شريحةٌ ونقطةُ ترميز**.

**ولا تسريبَ من الموضع إلى نفسه**: كلُّ نقلٍ يُقاس عن **الماضي** فقط،
وماضي الهدف **مطروحٌ بالشرط** لا مُهمَل. فما يبقى **زيادةُ الجار على
نفسِه**، لا مجموعَ ما بينهما.

**والصفريُّ مُبدَّل**: التقديرُ الساذجُ للنقل **منحازٌ إلى الموجب دائمًا**،
فيُقابَل بعشرين تبديلًا يحفظ الهوامشَ ويهدم الجوار، **ويُنشَر مجالُ ثقةٍ لا
نقطة**. **وما لم يجاوز الصفريَّ لا يُقال إنّه نقل.**

**والمحجوزُ هو الحكم**: النقلُ الملحَقُ **يربح دائمًا** بحكم الانحياز، فلا
خبرَ فيه. **فالحكمُ على شقٍّ لم يُقدَّر عليه**، بتنعيم لابلاس وبالتبادل.

**والقناتان لا تُقابَلان خامًا**: أبجديّةُ `ح` ثمانٍ وأبجديّةُ `ر` أوسع،
فالمقابلةُ **بنصيبٍ من إنتروبيا الهدف** لا ببتّاتٍ مطلقة. **وهذا مكتوبٌ
قبل النظر كي لا يُقارَن ما لا يُقارَن.**

**وinduction on**: مبرهناتٌ مُصانةٌ عند كلّ حال: `I ≥ ٠`، والشرطُ لا يرفع
الإنتروبيا، و`log₂ التباديل ≤ N·H`. **وinduction FOR**: الحلقةُ تشهد
عليها **سطرًا سطرًا** وتُقابِل العدّاداتِ بالأسطر، **وطرفاها بعد ألفِ لفظ**.

**وحدُّ اللفظ هو المُصحَّح** من `494465d1…`. **ولا يُعاد الخطأُ الثالثُ
والعشرون.**
"""

