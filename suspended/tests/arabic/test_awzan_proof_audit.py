"""برهانُ الوزن: **الجبرُ كسبٌ، و«الجامعُ المانع» يسقط في الجهتين**.

`THE_KEY_ALGEBRA_IS_THE_REAL_FIND`: ويُقرّ أوّلًا وأقواه: قراءةُ المزيدات
**تراكيبَ مفاتيحَ** لا فهرسًا — **V = تاء + II**، و**VI = تاء + III** —
كسبٌ بنيويٌّ حقيقيّ: يردّ عشرةَ أوزانٍ إلى مفاتيحَ أقلّ، **ويولّد بدل أن
يعدّ**. وهو أوّلُ موضعٍ في السلسلة تُقترح فيه بنيةٌ توليديّةٌ صريحة.

`BUT_THE_KEY_COMPOSES_ONLY_WHERE_A_LIST_PERMITS`: غير أنّ التاء تتركّب مع
II وIII **ولا تتركّب مع IV**: «تأفعل» ليس وزنًا. فالتوليدُ يحتاج **قاعدةَ
منعٍ** ليست في الإيداع — وبدونها فالمُولِّدُ يُنتج ما ليس في W، والمانعُ هو
القائمةُ التي قيل إنّها استُبدلت. فالبنيةُ توليديّةٌ **بقيدٍ فهرسيّ**.

`THE_SPACE_IS_FIFTEEN_ONLY_BY_FOLDING_TWO_BLOCKS`: و«١٥ وزنًا» تطوي طيّتين:
**المجرّدُ بأبوابه الستّة وزنًا واحدًا**، و**XI–XV كتلةً واحدة**. فإن كانت
الستّةُ أبوابًا متمايزةً والخمسةُ أوزانًا، فالفضاءُ **٦+٩+٤+٥ = ٢٤**،
والخاناتُ **١٩٢** لا ١٢٠. وإن كانتا كتلتين فالعدُّ يجمع **أعيانًا إلى
أصناف** — وهي صورةُ عطلِ الوحدات الخامسة، وبنيةُ «خمسةِ صفوفٍ وستِّ مديات»
بعينها.

`AND_THE_FOLD_DESTROYS_WHAT_A_LATER_LAW_NEEDS`: والأخطر أنّ الطيّةَ الأولى
**تُتلف ما يحتاجه §٣**: «الأمرُ من المضارع بحذف حرف المضارعة وتحريك» —
والتحريكُ **يتعيّن بالباب**: اُكْتُبْ بالضمّ، اِضْرِبْ بالكسر، اِفْتَحْ
بالفتح. فالأبوابُ الستّةُ طُويت في §١ **وهي مُعيِّنُ الحركة في §٣**.

`THE_AXIS_IS_NOT_EXHAUSTIVE`: و«لا خامسَ» تسقط بالمدوّنة: **«وغلَّقتِ
الأبوابَ»** — II تكثيرًا لا تعديةً؛ **«حين تُمسون وحين تُصبحون»** — IV
دخولًا في الوقت؛ **«واستكبر»** (٢٨ موضعًا) — X اعتقادًا لا طلبًا. ثلاثُ
دلالاتٍ **خارج محور التعدية** جملةً.

`AND_IT_IS_NOT_DISJOINT_EITHER`: و«مانعٌ» تسقط كذلك: **«هذان خصمان
اختصموا»** — VIII **مشاركةً**، و«فانفلق» VII مطاوعةً؛ وX في **«فاستغفروا»**
طلبًا وفي **«واستكبر»** اعتقادًا. فالوزنُ الواحدُ يقع في أكثرَ من خانة.

`A_FORM_MAPS_TO_A_SET_OF_FUNCTIONS_AND_THAT_IS_A_RELATION`: وهذه **نفسُ
النتيجة** التي خرجت من تشغيل π_اشتقاقي: صيغةٌ تُعطي **مجموعةً** من
الوظائف لا واحدة. فالمُودَعُ الثاني علاقةٌ كالأوّل — **مرّتان في تسليمين
متعاقبين**، والعطلُ واحد: دالّةٌ تُعلَن وعلاقةٌ تُسلَّم.

`THE_INVOLUTION_HOLDS_WHERE_IT_IS_EMPTY`: و«V² = هوية» صادقةٌ على
**الصيغتين** (فَعَلَ ⟷ فُعِلَ) وهي هناك تحصيلُ حاصل؛ وكاذبةٌ حيث تُفيد:
البناءُ للمجهول **يحذف الفاعل**، فـ«ضُرِبَ عمرٌو» صورةُ «ضرب زيدٌ عمرًا»
و«ضرب بكرٌ عمرًا» معًا — **غيرُ متباينة، فلا عكسَ لها**. والانقلابُ الذاتيُّ
يقتضي التباين.

`AND_THE_FULL_COUNT_IS_ASSERTED_NOT_EXHIBITED`: و«١٠٢ + ١٨ = ١٢٠ بالعدّ
التامّ» **لا جدولَ لها في الإيداع**: §٤ تقول «خانةً خانة» ولا خانةَ مكتوبة.
فالجمعُ صحيحٌ والعدُّ غيرُ معروض — وهو عطلُ «عددٍ يحمل قانونًا بلا مصدر».

`AND_IT_DOES_NOT_MEET_ITS_OWN_SPECIFICATION_FOR_PI_SARFI`: وأخيرًا
`projection_specs.md` §٣ تشترط لـπ_صرفي «جدولَ التفعيلات المعلَن **+ قواعدَ
مطابقةٍ تصرّح بالإدغام والإعلال**» — و«إدغام» و«إعلال» **لا تردان في وثيقة
الأوزان ولا مرّةً واحدة**. فلا تقوم مقامَ الإيداع الثاني بشرطِ كاتبها نفسِه،
والطبقةُ الصرفيّةُ تبقى `UNREACHABLE` بنصّ صاحبها.
"""

from __future__ import annotations

import re
from pathlib import Path

from frozen_corpus import CORPUS, requires_corpus

REPOSITORY = Path(__file__).resolve().parents[2]
AWZAN = REPOSITORY / "deposits" / "awzan_proof.md"
SPECS = REPOSITORY / "deposits" / "projection_specs.md"
MARKS = re.compile(r"[ً-ْٰـ]")

FOLDED = {"أبواب المجرّد": 6, "نوادر XI–XV": 5}
UNFOLDED = 6 + 9 + 4 + 5
CELLS = 8
PUBLISHED_FORMS = 15
PUBLISHED_CELLS = 120

OFF_AXIS = {
    "II تكثيرًا": "وغلقت الأبواب",
    "IV دخولًا في الوقت": "حين تمسون وحين تصبحون",
    "X اعتقادًا": "استكبر",
}
OVERLAPPING = {"VIII مشاركةً": "خصمان اختصموا", "X طلبًا": "فاستغفروا لذنوبهم"}
IMPERATIVE_VOWEL = {"كتب": "ضم", "ضرب": "كسر", "فتح": "فتح"}


def _bare() -> list[str]:
    return [
        MARKS.sub("", line) for line in CORPUS.read_text(encoding="utf-8").splitlines()
    ]


def _attested(needle: str) -> int:
    return sum(1 for line in _bare() if needle in line)


def test_the_published_space_folds_two_blocks_into_single_forms() -> None:
    """١٥ = ١ + ٩ + ٤ + ١، والمطويُّ ستّةُ أبوابٍ وخمسةُ نوادر."""

    assert 1 + 9 + 4 + 1 == PUBLISHED_FORMS
    assert PUBLISHED_FORMS * CELLS == PUBLISHED_CELLS
    assert UNFOLDED == 24
    assert UNFOLDED * CELLS == 192 != PUBLISHED_CELLS
    assert sum(FOLDED.values()) == 11  # المطويّاتُ إحدى عشرةَ صيغة


def test_the_fold_removes_what_the_imperative_rule_needs() -> None:
    """حركةُ همزة الوصل تتعيّن بالباب، والأبوابُ طُويت قبلَ القانون."""

    assert len(IMPERATIVE_VOWEL) == 3
    assert len(set(IMPERATIVE_VOWEL.values())) == 3  # ثلاثُ حركاتٍ لا واحدة
    assert FOLDED["أبواب المجرّد"] == 6 > len(IMPERATIVE_VOWEL)


def test_the_composition_key_is_blocked_without_a_stated_rule() -> None:
    """تاء + II وتاء + III موجودان، وتاء + IV ليس وزنًا — والمنعُ غيرُ معلن."""

    composes = {("تاء", "II"): "تفعّل", ("تاء", "III"): "تفاعل"}
    blocked = ("تاء", "IV")
    assert len(composes) == 2
    assert blocked not in composes
    text = AWZAN.read_text(encoding="utf-8")
    assert "تأفعل" not in text  # والممنوعُ لا يُسمّى فلا يُمنَع بقاعدة


@requires_corpus
def test_the_transitivity_axis_is_not_exhaustive() -> None:
    """ثلاثُ دلالاتٍ خارجَ المحور، كلُّها مشهودة."""

    for witness in OFF_AXIS.values():
        assert _attested(witness) >= 1
    assert _attested("استكبر") == 28
    assert len(OFF_AXIS) == 3


@requires_corpus
def test_the_five_operations_are_not_disjoint() -> None:
    """VIII مشاركةً ومطاوعةً، وX طلبًا واعتقادًا — فالخاناتُ متداخلة."""

    for witness in OVERLAPPING.values():
        assert _attested(witness) >= 1
    assert _attested("فانفلق") == 1  # VII مطاوعةً بإزاء VIII مشاركةً
    forms = {"VIII": {"مطاوعة", "مشاركة"}, "X": {"طلب", "اعتقاد"}}
    for senses in forms.values():
        assert len(senses) == 2 > 1  # صيغةٌ ⟼ مجموعةُ وظائف


def test_the_passive_is_not_injective_so_it_is_not_an_involution() -> None:
    """«ضُرِبَ عمرٌو» صورةُ أكثرَ من أصل — فلا عكسَ ولا انقلابَ ذاتيّ."""

    preimages = {"ضرب زيدٌ عمرًا", "ضرب بكرٌ عمرًا", "ضرب خالدٌ عمرًا"}
    image = "ضُرِبَ عمرٌو"
    assert len(preimages) == 3 and len({image}) == 1
    assert len(preimages) > 1  # والانقلابُ الذاتيُّ يقتضي التباين
    patterns = {"فَعَلَ", "فُعِلَ"}
    assert len(patterns) == 2  # وعلى الصيغتين وحدَهما يصدق تحصيلَ حاصل


def test_the_full_count_is_asserted_without_its_table() -> None:
    """«١٠٢ + ١٨» جمعٌ صحيحٌ بلا خانةٍ معروضة."""

    text = AWZAN.read_text(encoding="utf-8")
    assert "١٠٢" in text and "١٨" in text
    assert 102 + 18 == PUBLISHED_CELLS
    assert "ماضٍ (معلوم/مجهول)" in text
    assert "| ماضٍ" not in text  # ولا جدولَ خلايا في الوثيقة


def test_it_does_not_meet_the_deposits_own_requirement_for_pi_sarfi() -> None:
    """الإيداعُ يشترط الإدغامَ والإعلال، والوثيقةُ لا تذكرهما."""

    required = SPECS.read_text(encoding="utf-8")
    assert "الإدغام والإعلال" in required
    supplied = AWZAN.read_text(encoding="utf-8")
    assert "إدغام" not in supplied
    assert "إعلال" not in supplied
