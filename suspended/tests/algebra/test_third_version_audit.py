"""النسخةُ ٣: **الشاهدُ يُقوَّى، والتدرّجُ والإغلاقُ يسقطان، وF12 يحتاج شرطًا**.

**لا مرفقَ ورد**؛ والمادّةُ مبنيّةٌ باليد.

`THE_PASSIVE_WITNESS_IS_RIGHT_AND_CAN_BE_MADE_STRONGER`: دعواكم «**الرفعُ
علامةُ جهةِ الحمل لا علامةُ الذات**» **صحيحة**، ومثالُها أضعفُ ممّا تحتمل.
فالنائبُ ليس المفعولَ وحدَه: «صِيمَ يومُ الجمعةِ» (ظرف)، «جُلِسَ جلوسٌ»
(مصدر)، و**«سِيرَ بالمريضِ»** — والنائبُ فيها **جارٌّ ومجرور**، مجرورٌ
لفظًا **مرفوعٌ محلًّا**. فالجهةُ تُسنَد و**لا علامةَ في اللفظ أصلًا**.
وهذا يقوّي الدعوى: لو كان الرفعُ علامةَ ذاتٍ لامتنع أن يقع على مجرور.

`BUT_THE_FOURTH_STEP_OF_F10_IS_NOT_A_VERB_CASE_AT_ALL`: وتدرّجُ `F10`
(حرّ → مقيَّد → معلَّق → **ملغى بالجرّ**): و**الجرُّ لا يدخل الأفعالَ
ألبتّة**. فالخطوةُ الرابعةُ من تدرّجٍ عن **زمن الفعل** مأخوذةٌ من مقولة
الاسم. وهو **عينُ عطل «٤ = ٤»**: اتّحادٌ عبر مقولتين يُقرَأ تدرّجًا في
واحدة — ثالثُ ظهورٍ له.

`AND_F10_CONTRADICTS_Q4_AS_F9_DID`: و«ملغى» تقتضي أنّ الزمنَ كان محمولًا
فأُلغي، والمجرورُ **لم يحمل زمنًا قطّ**. و`Q4` يقيم الفرقَ بين «إسقاطٍ
معلن» و«عدم حملٍ أصلًا» ويجعل الجامدَ من الثاني. فهذا **ثاني** تعارضٍ بين
فرضٍ من سلسلة `F` وبين `Q4` — بعد `F9` في الطبقة الرابعة. والنمطُ يتكرّر:
كلَّما أُريد بيتٌ ثالثٌ أو خطوةٌ رابعة، أُخِذ من صنفِ «لم يحمل».

`THE_FOUR_ROLES_DO_NOT_COVER_THE_INVENTORY`: و«أدوارٌ أربعة» تُقابَل
بعشرةِ منصوباتٍ مقرَّرة: مفعولٌ به · مطلقٌ · لأجله · فيه · معه · حال ·
تمييز · مستثنى · خبرُ كان · اسمُ إنّ. والموسومُ في المتن **اثنان** منها.
فإمّا تُردّ الثمانيةُ إلى «مفعوليّة» فيَفرغ الاصطلاحُ من تمييزه، وإمّا
**الإغلاقُ عند أربعةٍ لا يصحّ**. وهو الرابعُ من الأعداد الحاملة بلا إسناد.

`AND_THE_TALLY_CARRIES_A_NUMBER_ALREADY_CORRECTED`: والحصيلةُ «٨+٢+٢٨
و**٩**» — والتسعةُ صُحِّحت في الدورة الماضية إلى **اثنتَي عشرة** (بحذف
حرف العلّة والنيابتين). فالمجموعُ المنشورُ يحمل عددًا مصحَّحًا لم يُحدَّث.

`THE_TADMIN_EXAMPLE_IS_A_DIFFERENT_MECHANISM`: و«اللازمُ يتعدّى بالتضمين
(ذهبتُ به)»: و«ذهبتُ به» **تعديةٌ بحرف الجرّ** لا تضمينًا. والتضمينُ
إشرابُ الفعلِ معنى فعلٍ آخرَ فيأخذ حرفَه — كـ«ولا تأكلوا أموالهم **إلى**
أموالكم» (ضُمِّن الأكلُ معنى الضمّ). فالآليّتان تعيدان توجيهَ الحمل، وهما
**غيران**، والمثالُ موسومٌ بغير اسمه.

`F12_IS_THE_RIGHT_POSTURE_AND_STILL_NEEDS_ITS_REFUTER`: و`F12` — «لا رابعَ
يبقى مفتوحًا حتّى يرد نقيض» — **أحسنُ موقفٍ في السلسلة كلِّها**: أوّلُ
دعوى إغلاقٍ تُترَك قابلةً للنقض بدل أن تُؤكَّد. **ولكنّها بلا شرطِ نقض**:
لم يُقَل **ما الذي يُعَدّ رابعًا**. ودعوى لا يُعرَف ناقضُها **آمنةٌ
بالبناء** لا مفتوحة. فيُكتَب: «رابعٌ = وحدةٌ في طبقةٍ لا تُردّ إلى حاملٍ
ولا محمولٍ ولا حمل» — وإلّا فالانفتاحُ لفظيّ.

`AND_THE_CHAIN_GLUE_IS_OUR_OWN_REFINEMENT_ORDER`: و«الغراءُ السلساليّ —
الحالةُ في طبقةٍ هي الحاملُ في أختها» **يوافق بناءَنا حرفًا**: `π: Σ → Λ`
ثمّ `Λ` أبجديّةُ الطبقة التالية. وقولُكم «انضباطُ Δ هو قانونُ الحمل نفسُه»
أصدقُ جملةٍ في الوثيقة — وهو ما بُني في `markov_layers` قبل أن يُسمّى.
"""

from __future__ import annotations

VERB_CASES = ("رفع", "نصب", "جزم")
NOUN_ONLY = "جرّ"
DEPUTIES = (
    ("ضُرِبَ زيدٌ", "مفعولٌ به", True),
    ("سِيرَ بالمريضِ", "جارٌّ ومجرور", False),
    ("صِيمَ يومُ الجمعةِ", "ظرف", True),
    ("جُلِسَ جلوسٌ", "مصدر", True),
)
MANSUBAT = (
    "مفعولٌ به",
    "مفعولٌ مطلق",
    "مفعولٌ لأجله",
    "مفعولٌ فيه",
    "مفعولٌ معه",
    "حال",
    "تمييز",
    "مستثنى",
    "خبرُ كان",
    "اسمُ إنّ",
)
ROLES = ("فاعليّة", "مفعوليّة", "سببيّة", "مسبِّبيّة")
MAPPED = {"مفعولٌ به": "مفعوليّة", "مفعولٌ لأجله": "سببيّة"}
MARKER_INVENTORY_CORRECTED = 12


def test_the_fourth_step_of_the_gradation_is_not_a_verb_case() -> None:
    """الجرُّ لا يدخل الأفعال — فتدرّجُ زمنِ الفعل يأخذ خطوتَه من الاسم."""

    assert NOUN_ONLY not in VERB_CASES
    assert len(VERB_CASES) == 3
    gradation = (*VERB_CASES, NOUN_ONLY)
    assert len(gradation) == 4
    assert gradation[-1] == NOUN_ONLY  # والرابعةُ من مقولةٍ أخرى


def test_the_deputy_is_not_always_the_object_and_may_carry_no_marker() -> None:
    """«سِيرَ بالمريضِ»: نائبٌ مجرورٌ لفظًا مرفوعٌ محلًّا — والدعوى تقوى به."""

    kinds = {kind for _, kind, _ in DEPUTIES}
    assert len(kinds) == 4  # أربعةُ أجناسٍ للنائب لا جنسٌ واحد
    unmarked = [one for one, _, marked in DEPUTIES if not marked]
    assert unmarked == ["سِيرَ بالمريضِ"]
    # ولو كان الرفعُ علامةَ ذاتٍ لامتنع وقوعُه على مجرور
    assert len(unmarked) == 1


def test_four_roles_do_not_cover_ten_accusative_positions() -> None:
    """اثنان من عشرةٍ موسومان، وثمانيةٌ بلا دور — فالإغلاقُ عند أربعةٍ دعوى."""

    assert len(ROLES) == 4
    assert len(MANSUBAT) == 10
    assert len(MAPPED) == 2
    unassigned = [one for one in MANSUBAT if one not in MAPPED]
    assert len(unassigned) == 8
    assert "حال" in unassigned and "تمييز" in unassigned


def test_the_tally_repeats_a_number_already_corrected() -> None:
    """التسعةُ صُحِّحت إلى اثنتَي عشرة، والحصيلةُ تحمل التسعة."""

    published = 9
    assert MARKER_INVENTORY_CORRECTED > published
    assert MARKER_INVENTORY_CORRECTED - published == 3
    assert 4 + 4 + 3 == 11  # وحسابُ الجديد صحيحٌ في نفسه


def test_the_no_fourth_claim_needs_a_stated_refuter() -> None:
    """دعوى لا يُعرَف ناقضُها آمنةٌ بالبناء؛ فيُكتَب شرطُ الرابع."""

    triad = ("حامل", "محمول", "حمل")
    assert len(triad) == 3
    refuter = "وحدةٌ في طبقةٍ لا تُردّ إلى حاملٍ ولا محمولٍ ولا حمل"
    assert all(one in refuter for one in triad)
    stated_in_document = False
    assert not stated_in_document
