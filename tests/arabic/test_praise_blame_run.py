"""شُغِّل ختمُ `efb2eac8…`: **ثمانٍ من اثنتي عشرة — والأربعُ الساقطةُ خبر**.

`THE_FIRST_CONSEQUENCE_HELD_AND_IT_IS_THE_ONE_THAT_MATTERS`: ش٥ صمد.
حقلُ الحال **ينضغط انضغاطًا بيّنًا** عند الموضع التالي للصورة المُودَعة:
**١٫٨٦٣٨** بتًّا مقابلَ **٢٫٦١٠٦** عامّةً — نزولٌ **٠٫٧٤٦٨** بتًّا.
**فللصورة أثرٌ في البتّات**، وهذا لازمُ المسوّدة الأوّلُ وقد صمد.

`BUT_THE_COMPRESSION_IS_NOT_TOWARD_ONE_MARK`: ش٦ **سقط**. أغلبُ علامةٍ
في ذلك الموضع نصيبُها **٠٫٤٣٠٦** — **دون النصف**. وثانيتُها **«بلا
علامة»** بـ**٠٫٣٤٧٢**، وهما متقاربتان. **فالانضغاطُ إلى خانتين لا إلى
واحدة**، ودعوايَ أنّ «علامةً بعينها تغلب» **ساقطةٌ برقمها**.

`AND_THE_EFFECT_IS_ONE_POSITION_NOT_TWO`: ش٧ **سقط بفارقٍ ضئيل**:
**٠٫٣٩١٣** والحدُّ ٠٫٤٠. **وأهمُّ من سقوطه أنّ الخانةَ الغالبةَ تبدّلت**:
في الموضع التالي غلبت خانةٌ، وفي الثالث **غلبت غيرُها**؛ وإنتروبيا الثالث
**٢٫٤٠٤٨** — قريبةٌ من العامّة **٢٫٦١٠٦**، بعيدةٌ عن **١٫٨٦٣٨**. **فالأثرُ
موضعٌ واحدٌ لا موضعان**، كما نصَّ شرطُ السقوط حرفًا.

`AND_A_STRONG_EFFECT_IS_NOT_A_WIDE_ONE`: ش١٢ **سقط**:
`I(الحال ؛ بتّةُ الجوار)` = **٠٫٠٠٠٥٧٢** بتًّا والحدُّ ٠٫٠٠١.
**ولا تناقضَ بينه وبين ش٥**: الصورُ **٧٢ موضعًا من ٧٨٬٢٤٥**. فالأثرُ
**شديدٌ حيث يقع، ضئيلٌ في جملة الحقل**. **وشدّةُ الأثر ليست سعتَه**، ولا
يُقرأ أحدُهما على الآخر.

`AND_THE_LADDER_TURNS_AT_THE_THIRD_STEP`: ش١٠ **سقط**: ينزل المحجوزُ في
**ثلاثٍ** من أربعٍ لا في أربع. والدرجةُ التي انقلبت **د٣** — الصورةُ
**والموضعُ** معًا: ربحُها الملحَقُ **+٠٫٠٠٠٦** وربحُها المحجوزُ
**−٠٫٠٠٠١**. **فزيادةُ بتّةِ الموضع انتحالُ تقديرٍ لا خبرُ مادّة**،
وموضعُ انقلابها **حدُّ ما تحمله المادّة** لا حدُّ ما تحمله القراءة.

`AND_THE_NEIGHBOUR_CARRIES_FAR_MORE_THAN_THE_DEPOSITED_SHAPES_DO`: ود٤ —
وهي تضيف **حالَ الموضع السابق** — تربح على المحجوز **+٠٫٠٦٩٣** بتًّا،
أي **أكثرَ من مئةِ ضعفٍ** ممّا ربحته درجاتُ الصور الثلاثُ مجتمعةً
(٠٫٠٠٠٦ + ٠٫٠٠٠٣ − ٠٫٠٠٠١). **فجارُ الموضع يحمل عن حاله أكثرَ ممّا تحمله
هذه الصورُ كلُّها.**

`AND_ONE_DEPOSITED_SKELETON_CONFLATES_THREE_SLICES`: وهيكلٌ واحدٌ من
المُودَع حمل **ثلاثَ شرائحَ متمايزةٍ بالضبط** في تسعِ وقوعات. **والهيكلُ
لا يعيّن ضبطَه** — وهو **المقيسُ** المُودَع قبلُ في
`deposits/word_escalation_run.log`: **١٬٨٨٦** هيكلًا غامضًا تحمل
**٣٤٬٩٠٢** لفظًا = **٠٫٤٤٦١** من الكتلة. **ولا أكتب ههنا العددَ الذي
سقط**: ٢٬٠٩٩ كان معروضًا وقد نقضه القياسُ (ك٧)، والمقيسُ وحدَه يُروى.
**فمن الاثنين والسبعين موضعًا ما ليس من باب
المسوّدة أصلًا**، ولا أفصل بينها: **الفصلُ يحتاج قراءةً، والقراءةُ ليست
لي**.

`AND_THREE_DEPOSITED_SHAPES_ARE_NOT_IN_THIS_CORPUS`: ثلاثُ صورٍ مُودَعةٍ
**لا شاهدَ لها**، وتُطبَع **بأسمائها** في السجلّ. **ولا يُقال إنّها ليست
في العربية** — يُقال إنّها **ليست في هذا المجمَّد**، وشاهداها في المسوّدة
**شعرٌ لا آية** بنصِّ المسوّدة نفسِها.

`AND_THE_FOUR_READINGS_ARE_NOT_SEPARATED_HERE`: والمسوّدةُ تعطي للمخصوص
المتأخّر **أربعةَ أعاريب**. **ولا تفترق في البايتات ألبتّة**: الحروفُ
واحدةٌ والعلاماتُ واحدة. **فلا يرجّح هذا القياسُ بينها، ولا يُدَّعى أنّه
يرجّح** — والمسوّدةُ **غيرُ موقَّعةٍ** ولم تُوقَّع بهذا التشغيل.
"""

