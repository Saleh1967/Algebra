"""**ختمٌ قبل النظر**: كم من العلامة الأخيرة **يحدّده اللفظُ نفسُه**؟

**لم يُشغَّل شيءٌ بعد.**

**لِمَ هذا التشغيل — وهو تحسينُ القراءة لا زيادةُ رقم**: كلُّ جسرٍ في
`docs/جسر-البتّات.md` معلَّقٌ على **جدولٍ لم يُودَع**، فالقراءةُ موقوفةٌ
كلُّها. **وثمّةَ ما يُحسِّنها من البايتات وحدَها**: أن يُفصَل ما يحدّده
**اللفظُ في نفسه** عمّا يُضيفه **جارُه**.

**والفصلُ يَحُدُّ القراءةَ حدًّا**: إن كانت العلامةُ الأخيرةُ مُحدَّدةً
بصورة اللفظ نفسِها فهي **من بنيته**، ولا يبقى للجار — ولا لأيّ حكمٍ
تركيبيّ — إلّا ما بقي **بعد** معرفة الصورة. **فالباقي سقفٌ على كلّ قراءةٍ
تركيبيّة، معدودٌ بالبتّات.** وهذا ما يُقاس ههنا، ولا يُقاس غيرُه.

**والمتغيّراتُ كلُّها شرائحُ من المجمَّد**:

- **(ه)** صورةُ اللفظ **منقوصةَ علامتِه الأخيرة**: يُحذَف آخرُ محرفٍ إن كان
  صنفُه `Mn`، وإلّا فاللفظُ كما هو. **ولا تسريب**: الصورةُ نفسُها لا تحمل
  المحذوف، ولفظٌ بلا علامةٍ يعطي الصورةَ عينَها التي يعطيها لفظٌ بعلامة.
- **(ج)** الهيكلُ **مجرَّدًا من كلّ علامة** — أخشنُ من (ه) بحكم البناء.
- **(ر)** حالُ اللفظ السابق، وقيمةٌ مُعلَنةٌ «بدء» لأوّل السطر.

**وماركوف**: (ج) **تكتيلٌ** لـ(ه) بحكم البناء، فالمعلوماتُ عليه **لا
تزيد** مبرهنةً (تراجعُ المعلومات). و(ه، ر) **تنقيحٌ** لـ(ه) فالإنتروبيا
الملحَقةُ **لا ترتفع**. **وinduction on** هاتان المبرهنتان، **وinduction
FOR** الحلقةُ تشهد عليهما في كلّ مقارنةٍ لا في واحدة.

**والمحجوزُ هو الحكم، والملحَقُ يُعرَض حدًّا أعلى لا أكثر**: فضاءُ (ه)
واسعٌ، **وتقديرُ المعلومات داخلَ العيّنة عليه منتفخٌ بالضرورة**. فالدعاوى
كلُّها على **المحجوز**، ويُعرَض الملحَقُ إلى جانبه **مُسمًّى منتفخًا** كي
لا يُقرَأ قياسًا.

**والخانةُ الغامضةُ تُشقَّق بالبايتات**: خانةُ «بلا علامة» نصيبُها
`٠٫٣١٠٨` وهي أكبرُ الخانات، **وتُقسَم بحرف خاتمتها** — وذلك فحصُ بايتاتٍ
لا تفسيرٌ نحويّ. فتصير الفجوةُ **مُسمّاةً بأقسامها** لا كتلةً واحدة.

**والمسندُ واحدٌ يُصرَّح به**: كلُّ مقدارٍ ههنا على **٧٨٬٢٤٥** لفظًا،
**ولا يُطرَح مقدارٌ من مقدارٍ على غيره** — كما أوجب العطل ٢٤.

**وما لا يُدَّعى، ويُكتَب قبل النظر**: هذا **لا يُسمّي بابًا ولا حكمًا**،
ولا يُثبِت أنّ الباقي بعد الصورة **إعرابٌ**. يقيس **مقدارًا**: ما تحدّده
الصورةُ، وما يزيده الجار بعدها. **والتسميةُ فعلُ صاحب المستودع.**
"""

