from __future__ import annotations

import importlib.util
import math
import sys
from pathlib import Path

from frozen_corpus import CORPUS, requires_corpus

REPOSITORY = Path(__file__).resolve().parents[2]
READER = REPOSITORY / "examples" / "rasm" / "run_cv_peel.py"

pytestmark = requires_corpus

UNITS = 364_747
RASM = 332_837
SHADDA_COUNT = 23_016
TANWIN_COUNT = 8_894
ALPHABET = 112
UNIT_ENTROPY = 5.5818
LEDGER = {
    "حامل": (65_641, 1.6813, 0.5563),
    "مربوطة": (17_306, 0.5722, 0.4352),
    "سكون": (118_095, 0.9005, 0.2739),
    "تنوين": (12_994, 0.9073, 0.7940),
    "شدّة": (27_580, 0.6473, 0.2445),
}
RESIDUE_BITS = 93_453
BODY_BITS = 2_035_933


def _reader() -> object:
    spec = importlib.util.spec_from_file_location("run_cv_peel", READER)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


def test_the_round_trip_is_byte_exact_on_the_whole_corpus() -> None:
    """`rebuild(peel(x)) == x` — والدعوى تُفحَص على البايتات لا على الوصف."""

    reader = _reader()
    raw = CORPUS.read_text(encoding="utf-8")
    units, extras = reader.peel(raw)  # type: ignore[attr-defined]
    assert reader.rebuild(units, extras) == raw  # type: ignore[attr-defined]


def test_the_induction_on_length_is_run_verse_by_verse() -> None:
    """كلُّ آيةٍ تُقشَّر وحدَها وتُعاد — الأساسُ والخطوةُ مفحوصان."""

    reader = _reader()
    lines = CORPUS.read_text(encoding="utf-8").splitlines()
    assert len(lines) == 6_236
    for line in lines:
        units, extras = reader.peel(line)  # type: ignore[attr-defined]
        assert reader.rebuild(units, extras) == line  # type: ignore[attr-defined]


def test_the_alphabet_is_exactly_one_hundred_and_twelve() -> None:
    """٢٨ × ٤، ولا وحدةَ خارجَها — فالعُريُ سكونٌ لا فراغ."""

    reader = _reader()
    units, _ = reader.peel(CORPUS.read_text(encoding="utf-8"))  # type: ignore[attr-defined]
    cv = [one for one in units if one[0] != reader.STRUCTURE]  # type: ignore[attr-defined]
    assert len(cv) == UNITS
    assert len(set(cv)) == ALPHABET == 28 * 4
    bases = {base for base, _ in cv}
    assert len(bases) == 28


def test_the_expansion_closes_with_no_remainder() -> None:
    """٣٣٢٬٨٣٧ + ٢٣٬٠١٦ + ٨٬٨٩٤ = ٣٦٤٬٧٤٧ — فلا ابتلاعَ ولا اختراع."""

    assert RASM + SHADDA_COUNT + TANWIN_COUNT == UNITS


def test_the_declared_ceiling_of_one_hundred_and_twelve_is_tight() -> None:
    """H = ٥٫٥٨١٨ دون log₂(112) = ٦٫٨٠٧٤، والأبجديّةُ ١١٢ فالسقفُ محكَم."""

    assert UNIT_ENTROPY < math.log2(ALPHABET)
    assert abs(math.log2(ALPHABET) - 6.8074) < 5e-5
    assert math.log2(len({1}) * ALPHABET) == math.log2(ALPHABET)  # سقفُ المرصود نفسُه
    assert math.log2(196) > math.log2(ALPHABET)  # والأوّلُ فضفاضٌ فوقَ ذلك


def test_the_residue_channels_are_measured_at_decision_sites() -> None:
    """مواضعُ القرار لا مواضعُ الوقوع — وإلّا خرج صفرٌ كاذب."""

    reader = _reader()
    units, extras = reader.peel(CORPUS.read_text(encoding="utf-8"))  # type: ignore[attr-defined]
    total = 0.0
    for key, (places, plain, inside) in LEDGER.items():
        seen, measured_plain, measured_inside = reader.conditioned(units, extras, key)  # type: ignore[attr-defined]
        assert seen == places, key
        assert abs(measured_plain - plain) < 5e-4, key
        assert abs(measured_inside - inside) < 5e-4, key
        total += measured_inside * seen
    assert abs(total - RESIDUE_BITS) < 1.0
    # ولا قناةَ صفرٌ بعد التصحيح
    assert all(inside > 0.2 for _, _, inside in LEDGER.values())


def test_the_script_is_ninety_six_percent_phonetic_by_the_ledger() -> None:
    """٩٣٬٤٥٣ بقيّةً من ٢٬١٢٩٬٣٨٦ — فنصيبُها ٠٫٠٤٣٩."""

    share = RESIDUE_BITS / (BODY_BITS + RESIDUE_BITS)
    assert abs(share - 0.0439) < 5e-4
    assert share < 0.05
    heaviest = max(LEDGER.items(), key=lambda pair: pair[1][0] * pair[1][2])
    assert heaviest[0] == "حامل"  # كرسيُّ الهمزة أثقلُ الاصطلاح


def test_the_context_removes_more_than_half_the_residue() -> None:
    """H₀ مجموعةً فوقَ الضعف — فأكثرُ اصطلاح الرسم مشتقٌّ من جواره."""

    plain = sum(places * value for places, value, _ in LEDGER.values())
    inside = sum(places * value for places, _, value in LEDGER.values())
    assert plain > 2 * inside
    assert abs(inside - RESIDUE_BITS) < 5  # الجدولُ بأربع خانات، فالفرقُ تقريبُ نشر
