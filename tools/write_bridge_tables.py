"""جداولُ الجسر: **تُودَع بتفويضٍ فتُرخِّص القراءةَ، وتبقى فرضًا يُنقَض**.

`A_TABLE_IS_WHAT_TURNS_A_READING_INTO_A_TESTABLE_CLAIM`: كلُّ عائلةٍ في
`docs/جسر-البتّات.md` كانت معلَّقةً على جدولٍ لم يُودَع، **فكانت القراءةُ
لا تُكذَّب لأنّ أحدًا لم يقلها**. وهذه الجداولُ تقولها: تُسنِد **نقطةَ
ترميزٍ** إلى **حكمٍ مُعلَن**، ومعه **استثناؤه المُعلَن**. فتصير القراءةُ
**لازمًا يُقاس ويسقط إن سقط**.

`AND_THE_CODEPOINTS_ARE_SLICED_NOT_TYPED`: مفاتيحُ الجداول **سداسيّةٌ**
(`064F`) لا حروفٌ مكتوبة، **والشريحةُ والعددُ يُقرآن من سجلٍّ مُودَع**.
فلا يدخل الجدولَ حرفٌ عربيٌّ كُتِب بيد — **وذلك المادّة ٩**.

`AND_EVERY_ROW_CARRIES_ITS_OWN_EXCEPTION`: ولا يُودَع حكمٌ بلا استثناءٍ
مُعلَن. **فجدولٌ بلا استثناءاتٍ دعوًى لا تُنقَض**: من قال «الضمّةُ رفعٌ»
ولم يقل «وترفَع المضارعَ كما ترفَع الفاعل» فقد أودع ما لا يُكذَّب. **فكلُّ
صفٍّ يحمل ما يُبطِله**، والبناءُ يردُّ صفًّا بلا استثناء.

`AND_THE_TABLE_IS_A_HYPOTHESIS_NOT_A_TRANSMISSION`: **وليس هذا نقلًا عن
عالمٍ ولا عن راوٍ**، ولا يُنسَب إلى أحد. هو **فرضٌ إسناديٌّ أوّليٌّ**
أُودِع بتفويضٍ كي يُقاس — ومن أراد جدولَ بابٍ منقولًا بإسنادٍ فليودِعه،
**فيُقابَل هذا به ويسقط أيُّهما خالف المقيس**.
"""

