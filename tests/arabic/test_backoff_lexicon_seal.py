"""**ختمٌ قبل النظر**: الإصلاحاتُ الثلاثة لقرار الضمير — ياءُ المثنّى، والصيغةُ
المعربة، والتراجع.

**لم يُعَدّ شيءٌ بهذه القاعدة بعد.** وقال صاحبُ المستودع: «اختم قبل العد».

**العِلّة**: ثبت في ختم b904a9f9 مانعُ التاء المربوطة، وبلغ الكاملُ ٠٫٩٣٢٠ وسقط دون
٠٫٩٥؛
وتشخيصُ أخطائه الـ٦٩٣ بعد التشغيل: ٥٠٥ جذعٌ نادر، و١٢٨ جذعٌ معروفٌ بلا ضمير
(«إِلَهَ» ⟵
«إِلْ»)، و٤٩ ياءٌ ساكنةٌ مكتوبة قبل الضمير (المثنّى). **والإصلاحات**:

1. **ياءُ المثنّى**: الياءُ الساكنةُ المكتوبة بعد فتحة («ـَيْـ») تجوز قبل الضمير.
2. **الصيغةُ المعربة**: الجذعُ لا يُعَدّ واردًا بلا لاحقةٍ إلّا إذا ورد لفظًا تامًّا
   آخرُه حركةُ
   إعراب (فتحةٌ أو ضمّةٌ أو كسرة)؛ فـ«إِلْ» الساكنةُ لا تُثبت «إِلَه» جذعًا.
3. **التراجع (back-off)**: إذا لم يثبت الجذعُ بلاحقتين، يُحكم بمعدّل الضمير نفسه في
   المعجم:
   كم مرّةً كان لفظٌ منتهٍ به (بشروطه) ذا جذعٍ ثابت — فإن بلغ النصفَ اختير.

**وتوقّعي بالتفكير**: يرتفع الكاملُ إلى ٠٫٩٥ فأكثر؛ ويبقى الفوريُّ دون ٠٫٩٥ منه أو
عنده، لأنّ
التراجعَ يحتاج معدّلًا مرّ؛ ولا تزيد أخطاءُ «ضميرٍ حيث لا ضمير» على ١٢٨ رغم التراجع.
"""

