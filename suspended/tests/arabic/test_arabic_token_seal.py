def test_the_seal_is_recomputed_from_the_written_conditions() -> None:
    """البصمةُ تُشتَقّ من الشروط لا تُنقَل."""

    assert seal(ORACLE, PREDICTIONS) == DIGEST


def test_the_arithmetic_and_the_unknown_are_separated_before_the_run() -> None:
    """ما يُحسَب بالطرح لا يُدَّعى تنبّؤًا — والقسمةُ مكتوبةٌ قبل النظر."""

    subtraction = {"ط٢", "ط٣", "ط١٠", "ط١١"}
    for one in PREDICTIONS:
        if one.identifier in subtraction:
            assert "طرح" in one.falsifies, one.identifier
    unknown = {"ط٦", "ط٧", "ط٨", "ط٩", "ط١٢"}
    assert not subtraction & unknown
    assert __doc__ is not None
    assert "كي لا يُدَّعى التنبّؤُ لما هو طرحٌ" in " ".join(__doc__.split())


def test_the_two_proven_bounds_are_taken_past_the_trivial_extreme() -> None:
    """ط٤ وط٥ بعد ألفِ لفظ — لا عند أوّل الحلقة حيث الحقلُ خانةٌ واحدة."""

    for identifier in ("ط٤", "ط٥"):
        found = next(one for one in PREDICTIONS if one.identifier == identifier)
        assert "بعد ألفِ لفظ" in found.statistic
    assert "بعد ألفِ لفظٍ لا عند أوّل الحلقة" in " ".join(ORACLE.extraction.split())


def test_the_first_seal_is_not_reinterpreted() -> None:
    """السجلُّ الأوّلُ يبقى، والشرطُ التاسعُ ساقطٌ ويبقى ساقطًا."""

    assert __doc__ is not None
    assert "لا يُحذَف ولا يُعاد تفسيرُه" in __doc__
    assert "ساقطٌ ويبقى ساقطًا" in __doc__
