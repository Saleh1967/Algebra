"""«الشاهد» مُشغَّلًا: فرقُ إحلالٍ من الرسم وحدَه، بخمسة شروطٍ مختومةٍ قبله.

**ما يفعله هذا المُشغِّل**: يقرأ محاذاةً عمودُها `loc` و`surface`، ويبني
**شاهدَ الإحلال** — عقدتان جارتان إن وقعتا في إطارٍ محليٍّ واحدٍ بعينه
(السابقُ واللاحقُ أنفسُهما لفظًا) — ثمّ يقيس الشروطَ الخمسةَ المُسجَّلةَ في
`df8fe34a88bbf641e554f2ca923ac17f8c4c355691a109261bbe3a9b8c06ba07`.

`THE_BYTES_ARE_CHECKED_AGAINST_A_DECLARED_DIGEST_NOT_TRUSTED`: ويُرَدّ
التشغيلُ إن خالفت بصمةُ الملفّ ما أُعلِن في `--digest`، أو خالف عددُ صفوفه
`--closure`. فالسطحُ المشتقُّ في مكانٍ آخرَ **مدوّنةٌ أخرى**، ولا يُعرَف ذلك
إلّا ببصمةٍ تُقارَن. والانضمامُ على مفتاحٍ من مدوّنتين انضمامُ هواء.

`THE_SURFACE_KIND_IS_A_DECISION_NOT_A_DEFAULT`: و«أرسمٌ خامٌ أم مخرَجُ
تطبيعٍ؟» قرارٌ يبدّل كلَّ رقمٍ بعده، فلا افتراضيَّ له: يُعلَن بـ
`--surface-kind` أو يُرَدّ التشغيل.

`THE_CLASS_ASSIGNMENT_IS_AN_INPUT_NOT_A_GUESS`: وأصنافُ السابق واللاحق
الخمسةُ مُسمّاةٌ في الختم، وأمّا **إسنادُ لفظٍ إلى صنفه** فمُدخَلٌ يُعلَن
بـ`--classes`. ولا يُخمَّن ههنا: تخمينُه يجعل الرقمَ خبرًا عن مخمِّنه.
وشرطُ ش٣ هو فحصُ هذا المُدخَل نفسِه: إن ابتلع «سواه» أكثرَ من النصف فالتوقيعُ
بتّةٌ واحدةٌ اسمُها «ليس من الأربعة».

`ONE_KEY_AND_TWO_SEALED_SURFACES`: ويُسمّى **العمودُ** بـ`--column`، وتُطبَع
بصمتُه وحدَه إلى جانب بصمة الملفّ. فرسمٌ خامٌ ينضمّ بايتًا ببايتٍ إلى وسمٍ
خارجيّ، ومخرَجُ تطبيعٍ مشتقٌّ منه، **يسكنان ملفًّا واحدًا بمفتاحٍ واحد**
ولكلٍّ بصمة. وبذلك لا يكون عمودٌ واحدٌ نقطةَ سقوطٍ لبندين.

`WHAT_IS_DESCRIBED_AFTER_THE_FACT_IS_NOT_A_CONDITION`: وتُطبَع في صدر
النتيجة **مقاماتٌ وأوصافٌ مُعلَنةٌ لا شروط**: عددُ العقد، ونصيبُ العقد التي
لها حافّةٌ أصلًا، ووسيطُ الدرجة ومتوسّطُها، وأعلى إطارٍ تركُّزًا، وإنتروبيا
أحجام الفرق، ومجالُ ثقةٍ بمعاودةٍ مجمَّعةٍ على العقد. ولا يدخل شيءٌ منها
الختمَ: الوصفُ البعديُّ جائزٌ مُعلَن، والشرطُ البعديُّ محرَّم.

`THE_HALF_THAT_HAS_NO_WITNESS_AT_ALL_IS_A_DENOMINATOR`: وأخفى المقامات:
عقدةٌ بلا حافّةٍ لا تدخل ش١ ألبتّة. فإن كان وسيطُ الدرجة صفرًا فنصفُ
المفردات **خارج القياس**، والرقمُ خبرٌ عمّن له شاهدُ إحلالٍ لا عن العربيّة
كلِّها. فيُطبَع نصيبُهم مع كلّ رقم.

`ONE_ESTIMATOR_FOR_BOTH_CLAIMS`: ويُشغَّل **المقدِّرُ نفسُه** على الدعويين:
فرقُ ت٢ وكسبُ ش٥ كلاهما يُعاد بمعاودةٍ مجمَّعةٍ على العقد، ويُطبَع مجالُه
ومعه **عددُ معاوداته**. فمجالٌ بلا `B` لا تُعرَف أرضيّتُه، ومكيالان لدعويين
عيبٌ في الحكم لا في البيانات.

`THE_BOUND_SAYS_UNESTABLISHED_NOT_REFUTED`: والقسمةُ على جذر أثر التصميم
حدٌّ محافظٌ يكافئ `ρ = 1`؛ فمن بلغه ثبت، ومن لم يبلغه **لم يُثبَت** ولم
يُرَدّ. و`algebra.design_effect` هي التي تُصدِر المنزلة، فلا تُكتَب بيد.
والمتوسّطُ الداخلُ في الأثر متوسّطُ **ذوي الشاهد** لا الكلّ.

`NO_Z_IS_PRINTED_UNDIVIDED`: ولا يُطبَع `z` إلّا مقسومًا على جذر «الحوافِّ
للعقدة»، ويُطبَع الخامُ بجانبه ليُرى مقدارُ ما طُرِح. فالحافّةُ ليست مشاهدةً
مستقلّة، والعقدةُ الواحدةُ تدخل حوافَّ كثيرة.
"""

from __future__ import annotations

import argparse
import csv
import hashlib
import math
import random
from collections import Counter, defaultdict
from fractions import Fraction
from pathlib import Path

from algebra.design_effect import ClusterProfile

SEAL = "df8fe34a88bbf641e554f2ca923ac17f8c4c355691a109261bbe3a9b8c06ba07"

CLASSES: tuple[str, ...] = ("جار", "فعل", "معرفة", "ضمير", "سواه")
CATCH_ALL = "سواه"

SURFACE_KINDS: tuple[str, ...] = ("رسم-خام", "مخرج-phon")

EDGE = "\u0000"
"""حدُّ الآية: إطارٌ لا يعبرها، فلا يُصنَع جوارٌ من طرفين متباعدين."""


class ShahidError(ValueError):
    """رُدَّ تشغيلٌ لنقصٍ في إعلانٍ أو لمخالفة إغلاق."""


def column_digest(values: list[str]) -> str:
    """بصمةُ العمود وحدَه: فالعمودان في ملفٍّ واحدٍ لهما بصمتان."""

    joined = "\n".join(values).encode("utf-8")
    return hashlib.sha256(joined).hexdigest()


def read_alignment(
    path: Path, closure: int, digest: str, column: str = "surface"
) -> list[tuple[str, str]]:
    """اقرأ (loc، العمودَ المُسمّى) بعد فحص البصمة والإغلاق؛ ويُرَدّ ما خالف."""

    seen = hashlib.sha256(path.read_bytes()).hexdigest()
    if seen != digest:
        raise ShahidError(
            f"بصمةُ الملفّ {seen[:12]}… والمُعلَنةُ {digest[:12]}… — "
            "مدوّنتان لا مدوّنة، ولا يُبنى على المخالفة."
        )
    with path.open(encoding="utf-8", newline="") as handle:
        reader = csv.DictReader(handle, delimiter="\t")
        if reader.fieldnames is None or column not in reader.fieldnames:
            raise ShahidError(
                f"لا عمودَ باسم «{column}» في الملفّ؛ والعمودُ يُسمّى ولا يُخمَّن."
            )
        rows = [(row["loc"].strip(), (row[column] or "").strip()) for row in reader]
    if len(rows) != closure:
        raise ShahidError(
            f"{len(rows)} صفًّا في الملفّ و{closure} في الإغلاق المُعلَن؛ "
            "والفرقُ يُعلَن ولا يُطوى."
        )
    if any(not loc or not surface for loc, surface in rows):
        raise ShahidError("صفٌّ بلا موضعٍ أو بلا سطحٍ لا يدخل العدّ.")
    return rows


def read_classes(path: Path) -> dict[str, str]:
    """اقرأ إسنادَ الألفاظ إلى الأصناف؛ وصنفٌ خارج الخمسة يُرَدّ."""

    with path.open(encoding="utf-8", newline="") as handle:
        table = {
            row["surface"].strip(): row["class"].strip()
            for row in csv.DictReader(handle, delimiter="\t")
        }
    unknown = {one for one in table.values() if one not in CLASSES}
    if unknown:
        raise ShahidError(f"أصنافٌ خارج الخمسة المختومة: {'، '.join(sorted(unknown))}.")
    return table


def _verse_of(loc: str) -> str:
    return ":".join(loc.split(":")[:2])


def frames(rows: list[tuple[str, str]]) -> list[tuple[str, str, str]]:
    """(السابقُ، المركزُ، اللاحقُ) داخلَ الآية الواحدة؛ ولا إطارَ يعبر آيتين."""

    built: list[tuple[str, str, str]] = []
    for index, (loc, surface) in enumerate(rows):
        verse = _verse_of(loc)
        before = (
            rows[index - 1][1]
            if index and _verse_of(rows[index - 1][0]) == verse
            else EDGE
        )
        after = (
            rows[index + 1][1]
            if index + 1 < len(rows) and _verse_of(rows[index + 1][0]) == verse
            else EDGE
        )
        built.append((before, surface, after))
    return built


def neighbours(built: list[tuple[str, str, str]]) -> set[frozenset[str]]:
    """شاهدُ الإحلال: مركزان في إطارٍ محليٍّ واحدٍ بعينه."""

    centres: dict[tuple[str, str], set[str]] = defaultdict(set)
    for before, centre, after in built:
        if before == EDGE or after == EDGE:
            continue
        centres[(before, after)].add(centre)
    edges: set[frozenset[str]] = set()
    for group in centres.values():
        ordered = sorted(group)
        for first in range(len(ordered)):
            for second in range(first + 1, len(ordered)):
                edges.add(frozenset((ordered[first], ordered[second])))
    return edges


def signatures(
    built: list[tuple[str, str, str]], classes: dict[str, str]
) -> dict[str, Counter[tuple[str, str]]]:
    """توقيعُ كلّ لفظٍ على **الجدول المشترَك**: ٢٥ خانةً لا عشرةُ هوامش."""

    table: dict[str, Counter[tuple[str, str]]] = defaultdict(Counter)
    for before, centre, after in built:
        cell = (
            classes.get(before, CATCH_ALL),
            classes.get(after, CATCH_ALL),
        )
        table[centre][cell] += 1
    return table


def _cosine(first: Counter[tuple[str, str]], second: Counter[tuple[str, str]]) -> float:
    shared = set(first) & set(second)
    if not shared:
        return 0.0
    dot = sum(first[cell] * second[cell] for cell in shared)
    left = math.sqrt(sum(value * value for value in first.values()))
    right = math.sqrt(sum(value * value for value in second.values()))
    return dot / (left * right) if left and right else 0.0


def transfer(
    edges: set[frozenset[str]],
    held_out: dict[str, Counter[tuple[str, str]]],
    seed: int,
    draws: int,
) -> tuple[float, float, int]:
    """(تشابهُ الجيران، تشابهُ أزواجٍ عشوائيّة، عددُ الأزواج المقيسة)."""

    pairs = [
        tuple(sorted(edge)) for edge in edges if all(one in held_out for one in edge)
    ]
    if not pairs:
        raise ShahidError("لا زوجَ جيرةٍ نجا إلى النصف المحجوب؛ فلا انتقالَ يُقاس.")
    observed = sum(_cosine(held_out[one], held_out[two]) for one, two in pairs)
    observed /= len(pairs)

    names = sorted(held_out)
    rng = random.Random(seed)
    null = 0.0
    for _ in range(draws):
        one, two = rng.sample(names, 2)
        null += _cosine(held_out[one], held_out[two])
    return observed, null / draws, len(pairs)


def paired_differences(
    edges: set[frozenset[str]],
    held_out: dict[str, Counter[tuple[str, str]]],
    seed: int,
    draws: int,
) -> dict[str, float]:
    """فرقُ كلّ عقدة: تشابهُ جيرانها ناقصًا تشابهَ عشوائيّيها.

    والمقترنُ يُسقِط قاعدةَ الربع الموجب دفعةً واحدة: كلُّ عقدةٍ تُقارَن
    بنفسها لا بمدًى مطلق. ووحدةُ الاستقلال ههنا **العقدة** لا الحافّة.
    """

    linked: dict[str, set[str]] = defaultdict(set)
    for edge in edges:
        one, two = sorted(edge)
        if one in held_out and two in held_out:
            linked[one].add(two)
            linked[two].add(one)
    names = sorted(held_out)
    rng = random.Random(seed)
    differences: dict[str, float] = {}
    for node, others in linked.items():
        near = sum(_cosine(held_out[node], held_out[one]) for one in others)
        near /= len(others)
        far = 0.0
        for _ in range(draws):
            picked = rng.choice(names)
            far += _cosine(held_out[node], held_out[picked])
        differences[node] = near - far / draws
    return differences


def clustered_interval(
    differences: dict[str, float], seed: int, replicates: int
) -> tuple[float, float, float]:
    """(المتوسّطُ، الحدُّ الأدنى، الأعلى) بمعاودةٍ مجمَّعةٍ **على العقد**."""

    values = list(differences.values())
    if not values:
        raise ShahidError("لا عقدةَ لها جارٌ في النصف المحجوب؛ فلا فرقَ يُقاس.")
    mean = sum(values) / len(values)
    if replicates < 1:
        return mean, mean, mean
    rng = random.Random(seed)
    drawn = []
    for _ in range(replicates):
        sample = [values[rng.randrange(len(values))] for _ in values]
        drawn.append(sum(sample) / len(sample))
    drawn.sort()
    low = drawn[int(0.025 * (len(drawn) - 1))]
    high = drawn[int(0.975 * (len(drawn) - 1))]
    return mean, low, high


def degree_profile(
    edges: set[frozenset[str]], nodes: set[str]
) -> tuple[float, float, float, int]:
    """(الوسيطُ، المتوسّطُ، نصيبُ ذوي الحافّة، الأقصى) — والصفرُ يُعَدّ عقدةً."""

    degrees: Counter[str] = Counter()
    for edge in edges:
        for one in edge:
            degrees[one] += 1
    ordered = sorted(degrees.get(one, 0) for one in nodes)
    if not ordered:
        return 0.0, 0.0, 0.0, 0
    half = len(ordered) // 2
    middle = (
        float(ordered[half])
        if len(ordered) % 2
        else (ordered[half - 1] + ordered[half]) / 2
    )
    mean = sum(ordered) / len(ordered)
    witnessed = sum(1 for one in ordered if one) / len(ordered)
    return middle, mean, witnessed, ordered[-1]


def group_entropy(edges: set[frozenset[str]]) -> float:
    """إنتروبيا أحجام الفرق بالبتّ: فرقةٌ واحدةٌ تبتلع الكلَّ تعطي صفرًا."""

    sizes = _group_sizes(edges)
    total = sum(sizes)
    if total <= 0:
        return 0.0
    entropy = 0.0
    for size in sizes:
        share = size / total
        if share > 0:
            entropy -= share * math.log2(share)
    return entropy


def top_frame_share(built: list[tuple[str, str, str]]) -> Fraction:
    """نصيبُ أكثر الإطارات تكرارًا من الإطارات كلِّها: حارسُ تنكُّر الصيغة."""

    frames_seen: Counter[tuple[str, str]] = Counter()
    for before, _, after in built:
        if before != EDGE and after != EDGE:
            frames_seen[(before, after)] += 1
    total = sum(frames_seen.values())
    if not total:
        return Fraction(0)
    return Fraction(frames_seen.most_common(1)[0][1], total)


def catch_all_share(
    built: list[tuple[str, str, str]], classes: dict[str, str]
) -> Fraction:
    """نصيبُ «سواه» من مواضع السابق واللاحق مجتمعةً."""

    total = 0
    caught = 0
    for before, _, after in built:
        for side in (before, after):
            if side == EDGE:
                continue
            total += 1
            if classes.get(side, CATCH_ALL) == CATCH_ALL:
                caught += 1
    if not total:
        raise ShahidError("لا موضعَ سياقٍ يُعَدّ؛ فالنصيبُ بلا مقام.")
    return Fraction(caught, total)


def _predict(
    built: list[tuple[str, str, str]],
    learned: dict[str, Counter[tuple[str, str]]],
    classes: dict[str, str],
    *,
    joint: bool,
) -> Fraction:
    """نصيبُ الإصابة في التنبّؤ بصنف اللاحق: بالجدول المشترَك أو بالهامش."""

    hits = 0
    tried = 0
    for before, centre, after in built:
        if after == EDGE or centre not in learned:
            continue
        cells = learned[centre]
        if joint:
            before_class = classes.get(before, CATCH_ALL)
            cells = Counter(
                {
                    cell: count
                    for cell, count in cells.items()
                    if cell[0] == before_class
                }
            )
            if not cells:
                cells = learned[centre]
        tally: Counter[str] = Counter()
        for (_, next_class), count in cells.items():
            tally[next_class] += count
        if not tally:
            continue
        tried += 1
        if tally.most_common(1)[0][0] == classes.get(after, CATCH_ALL):
            hits += 1
    if not tried:
        raise ShahidError("لا موضعَ يُتنبَّأ به في النصف المحجوب.")
    return Fraction(hits, tried)


def _group_sizes(edges: set[frozenset[str]]) -> list[int]:
    """أحجامُ الفرق: المركّباتُ المتّصلةُ في مخطّط الجيرة."""

    parent: dict[str, str] = {}

    def find(node: str) -> str:
        parent.setdefault(node, node)
        while parent[node] != node:
            parent[node] = parent[parent[node]]
            node = parent[node]
        return node

    for edge in edges:
        one, two = sorted(edge)
        parent[find(one)] = find(two)
    groups: Counter[str] = Counter(find(node) for node in list(parent))
    return sorted(groups.values())


def gain_by_node(
    built: list[tuple[str, str, str]],
    learned: dict[str, Counter[tuple[str, str]]],
    classes: dict[str, str],
) -> dict[str, float]:
    """كسبُ ش٥ لكلّ عقدة: إصابةُ الجدول المشترَك ناقصًا إصابةَ الهامش.

    ووحدةُ الاستقلال العقدةُ ههنا كما هي في ت٢ — فالمقدِّرُ واحدٌ للدعويين.
    """

    per_node: dict[str, list[tuple[bool, bool]]] = defaultdict(list)
    for before, centre, after in built:
        if after == EDGE or centre not in learned:
            continue
        truth = classes.get(after, CATCH_ALL)
        joint = _guess(learned[centre], classes.get(before, CATCH_ALL))
        marginal = _guess(learned[centre], None)
        if joint is None or marginal is None:
            continue
        per_node[centre].append((joint == truth, marginal == truth))
    return {
        node: sum(1 for one, _ in seen if one) / len(seen)
        - sum(1 for _, two in seen if two) / len(seen)
        for node, seen in per_node.items()
        if seen
    }


def _guess(cells: Counter[tuple[str, str]], before_class: str | None) -> str | None:
    """أرجحُ صنفٍ لاحقٍ: بالجدول المشترَك إن سُمّي السابقُ، وبالهامش إن لم يُسمَّ."""

    chosen = cells
    if before_class is not None:
        narrowed = Counter(
            {cell: count for cell, count in cells.items() if cell[0] == before_class}
        )
        chosen = narrowed or cells
    tally: Counter[str] = Counter()
    for (_, next_class), count in chosen.items():
        tally[next_class] += count
    return tally.most_common(1)[0][0] if tally else None


def _smallest_group(edges: set[frozenset[str]]) -> int:
    """أصغرُ فرقةٍ (مركّبةٍ متّصلة) تدخل القراءة."""

    sizes = _group_sizes(edges)
    return sizes[0] if sizes else 0


