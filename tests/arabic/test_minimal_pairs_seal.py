"""**ختمٌ قبل النظر**: الأزواجُ الدنيا — أين يقع الفرقُ حين لا يفرّق إلّا حركةٌ واحدة؟

**لم يُعَدّ زوجٌ واحدٌ بعد.**

**العِلّة**: الوحدةُ من الـ١١٢ لا تفيد وحدها (ج٥ في ختم `a581ddb9…`: لا لفظَ من
حرفٍ واحدٍ عليه حركة). والإفادةُ تتحقّق في انتقالٍ مرخَّص. فإن كان صاحبُ
المستودع مصيبًا في أنّ الحركةَ داخلَ اللفظ تنتج أبوابًا (هيئةَ الفعل، والإعراب،
وأدواتِ الربط) فالموضعُ الذي تفرّق فيه حركةٌ واحدةٌ بين لفظين **ليس موزّعًا
على اللفظ بالسويّة**، بل يتركّز حيث تقع الأبواب:

- **الوحدةُ الأخيرة** — الإعراب؛
- **الوحدتان الأوليان** — حرفُ المضارعة وفاءُ الفعل، وهيئةُ المعلوم والمجهول،
  وحروفُ المعاني الملتصقة (لِ، لَ، بِ).

**والتعريفُ بالوحدات لا بالحروف**: اللفظان زوجٌ أدنى إذا تساوت وحداتُهما عددًا
وحروفًا في كلّ موضع، واختلفت الحالُ في موضعٍ واحدٍ لا غير. فالشدّةُ التي تزيد
وحدةً تُخرج الزوج، و«اً» على الألف تُخرجه — وهذا حدٌّ في الشرط يُعلَن قبل العدّ.

**والطولُ شرط**: في لفظٍ من ثلاث وحداتٍ كلُّ موضعٍ هو «الأخير» أو «الأوّلان»،
فلا يبقى للشرط ما يُسقطه. فيُقصَر على ما بلغ خمسَ وحداتٍ فأكثر، ويُقاس على ما
يُتوقَّع لو وقع الفرقُ في موضعٍ عشوائيٍّ من اللفظ.

**وما رُئي قبل الختم**: جردُ الوحدات وتوزيعُ الحركات داخلَ اللفظ وآخرَه على
المصحف كلّه، ونتائجُ ختم `c35956ef…` في العامل. **ولم يُرَ زوجٌ أدنى.**
"""

from __future__ import annotations

from fractions import Fraction

from algebra.signified import Direction, Oracle, Prediction, seal

ORACLE = Oracle(
    name="موضعُ الفرق في الأزواج الدنيا بالحركة",
    source="quran-simple-enhanced.txt — البصمة 37633090…",
    extraction=(
        "يُطرح الوسم <sel> فراغًا، واللفظُ ما فصلته الفراغات، وتُؤخذ صورُه المتميّزة "
        "بايتاتٍ؛ ووحداتُ الصورة ما يُخرجه run_cv_peel.peel بعد طرح الوحدات "
        "البنيويّة وذيل التنوين؛ والصورتان زوجٌ أدنى إذا تساوى عددُ وحداتهما "
        "وحرفُ كلّ موضعٍ فيهما واختلفت الحالُ في موضعٍ واحدٍ فقط؛ ويُعَدّ كلُّ "
        "زوجٍ مرّةً واحدة؛ ويُقصَر المقامُ على ما بلغت وحداتُه خمسًا فأكثر؛ "
        "والموضعُ «أخير» إن كان آخرَ الوحدات، و«أوّلان» إن كان الأوّلَ أو "
        "الثاني؛ والمتوقَّعُ لو كان الموضعُ عشوائيًّا متوسّطُ ثلاثةٍ على عدد "
        "الوحدات في الأزواج؛ وتوزيعُ الحركات داخلَ اللفظ وآخرَه ونتائجُ ختم "
        "c35956ef رُئيت قبل الختم، والأزواجُ الدنيا لم تُرَ"
    ),
)

PREDICTIONS = (
    Prediction(
        identifier="م١",
        statistic="نصيبُ الأزواج التي فرقُها في الأخير أو الأوّلين",
        threshold=Fraction(3, 4),
        direction=Direction.AT_LEAST,
        falsifies=(
            "القولَ بأنّ الحركةَ المفرِّقة تسكن مواضعَ الأبواب: إن لم يبلغ الأخيرُ "
            "والأوّلان ثلاثةَ أرباع الأزواج فالفرقُ يقع في جسد اللفظ كما يقع في طرفيه"
        ),
    ),
    Prediction(
        identifier="م٢",
        statistic="ذلك النصيبُ ناقصًا المتوقَّعَ لو كان الموضعُ عشوائيًّا",
        threshold=Fraction(1, 5),
        direction=Direction.AT_LEAST,
        falsifies=(
            "القولَ بأنّ التركّزَ ليس أثرَ الطول: إن لم يزد النصيبُ على العشوائيّ "
            "بخُمسٍ فالطرفان يأخذان ما يأخذانه لأنّهما طرفان لا لأنّهما بابان"
        ),
    ),
    Prediction(
        identifier="م٣",
        statistic="نصيبُ الأزواج التي فرقُها في الوحدة الأخيرة وحدها",
        threshold=Fraction(1, 2),
        direction=Direction.AT_LEAST,
        falsifies=(
            "القولَ بأنّ الإعرابَ أغلبُ ما تفرّق به حركةٌ واحدة: إن لم يبلغ الأخيرُ "
            "النصفَ فهيئةُ الكلمة تفرّق أكثرَ ممّا يفرّق موقعُها في الجملة"
        ),
    ),
)

DIGEST = "90ce48a5ce230ad77c5f2920acf0d52861ddc53cb59fc26ef6df80f6dd23c1b7"
"""يُثبَّت بعد أوّل اشتقاق، ولا يُمَسّ بعدَه."""


def test_the_seal_is_recomputed_from_the_written_conditions() -> None:
    """البصمةُ تُشتَقّ من الشروط لا تُنقَل."""

    assert seal(ORACLE, PREDICTIONS) == DIGEST


def test_three_conditions_about_where_one_vowel_divides() -> None:
    """ثلاثةٌ عن المادّة، ولكلٍّ نصُّ سقوط."""

    assert {one.identifier for one in PREDICTIONS} == {"م١", "م٢", "م٣"}
    for one in PREDICTIONS:
        assert one.falsifies.strip()


def test_what_was_seen_before_the_seal_is_declared() -> None:
    """الأزواجُ لم تُرَ — مُعلَنٌ في الاستخراج."""

    assert "والأزواجُ الدنيا لم تُرَ" in ORACLE.extraction
