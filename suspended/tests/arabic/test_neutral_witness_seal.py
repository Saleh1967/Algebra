"""**ختمٌ قبل الحكم**: شاهدُ الوسط في الأُطُر المناوِبة — و∅ معدودٌ فيه.

**وما رأيتُه قبل الختم يُعلَن ههنا ولا يُخفى**: بُنِيت الآلةُ أوّلًا
(`examples/rasm/run_neutral_witness.py`) وشُغِّلت على المدوّنة المجمَّدة
قبل كتابة هذا الختم، **فرأيتُ مخرَجَها**. فهذا الختمُ ليس تسجيلًا سابقًا
للنظر، وادّعاءُ ذلك كذب. وإنّما هو **تقييدُ الأحكام بشروطٍ مكتوبةٍ ذاتِ
حدودٍ واتّجاهات** تُشتَقّ منها بصمةٌ لا تُمَسُّ بعدها — كي يُعرَف تبديلُ
شرطٍ لاحقًا بتغيُّر البصمة. وأصلُ الحدود ليس من عندي: **كلُّها منقولةٌ من
دعاوى القياس السابق** (`المحايدُ هو الحذف` · `الألفُ ظلُّه الأعظم` ·
`صفرٌ شرطيّ` · `ضغطٌ ٠٫٣٠`)، فالحدُّ مكتوبٌ في دعوى الخصم لا مفصَّلٌ على
مقاس المقيس.

**والأوراكلُ هو المدوّنةُ وحدَها**: لا وسمَ صرفيًّا يدخل من خارج بايتاتها،
ولا جدولَ جذورٍ يُستشار. والفصلُ بين الاسم والفعل **بالمناوبة المرصودة**:
إطارٌ يُرى ممدودًا (`قَالَ`) ومقصورًا (`قُلْنَا`) معًا. والجامدُ لا يقصُر،
فـ`شَيْء` لا يدخل إطارَ `شَاءَ` — **بالإنشاء لا باستثناءٍ يُسمّى**.

**وأربعةُ حدودٍ قابلةٌ للسقوط، وثلاثةٌ منها ماتت بحقّ**: حدُّ الحذف لو
غلب ∅ لثبتت الدعوى الكبرى، وحدُّ الألف لو غلب غيرُه لسقط، وحدُّ الصفر
الشرطيِّ **عدّادُه لا يذكر العلّةَ في شرطه** فيجوز أن يمتلئ بغيرها، وحدُّ
الضغط يُقابَل بسقفٍ **مرصود** لا بسعةٍ مفترَضة.
"""

from __future__ import annotations

from fractions import Fraction

from algebra.signified import Direction, Oracle, Prediction, seal

ORACLE = Oracle(
    name="شاهدُ الوسط في الأُطُر المناوِبة",
    source="quran-simple-enhanced.txt — البصمة 37633090…",
    extraction=(
        "تُقرأ ألفاظُ المدوّنة بشكلها، ويُقام الإطارُ (صامتٌ أوّلُ · صامتٌ "
        "آخِرُ) على **المناوبة المرصودة** وحدَها: ما رُئي جذعًا ممدودًا "
        "(صامتٌ فحركةٌ فمدٌّ من جنسها فصامت) وجذعًا مقصورًا (صامتان بينهما "
        "حركةٌ قصيرةٌ ثمّ سكونٌ فضميرُ رفعٍ متّصل) معًا. ثمّ يُعَدّ شاهدُ "
        "الوسط من أربعةٍ مُعلَنةٍ قبل العدّ (ا و ي ∅)، ويُمسَح وسطُ الإطار "
        "على المدوّنة كلِّها **بعدّادٍ لا يذكر العلّةَ في شرطه** فيُعَدّ "
        "المتطفّلُ إن وقع ويُسمّى. ويُقابَل الشاهدُ بإنتروبيا الوسط "
        "**مرصودةً على الأُطُر كلِّها**، لا بـlog₂28"
    ),
)

