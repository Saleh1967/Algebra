def test_my_hand_text_differs_from_the_bytes_in_two_words() -> None:
    """البسملةُ ثلاثًا، وعشرون ترتيبَ شدّة، و«كُفُواً» و«إِلَهِ» — والباقي سواء."""

    window = _window()
    assert sum(1 for line in window if line.startswith("بِسْمِ")) == 3

    def canonical(one: str) -> str:
        return re.sub("([ًٌٍَُِ])ّ", "ّ\\1", one)

    order_only = 0
    real: list[tuple[str, str]] = []
    for hand, line in zip(HAND_WINDOW, window, strict=True):
        tokens = line.split()
        written = hand.split()
        if len(tokens) == len(written) + 4:
            tokens = tokens[4:]
        for mine, theirs in zip(written, tokens, strict=True):
            if mine == theirs:
                continue
            if canonical(mine) == theirs:
                order_only += 1
            else:
                real.append((mine, theirs))
    assert order_only == ORDER_ONLY
    assert real == REAL_DIFFERENCES


