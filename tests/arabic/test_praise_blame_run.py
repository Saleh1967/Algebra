def test_every_absent_shape_is_printed_by_name_and_none_is_swallowed() -> None:
    """ش٣ وش٤: ١٧ موجودةٌ و٣ غائبةٌ **بأسمائها** — والخلوُّ يُصنَّف."""

    deposited = int(_grab(r"— الصورُ المُودَعة: (\d+)"))
    found, absent = re.findall(
        r"— الصورُ الموجودة: (\d+) \| الغائبة: (\d+)", LOG.read_text("utf-8")
    )[0]
    assert (deposited, int(found), int(absent)) == (DEPOSITED, FOUND, ABSENT)
    assert int(found) + int(absent) == deposited
    named = re.findall(r"غائبةٌ باسمها: (\S+)", LOG.read_text("utf-8"))
    assert len(named) == ABSENT
    assert _one("ش٣").verdict(Fraction(0)) is Verdict.MET  # type: ignore[attr-defined]
    assert _one("ش٤").verdict(Fraction(int(found))) is Verdict.MET  # type: ignore[attr-defined]
    for shape in named:
        assert shape in RULE.read_text(encoding="utf-8")  # مقروءةٌ لا مكتوبة
    assert "شعرٌ لا آية" in RULE.read_text(encoding="utf-8")


def test_the_field_compresses_after_a_deposited_shape() -> None:
    """ش٥ صمد: ١٫٨٦٣٨ مقابلَ ٢٫٦١٠٦ — نزولٌ ٠٫٧٤٦٨ بتًّا."""

    field = float(_grab(r"حقلُ الحال العامّ: H = ([\d.]+)"))
    places, after = re.findall(
        r"الموضعُ التالي للصورة: مواضعُ (\d+) \| H = ([\d.]+)", LOG.read_text("utf-8")
    )[0]
    assert abs(field - FIELD) < 5e-5 and abs(float(after) - AFTER) < 5e-5
    assert int(places) == PLACES
    assert _one("ش٥").verdict(_exact(float(after))) is Verdict.MET  # type: ignore[attr-defined]
    assert abs((field - float(after)) - 0.7468) < 5e-5


def test_the_compression_goes_to_two_boxes_not_one() -> None:
    """ش٦ سقط: ٠٫٤٣٠٦ دون النصف، وثانيتُها ٠٫٣٤٧٢ — خانتان لا واحدة."""

    shares = [
        float(one)
        for one in re.findall(
            r"^    \S+ \d+ \| نصيبٌ ([\d.]+)$",
            LOG.read_text("utf-8")
            .split("الموضعُ التالي للصورة")[1]
            .split("الموضعُ الثالث")[0],
            re.M,
        )
    ]
    assert abs(shares[0] - TOP_AFTER) < 5e-5
    assert abs(shares[1] - SECOND_AFTER) < 5e-5
    assert _one("ش٦").verdict(_exact(shares[0])) is Verdict.FALSIFIED  # type: ignore[attr-defined]
    assert shares[0] + shares[1] > 0.77  # وهما معًا أكثرُ من ثلاثة أرباع
    assert abs(sum(shares) - 1.0) < 5e-4


def test_the_effect_is_one_position_and_the_top_box_changes() -> None:
    """ش٧ سقط: ٠٫٣٩١٣ والحدُّ ٠٫٤٠ — والخانةُ الغالبةُ تبدّلت."""

    below = LOG.read_text("utf-8").split("الموضعُ الثالث")[1]
    third_h = float(_grab(r"الموضعُ الثالث: مواضعُ \d+ \| H = ([\d.]+)"))
    rows = re.findall(r"^    (\S+) \d+ \| نصيبٌ ([\d.]+)$", below, re.M)
    assert abs(float(rows[0][1]) - TOP_THIRD) < 5e-5
    assert _one("ش٧").verdict(_exact(float(rows[0][1]))) is Verdict.FALSIFIED  # type: ignore[attr-defined]
    assert abs(third_h - THIRD_H) < 5e-5
    assert third_h > float(_grab(r"الموضعُ التالي للصورة: مواضعُ \d+ \| H = ([\d.]+)"))
    near = (
        LOG.read_text("utf-8")
        .split("الموضعُ التالي للصورة")[1]
        .split("الموضعُ الثالث")[0]
    )
    top_near = re.findall(r"^    (\S+) \d+ \| نصيبٌ [\d.]+$", near, re.M)[0]
    assert rows[0][0] != top_near  # الغالبةُ ههنا غيرُ الغالبة هناك


def test_a_strong_effect_is_not_a_wide_one() -> None:
    """ش١٢ سقط: ٠٫٠٠٠٥٧٢ — والصورُ ٧٢ موضعًا من ٧٨٬٢٤٥، فالأثرُ ضيّق."""

