"""**ختمٌ قبل النظر**: الفراكتاليّة — أيعمل العاملُ داخلَ اللفظ كما يعمل بين لفظين؟

**لم يُعَدّ لفظٌ واحدٌ بهذا الشرط بعد.**

**العِلّة**: دعوى التكرار الفراكتاليّ أنّ **العمليّةَ نفسَها** تتكرّر في كلّ مستوى.
وأوضحُ عمليّةٍ ثبتت بالعدّ: **عاملٌ على اليسار يقرّر حركةَ الطرف الأيمن**. ختمُ
`c35956ef…` قاسها **بين لفظين**: بعد حرف جرٍّ منفصل كسرةُ آخر اللفظ التالي
٠٫٨١٠٩. **فإن كانت البنيةُ فراكتاليّة** فالعمليّةُ نفسُها **داخلَ اللفظ الواحد**:
حرفُ جرٍّ ملتصقٌ في أوّله (بِالْ، لِلْ) يقرّر كسرةَ آخره بالقدر نفسه تقريبًا.
**وإن لم تكن**، فالالتصاقُ يغيّر العمل، ويبتعد الرقمان.

**والضابط**: الواو والفاء الملتصقتان مع «ال» (وَالْ، فَالْ) لا تعملان جرًّا، فكسرةُ
آخر ألفاظهما لا تُقرَّر بعامل في أوّلها.

- **ف١**: نصيبُ الكسرة في آخر اللفظ الذي أوّلُه «بِال» أو «لِل» لا يقلّ عن ٠٫٧٥.
- **ف٢ — التشابهُ عبر المستويين**: الفرقُ المطلق بين ذلك النصيب و٠٫٨١٠٩ (المقيس
  بين لفظين) لا يزيد على عُشر.
- **ف٣**: نصيبُ الكسرة بعد «بِال/لِل» يزيد على نصيبها بعد «وَال/فَال» بثلاثة
  أعشارٍ على الأقلّ.

**وما رُئي قبل الختم**: نتائجُ ختم `c35956ef…` (بين لفظين)، وتوزيعُ الحركات
داخلَ اللفظ وآخرَه على المصحف كلّه (مقامٌ آخر). **ولم يُعَدّ لفظٌ بحسب سابقته
الملتصقة.**
"""

from __future__ import annotations

from fractions import Fraction

from algebra.signified import Direction, Oracle, Prediction, seal

ORACLE = Oracle(
    name="العاملُ الملتصق والعاملُ المنفصل — عمليّةٌ واحدة في مستويين",
    source="quran-simple-enhanced.txt — البصمة 37633090…",
    extraction=(
        "يُطرح الوسم <sel> فراغًا، واللفظُ ما فصلته الفراغات بتكراره؛ ووحداتُه "
        "وحداتُ run_cv_peel.peel بعد طرح البنيويّ وذيل التنوين؛ والملتصقُ العامل "
        "لفظٌ أوّلُ وحدته باءٌ مكسورة تليها ألفٌ ثمّ لام، أو لامٌ مكسورة تليها "
        "لام، وله بعد هذه الوحدات وحدتان فأكثر؛ والضابطُ لفظٌ أوّلُ وحدته واوٌ "
        "أو فاءٌ مفتوحة تليها ألفٌ ثمّ لام، وله بعدها وحدتان فأكثر؛ والحركةُ "
        "الأخيرة حالُ آخر وحدة، فإن كانت فتحةً أو ضمّةً أو كسرةً فهي، وإلّا خرج "
        "اللفظ؛ والنصيبُ عددُ الكسرة على ما ظهرت حركتُه؛ و٠٫٨١٠٩ من ختم "
        "c35956ef رُئي قبل الختم، والعدُّ بالسابقة الملتصقة لم يُرَ"
    ),
)

PREDICTIONS = (
    Prediction(
        identifier="ف١",
        statistic="نصيبُ الكسرة في آخر اللفظ الذي أوّلُه «بِال» أو «لِل»",
        threshold=Fraction(3, 4),
        direction=Direction.AT_LEAST,
        falsifies=(
            "أنّ الجارَّ الملتصق يعمل: إن لم تغلب الكسرةُ في آخر لفظه فالعاملُ "
            "داخلَ اللفظ لا يقرّر طرفَه"
        ),
    ),
    Prediction(
        identifier="ف٢",
        statistic="الفرقُ المطلق بين ذلك النصيب و٨١٠٩ من عشرة آلاف",
        threshold=Fraction(1, 10),
        direction=Direction.AT_MOST,
        falsifies=(
            "التكرارَ الفراكتاليّ في هذه العمليّة: إن ابتعد النصيبان أكثرَ من عُشر "
            "فالعاملُ لا يعمل داخلَ اللفظ كما يعمل بين لفظين"
        ),
    ),
    Prediction(
        identifier="ف٣",
        statistic="نصيبُ الكسرة بعد «بِال/لِل» ناقصًا نصيبَها بعد «وَال/فَال»",
        threshold=Fraction(3, 10),
        direction=Direction.AT_LEAST,
        falsifies=(
            "أنّ الفرقَ من العامل لا من الالتصاق: إن لم تبتعد الكسرةُ عن ضابطها "
            "فالسابقةُ الملتصقة تفعل ما تفعله أيّةُ سابقة"
        ),
    ),
)

DIGEST = "58e14ba98c8806a0c8cd32affec4dab3df717cb1a05f7f3a886ddcf501be332f"
"""يُثبَّت بعد أوّل اشتقاق، ولا يُمَسّ بعدَه."""

BETWEEN_WORDS = Fraction(8109, 10000)
"""المقيسُ بين لفظين في ختم c35956ef — يدخل ف٢ حدًّا مكتوبًا."""


def test_the_seal_is_recomputed_from_the_written_conditions() -> None:
    """البصمةُ تُشتَقّ من الشروط لا تُنقَل."""

    assert seal(ORACLE, PREDICTIONS) == DIGEST


def test_three_conditions_across_two_scales() -> None:
    """ثلاثةٌ عن المادّة، ولكلٍّ نصُّ سقوط."""

    assert {one.identifier for one in PREDICTIONS} == {"ف١", "ف٢", "ف٣"}
    for one in PREDICTIONS:
        assert one.falsifies.strip()


def test_what_was_seen_before_the_seal_is_declared() -> None:
    """المقيسُ بين لفظين رُئي، وداخلَ اللفظ لم يُرَ."""

    assert "والعدُّ بالسابقة الملتصقة لم يُرَ" in ORACLE.extraction
