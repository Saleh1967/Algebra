"""**ختمٌ قبل النظر**: تصعيدٌ بتّةً بتّة **بلا تسريب** — والسياقُ ما مضى.

**لم يُشغَّل شيءٌ بعد.**

**من أين يُستأنَف**: من `494465d1…` — حدُّ اللفظ المُصحَّح — ومن حقل الحال
الذي قِيس فيه: ثمانُ خاناتٍ، `H = ٢٫٦١٠٦`، و`I` مع الجار `٠٫٠٦٥٣`.

**وما يُمنَع ههنا منعًا**:

- **لا قائمةَ مُودَعةٌ ولا صورةٌ منقولةٌ عن نصٍّ خارجيّ.** كلُّ سؤالٍ في
  السلّم **دالّةٌ في بايتات المجمَّد** لا غير.
- **ولا اسمَ بابٍ ولا اسمَ علامة.** ولا يُطبَع اسمُ يونيكود للمحرف —
  **يُطبَع المحرفُ شريحةً ونقطةَ ترميزٍ سداسيّة**، فلا يدخل السجلَّ اسمٌ
  وُضِع خارجَ المجمَّد.
- **ولا تسريبَ من الموضع إلى نفسه.** السياقُ **ما مضى وحدَه** والموضعُ من
  السطر: حالُ السابق، وحرفُ خاتمته، وحالُ ما قبله، وأأوّلُ السطر، وأآخرُه.
  **ولا يدخل السياقَ شيءٌ من بايتات الموضع المسؤولِ عنه** — وحرفُ خاتمته
  يحمل `١٫٠٣١٠` بتًّا عنه، فإدخالُه جوابٌ لا سؤال.

**وبتّةً بتّة على الحقيقة**: كلُّ درجةٍ تضيف **سؤالًا ثنائيًّا واحدًا** لا
أكثر، فتُضاعِف القسمةَ مرّةً واحدة. والسؤالُ يُختار **جشعًا** من جملة
الأسئلة المتاحة: «أحالُ السابق كذا؟» و«أحرفُ خاتمته كذا؟» و«أحالُ ما قبله
كذا؟» و«أأوّلُ السطر؟» و«أآخرُه؟». **والقيمُ تُجمَع من المجمَّد لا تُكتَب.**

**والجشعُ ههنا غيرُ مبرهَن** — كما في `620b63a2…`: أفضلُ سؤالٍ الآن ليس
أفضلَ سلّمٍ في النهاية. **فما يُبلَغ حدٌّ أدنى** لِما يبلغه بحثٌ أوسع، ولا
يُقال «لا يُبلَغ» بل «لم يُبلَغ بهذا الجشع».

**والاختيارُ بالمحجوز لا بالملحَق**: النزولُ داخلَ العيّنة **مضمونٌ
بالمبرهنة** عند كلّ تنقيح، فلا خبرَ فيه. **فالسلّمُ يقف حين لا يبقى سؤالٌ
يربح محجوزًا** — وذاك **حدُّ ما تحمله المادّة**.

**وinduction on**: مبرهنتان مُصانتان عند كلّ درجةٍ وكلّ حال: **التنقيحُ لا
يرفع الإنتروبيا الملحَقة** (وكلُّ درجةٍ تنقيحٌ لسابقتها بحكم البناء)،
و`log₂ التباديل ≤ N·H`. **وinduction FOR**: الحلقةُ تشهد عليهما **درجةً
درجةً وسطرًا سطرًا** وتُقابِل العدّاداتِ بالأسطر.

**وطرفا المبرهنتين بعد ألفِ لفظ** لا عند أوّل الحلقة — كما أُصلِح في
`494465d1…`.

**وماركوف**: كلُّ درجةٍ **تكتيلٌ** لفضاء السياق؛ والسلّمُ سلسلةُ تكتيلاتٍ
من الأخشن (كتلةٌ واحدة) إلى الأدقّ. **وتراجعُ الإنتروبيا الشرطيّة بالتنقيح
مبرهنةٌ لا تنبّؤ**، والتنبّؤُ في **أيّ سؤالٍ يُختار** و**متى يقف**.
"""

