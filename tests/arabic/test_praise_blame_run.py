def test_one_deposited_skeleton_carries_three_distinct_slices() -> None:
    """هيكلٌ لا يعيّن ضبطَه: ثلاثُ شرائحَ تحت واحدٍ — ولا أفصل بينها."""

    rows = re.findall(r"وقوعاتٌ\s+(\d+) \| شرائحُها: (.+)$", LOG.read_text("utf-8"), re.M)
    assert len(rows) == FOUND
    widest = max(rows, key=lambda one: len(one[1].split(" · ")))
    assert len(widest[1].split(" · ")) == 3
    assert int(widest[0]) == 9
    assert sum(int(one) for one in [two for two, _ in rows]) == PLACES
    assert int(_grab(r"وفي صدر السطر: (\d+) من \d+")) == AT_HEAD
    assert __doc__ is not None
    assert "الفصلُ يحتاج قراءةً، والقراءةُ ليست" in " ".join(__doc__.split())
    vague, share = re.findall(
        r"غامضةٌ منها: (\d+) \(([\d.]+) من الهياكل\)",
        VAGUE.read_text(encoding="utf-8"),
    )[0]
    mass, of_mass = re.findall(
        r"كتلتُها من الكلم: (\d+) \(([\d.]+) من الكلم\)",
        VAGUE.read_text(encoding="utf-8"),
    )[0]
    assert (int(vague), int(mass)) == (1_886, 34_902)
    assert abs(float(of_mass) - 0.4461) < 5e-5
    assert abs(float(share) - 0.1219) < 5e-5
    withdrawn = next(one for one in ESCALATION if one.identifier == "ك٧")
    assert withdrawn.threshold == 0  # والحدُّ فرقٌ لا عدد
    assert "٢٬٠٩٩" in withdrawn.statistic  # ٢٬٠٩٩ مسكنُها ذلك الختم
    assert int(vague) != 2_099  # والمقيسُ خالفه فسقط هناك لا ههنا


def test_the_header_row_flaw_changed_nothing_but_the_header() -> None:
    """صفُّ العنوان قُرئ صورةً، فأُصلِح — والسجلّان يُقابَلان سطرًا بسطر."""

    skip = ("الصورُ المُودَعة", "الصورُ الموجودة", "صفوفٌ لا تحمل", "الهيكل")

    def kept(where: Path) -> list[str]:
        return [
            one
            for one in where.read_text(encoding="utf-8").splitlines()
            if not any(two in one for two in skip)
        ]

    assert kept(LOG) == kept(FLAWED)
    assert int(_grab(r"صفوفٌ لا تحمل مصدرًا فأُسقِطت: (\d+)")) == 1
    before = re.findall(r"غائبةٌ باسمها: (\S+)", FLAWED.read_text(encoding="utf-8"))
    after = re.findall(r"غائبةٌ باسمها: (\S+)", LOG.read_text(encoding="utf-8"))
    assert len(before) == len(after) + 1
    (stray,) = set(before) - set(after)
    header = next(
        one
        for one in RULE.read_text(encoding="utf-8").splitlines()
        if one.startswith("| ") and "---" not in one
    )
    assert stray in header  # الشاردُ صفُّ العنوان نفسُه، مقروءًا لا مكتوبًا


