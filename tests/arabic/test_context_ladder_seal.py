def test_the_context_excludes_the_position_it_is_asked_about() -> None:
    """لا تسريبَ من الموضع إلى نفسه — وحرفُ خاتمته جوابٌ لا سؤال."""

    assert __doc__ is not None
    text = " ".join(__doc__.split())
    assert "السياقُ **ما مضى وحدَه**" in text
    assert "ولا يدخل السياقَ شيءٌ من بايتات الموضع المسؤولِ عنه" in text
    assert "ولا شيءَ من بايتات الموضع نفسِه" in " ".join(ORACLE.extraction.split())


def test_no_name_from_outside_the_corpus_may_enter() -> None:
    """لا اسمَ بابٍ ولا علامةٍ ولا يونيكود — المحرفُ شريحةٌ ونقطةُ ترميز."""

    assert __doc__ is not None
    text = " ".join(__doc__.split())
    assert "ولا اسمَ بابٍ ولا اسمَ علامة" in text
    assert "يُطبَع المحرفُ شريحةً ونقطةَ ترميزٍ سداسيّة" in text
    twelfth = next(one for one in PREDICTIONS if one.identifier == "ق١٢")
    assert twelfth.threshold == Fraction(0)
    assert "تسريبٌ" in twelfth.falsifies


def test_the_greedy_is_declared_unproven_and_its_bound_is_a_floor() -> None:
    """الجشعُ غيرُ مبرهَن — فما يُبلَغ حدٌّ أدنى، ولا يُقال «لا يُبلَغ»."""

    assert __doc__ is not None
    text = " ".join(__doc__.split())
    assert "**والجشعُ ههنا غيرُ مبرهَن**" in text
    assert "لم يُبلَغ بهذا الجشع" in text
    assert "بأكبرِ كسبٍ **محجوز**" in " ".join(ORACLE.extraction.split())


def test_five_conditions_are_machine_or_proven_and_seven_are_exposed() -> None:
    """خمسةٌ تردُّ الآلةَ أو مبرهَنة، وسبعٌ دعاوٍ لي معرَّضةٌ للسقوط."""

    machine = {"ق١", "ق٢", "ق٣", "ق٤", "ق١١"}
    mine = {one.identifier for one in PREDICTIONS} - machine
    assert len(mine) == 7
    for one in PREDICTIONS:
        if one.identifier in mine - {"ق٩", "ق١٢"}:
            assert "دعواي" in one.falsifies, one.identifier
