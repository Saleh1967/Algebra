DIGEST = "a57f54c124a4ab36dfd6e810991e1a578b7ddeeab0ee5ae37fbd089ba177b239"
"""يُثبَّت بعد أوّل اشتقاق، ولا يُمَسّ بعدَه."""


def test_the_seal_is_recomputed_from_the_written_conditions() -> None:
    """البصمةُ تُشتَقّ من الشروط لا تُنقَل."""

    assert seal(ORACLE, PREDICTIONS) == DIGEST


def test_one_zero_condition_and_one_machine_guard() -> None:
    """ص١ صفرٌ بلا هامش، وص٢ أنّ كلَّ بابٍ يعمل."""

    assert {one.identifier for one in PREDICTIONS} == {"ص١", "ص٢"}
    assert all(one.threshold == 0 for one in PREDICTIONS)


def test_the_table_is_signed_before_the_count() -> None:
    """الجدولُ موقَّعٌ في سطر توقيعه — والعدُّ لم يُرَ."""

    from pathlib import Path

    table = (
        Path(__file__).resolve().parents[2] / "deposits" / "jarr_exceptions_draft.tsv"
    )
    assert "# التوقيع: موقَّع" in table.read_text(encoding="utf-8")
    assert "والعدُّ على الجدول لم يُرَ" in ORACLE.extraction
