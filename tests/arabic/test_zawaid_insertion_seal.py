"""**ختمٌ قبل النظر**: «سألتمونيها» حرفًا حرفًا — أيُّ الحروف يُزاد على اللفظ؟

**لم يُعَدّ زوجٌ واحدٌ بعد.**

**العِلّة**: ختمُ `aaf77e3d…` جمع التسعةَ مجموعةً واحدة، فألغى وجهاها (أصليٌّ
وزائد) أثرَ أحدهما الآخر، وسقط شرطُه الثاني لأنّ المتوقَّعَ من نسب الحروف لم
يُحسَب قبل الختم. **فهذا الختمُ يسأل الحرفَ نفسَه، ويكتب خطَّ الأساس قبله.**

**الطريقة**: صورتان من ألفاظ المصحف (بحروفهما بلا حركات) تكون حروفُ الأولى
مضمَّنةً في الثانية بترتيبها، والثانيةُ أطولُ بحرفٍ إلى ثلاثة — «علم ⊂ عالم»،
«صبر ⊂ اصطبر». **فالحروفُ المُضافة عيّنةٌ من الزيادة في الاستعمال**، بلا جدول
جذور. وفيها مصادفاتٌ بين جذرين مختلفين («من ⊂ منع»)، فلا يُنتظَر الصفاء.

**دعوى الجدول الموقَّع** (الاشتقاقيّ): التسعةُ تكون أصلًا وزائدة، وغيرُها «أصليٌّ
لا يُزاد إلا تكريرًا»؛ **إلا الطاء والدال** فتُبدَلان من تاء الافتعال
(«اصطبر»، «ازدجر»). والملتصقاتُ ب ف ك تُزاد على **طرف** اللفظ لا في وسطه.

**خطُّ الأساس، مكتوبًا قبل العدّ** (من نسب المجموعات في ختم `aaf77e3d…`، وقد
رُئيت): لو كان الحرفُ المُضاف حرفًا عشوائيًّا من حروف المصحف لكان من التسعة أو
من ب ف ك في **٠٫٨١٢٥** من المرّات، ومن الستّة عشر الباقية في **٠٫١٨٧٥**.

- **ز١**: نصيبُ الحروف المُضافة التي هي من التسعة أو من ب ف ك أو تكريرٌ لحرفٍ
  يجاورها لا يقلّ عن ٠٫٩٣ — أي أنّ الستّةَ عشر لا تُضاف إلا في ٧٪ على الأكثر
  مكانَ ١٨٫٧٥٪.
- **ز٢**: من ب ف ك المُضافة، نصيبُ ما وقع على الطرف لا يقلّ عن ٠٫٩.
- **ز٣ — الفصلُ حرفًا حرفًا**: لكلّ حرفٍ معدّلُ زيادته = نصيبُه في المُضاف على
  نصيبه في حروف المصحف. **أعلى معدّلٍ في الستّة عشر عدا الطاء والدال أقلُّ من
  أدنى معدّلٍ في التسعة.** فلو كان في الستّة عشر حرفٌ يعمل عملَ الزوائد لظهر.
"""

from __future__ import annotations

from fractions import Fraction

from algebra.signified import Direction, Oracle, Prediction, seal

ORACLE = Oracle(
    name="الحروفُ المُضافة بين صورتين من ألفاظ المصحف — حرفًا حرفًا",
    source=(
        "quran-simple-enhanced.txt — البصمة 37633090…؛ والدعوى من "
        "deposits/unit_roles_draft.tsv الموقَّع"
    ),
    extraction=(
        "يُطرح الوسم <sel> فراغًا، واللفظُ ما فصلته الفراغات؛ وحروفُه وحداتُ "
        "run_cv_peel.peel بعد طرح البنيويّ وذيل التنوين والشطر الأوّل من الشدّة، "
        "والصورةُ سلسلةُ حروفه، وتُؤخذ الصورُ المتميّزة؛ والزوجُ صورتان ق وط، "
        "طولُ ق ثلاثةٌ فأكثر، وط أطولُ منها بحرفٍ إلى ثلاثة، وق تخرج من ط بحذف "
        "حروفٍ منها؛ وتُؤخذ من مواضع الحذف أصغرُها ترتيبًا، فيُعَدّ الزوجُ مرّةً؛ "
        "والمُضافُ حروفُ ط في تلك المواضع؛ والتكريرُ مُضافٌ يساوي حرفًا يجاوره في "
        "ط؛ والتسعة: ا س ل ت م و ن ي ه، والملتصقات: ب ف ك؛ والطرفُ الموضعان "
        "الأوّلان من ط أو الثلاثة الأخيرة؛ ومعدّلُ الحرف نصيبُه في المُضاف غيرِ "
        "التكرير على نصيبه في حروف ألفاظ المصحف بتكرارها؛ ونسبُ المجموعات في "
        "ختم aaf77e3d رُئيت قبل الختم، والأزواجُ لم تُرَ"
    ),
)

PREDICTIONS = (
    Prediction(
        identifier="ز١",
        statistic="نصيبُ المُضاف من التسعة أو من ب ف ك أو تكريرًا",
        threshold=Fraction(93, 100),
        direction=Direction.AT_LEAST,
        falsifies=(
            "دعوى الجدول الموقَّع أنّ غيرَ التسعة لا يُزاد إلا تكريرًا: إن أُضيفت "
            "الستّةُ عشر في أكثر من سبعةٍ من مئة فالزيادةُ لا تنحصر في «سألتمونيها»"
        ),
    ),
    Prediction(
        identifier="ز٢",
        statistic="نصيبُ ب ف ك المُضافة على طرف اللفظ",
        threshold=Fraction(9, 10),
        direction=Direction.AT_LEAST,
        falsifies=(
            "أنّ ب ف ك ملتصقاتٌ لا زوائد: إن أُضيفت في وسط اللفظ عُشرًا فأكثر "
            "فهي تدخل الوزنَ كما تدخله التسعة"
        ),
    ),
    Prediction(
        identifier="ز٣",
        statistic="أدنى معدّلٍ في التسعة ناقصًا أعلى معدّلٍ في الستّة عشر عدا ط د",
        threshold=Fraction(0),
        direction=Direction.AT_LEAST,
        falsifies=(
            "حصرَ الزيادة في «سألتمونيها» حرفًا حرفًا: إن زاد معدّلُ حرفٍ من "
            "خارجها على أدنى معدّلٍ فيها فذلك الحرفُ يعمل عملَ الزوائد"
        ),
    ),
)

DIGEST = "113fc28040f6e44e2c110e2d52fdaa8f4e8ca4633ba9bf1fa3ebf9f84a3baa0a"
"""يُثبَّت بعد أوّل اشتقاق، ولا يُمَسّ بعدَه."""


def test_the_seal_is_recomputed_from_the_written_conditions() -> None:
    """البصمةُ تُشتَقّ من الشروط لا تُنقَل."""

    assert seal(ORACLE, PREDICTIONS) == DIGEST


def test_three_conditions_letter_by_letter() -> None:
    """ثلاثةٌ عن المادّة، ولكلٍّ نصُّ سقوط."""

    assert {one.identifier for one in PREDICTIONS} == {"ز١", "ز٢", "ز٣"}
    for one in PREDICTIONS:
        assert one.falsifies.strip()


def test_the_baseline_is_written_before_the_count() -> None:
    """خطُّ الأساس مكتوبٌ في الشرح قبل العدّ، والأزواجُ لم تُرَ."""

    assert "والأزواجُ لم تُرَ" in ORACLE.extraction
