"""**ختمٌ قبل النظر**: المستوى الثالث — أيبقى ثابتُ الجرّ حين يبعد المعمول لفظًا؟

**لم تُعَدّ سلسلةٌ واحدةٌ من ثلاثة ألفاظ بعد.**

**العِلّة**: في المستويين الأوّلين ظهر للجرّ **ثابتٌ واحد** (حسابًا بعد تشغيل
`58e14ba9…`، وصفًا لا حكمًا): الحركةُ الأخيرة في الألفاظ كلّها كسرةٌ بنسبة
٠٫٢٦٣٢، والكسرةُ بعد الجارّ المنفصل ٠٫٨١٠٩ (PMI = ١٫٦٢٤ بتّ)، وبعد الملتصق
٠٫٨٢٥٦ (PMI = ١٫٦٤٩ بتّ)، ومتوسّطُهما **١٫٦٣٦٥ بتّ**. **والفراكتاليّةُ تتنبّأ**
بأنّ العملية نفسها في مستوًى ثالث — العاملُ يبلغ لفظًا لا يجاوره — تعطي الثابتَ
نفسه.

**والمستوى الثالث**: جارٌّ منفصل، ثمّ لفظٌ آخرُه كسرة (مجرورُه)، ثمّ لفظٌ يبدأ
بـ«ال» أو «وَال» — تابعٌ غالبًا («فِي السَّمَاوَاتِ وَالْأَرْضِ»)، وقد يكون
ابتداءَ جملة («إِلَى اللَّهِ الْمَصِيرُ»). فالشرطُ لا يُضمَن سلفًا.

- **ث١**: بُعدُ PMI الكسرة في آخر اللفظ الثالث عن ١٫٦٣٦٥ لا يزيد على ٠٫١٥ بتّ.
- **ث٢**: كثافةُ الربح موجبة: PMI لا يقلّ عن log₂e ≈ ١٫٤٤٢٧ — فالقاعدةُ الجشعة
  ترخّص الاقترانَ في المستوى الثالث كما رخّصته في الأوّلين.
- **ث٣ — الضابط**: كسرةُ اللفظ الثالث بعد مجرورٍ آخرُه كسرة تزيد بثلاثة أعشارٍ
  على الأقلّ على كسرته بعد لفظٍ آخرُه ضمّة (أيًّا كان ما قبله).

**وما رُئي قبل الختم**: نتائجُ ختمَي `c35956ef…` و`58e14ba9…`، وتوزيعُ الحركة
الأخيرة في الألفاظ كلّها، وPMI في المستويين. **ولم تُعَدّ سلسلةٌ من ثلاثة ألفاظ.**
"""

from __future__ import annotations

from fractions import Fraction

from algebra.signified import Direction, Oracle, Prediction, seal

ORACLE = Oracle(
    name="ثابتُ الجرّ في المستوى الثالث — العاملُ يبلغ لفظًا لا يجاوره",
    source="quran-simple-enhanced.txt — البصمة 37633090…",
    extraction=(
        "يُطرح الوسم <sel> فراغًا، والألفاظُ ما فصلته الفراغات في سطرها؛ والجارُّ "
        "المنفصل والحركةُ الأخيرة كما عرّفهما run_governed_vowel في ختم c35956ef؛ "
        "والسلسلةُ ثلاثةُ ألفاظٍ متتالية في سطر: أوّلُها جارٌّ منفصل، وثانيها "
        "حركتُه الأخيرة كسرة، وثالثُها يبدأ هيكلُه بـ«ال» أو بواوٍ مفتوحة يليها "
        "«ال»؛ والضابطُ لفظان متتاليان في سطر: أوّلُهما حركتُه الأخيرة ضمّة، "
        "وثانيهما يبدأ كذلك؛ والنصيبُ عددُ الكسرة في آخر اللفظ الأخير على ما "
        "ظهرت حركتُه؛ وPMI لوغاريتمٌ ثنائيّ للنصيب على ٢٦٣٢ من عشرة آلاف، "
        "نصيبِ الكسرة في آخر الألفاظ كلّها؛ وهذه النسبةُ وPMI المستويين الأوّلين "
        "رُئيت قبل الختم، والسلاسلُ الثلاثيّةُ لم تُرَ"
    ),
)

PREDICTIONS = (
    Prediction(
        identifier="ث١",
        statistic="البعدُ المطلق بين PMI الكسرة في المستوى الثالث و١٫٦٣٦٥ بتّ",
        threshold=Fraction(15, 100),
        direction=Direction.AT_MOST,
        falsifies=(
            "التكرارَ الفراكتاليّ للجرّ في ثلاثة مستويات: إن ابتعد PMI أكثرَ من "
            "٠٫١٥ بتّ فالثابتُ لا يحمله العاملُ حين يبعد معمولُه"
        ),
    ),
    Prediction(
        identifier="ث٢",
        statistic="PMI الكسرة في المستوى الثالث ناقصًا log₂e",
        threshold=Fraction(0),
        direction=Direction.AT_LEAST,
        falsifies=(
            "أنّ القاعدةَ الجشعة ترخّص الاقترانَ في المستوى الثالث: إن سلبت "
            "كثافةُ الربح فالاقترانُ عن بُعدٍ أضعفُ من أن يُدمَج"
        ),
    ),
    Prediction(
        identifier="ث٣",
        statistic="نصيبُ الكسرة في السلسلة ناقصًا نصيبَها في الضابط",
        threshold=Fraction(3, 10),
        direction=Direction.AT_LEAST,
        falsifies=(
            "أنّ الكسرةَ في اللفظ الثالث من السلسلة لا من «ال»: إن لم تبتعد عن "
            "ضابطها فالبادئةُ وحدها تفسّر ما يُرى"
        ),
    ),
)

DIGEST = "6be35fd836ecd5e87033e0773cabb66209d2674167efdbf8baf9a1e055bd5e0d"
"""يُثبَّت بعد أوّل اشتقاق، ولا يُمَسّ بعدَه."""

BASE_KASRA = Fraction(2632, 10000)
"""نصيبُ الكسرة في آخر الألفاظ كلّها — رُئي قبل الختم."""

CONSTANT = Fraction(16365, 10000)
"""متوسّطُ PMI المستويين الأوّلين بالبتّ — رُئي قبل الختم."""


def test_the_seal_is_recomputed_from_the_written_conditions() -> None:
    """البصمةُ تُشتَقّ من الشروط لا تُنقَل."""

    assert seal(ORACLE, PREDICTIONS) == DIGEST


def test_three_conditions_at_the_third_scale() -> None:
    """ثلاثةٌ عن المادّة، ولكلٍّ نصُّ سقوط."""

    assert {one.identifier for one in PREDICTIONS} == {"ث١", "ث٢", "ث٣"}
    for one in PREDICTIONS:
        assert one.falsifies.strip()


def test_what_was_seen_before_the_seal_is_declared() -> None:
    """السلاسلُ الثلاثيّة لم تُرَ — مُعلَنٌ في الاستخراج."""

    assert "والسلاسلُ الثلاثيّةُ لم تُرَ" in ORACLE.extraction
