def eastern(one: object) -> str:
    return str(one).translate(EASTERN)


def articles() -> list[tuple[int, str, Article]]:
    """كلُّ مادّةٍ برقمها وبابها — والترقيمُ يُشتَقّ ولا يُكتَب."""

    out: list[tuple[int, str, Article]] = []
    number = 0
    for chapter, rows in CHAPTERS:
        for row in rows:
            number += 1
            out.append((number, chapter, row))
    return out


def render() -> str:
    every = articles()
    unguarded = [one for one in every if one[2][3]]
    out: list[str] = []
    add = out.append
    add("# دستورُ القياس — ما يُلزِم الآلةَ، وأين يُنفَّذ")
    add("")
    add("**هذا الملفُّ مُشتَقٌّ من الشجرة** ويُعاد توليدُه. **ولا مادّةَ فيه**")
    add("**بلا موضعٍ يُنفِّذها**؛ ومن لم يكن لها مُنفِّذٌ آليٌّ **مكتوبٌ**")
    add("**عندها ذلك بنصّه**، ولا تُترَك للنيّة.")
    add("")
    add(f"**الموادّ**: {eastern(len(every))} في {eastern(len(CHAPTERS))} أبواب،")
    add(f"منها **{eastern(len(unguarded))}** بلا مانعٍ آليٍّ وهي مُسمّاة.")
    add("")
    add("**وكلُّ مادّةٍ وُلِدت من عطلٍ وقع** — لا من رأيٍ سابق. ورقمُ العطل")
    add("مذكورٌ حيث كان، ويُقرَأ في [`سجل-الأعطال.md`](سجل-الأعطال.md).")
    add("")
    for chapter, rows in CHAPTERS:
        add(f"## بابُ {chapter}")
        add("")
        for number, _, row in every:
            if row not in rows:
                continue
            text, flaw, where, limit = row
            add(f"**المادّة {eastern(number)}** — {text}")
            born = f" · **وَلَدها العطل {eastern(flaw)}**" if flaw else ""
            add(f"  ← `{where}`{born}")
            if limit:
                add(f"  ⚠ **{NO_GUARD}**: {limit}.")
            add("")
    add("## ما لا يُنفِّذه الدستورُ آليًّا")
    add("")
    add("**ثلاثةُ حدودٍ تُقال ولا تُحرَس**، وتُذكَر كي لا تُظَنّ محروسة:")
    add("")
    for number, _, row in every:
        if row[3]:
            add(f"- **المادّة {eastern(number)}** — {row[3]}.")
    add("- **وكاتبُ ختمٍ قد يُغفِل ما في الشجرة** — وقد وقع (العطل ٢٣).")
    add("")
    add("## القاعدةُ التي تحكم الدستور")
    add("")
    add("**كلُّ مادّةٍ ههنا وُلِدت من خطأٍ وقع وسُجِّل.** ولم تُكتَب واحدةٌ")
    add("منها قبل أن تُدفَع ثمنُها. **فمن أراد أن يزيد مادّةً فليأتِ**")
    add("**بعطلها** — وإلّا فهي رأيٌ لا دستور.")
    add("")
    return "\n".join(out) + "\n"


def main() -> int:
    PAPER.write_text(render(), encoding="utf-8")
    print(f"كُتِب {PAPER.relative_to(REPOSITORY)} — {len(render().splitlines())} سطرًا")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
